"""Summarise the size probes of each cross target from their GNU ld maps.

For every target and probe (pure, core, ledger) it reports flash (text +
rodata + data) and static RAM (data + bss) split by origin: the libzxv
adapter, the kernel modules, the port layer, zxe, the C library, libgcc
(with the soft-float helpers counted separately), the string literals the
linker merged across objects (mostly libzxv's error texts, which the map
attributes to whichever object came first) and the probe itself.
Sizes are what --gc-sections kept, not what the archives contain.

usage: python3 tools/size_report.py BUILD_DIR TARGET...   (Markdown on stdout)
"""
import os
import re
import sys

SEC = re.compile(r"^ (\.[\w.$]+|COMMON)\s*(?:\n\s+)?0x([0-9a-f]+)\s+0x([0-9a-f]+)\s+(\S+)"
                 r"(?:\n\s+0x([0-9a-f]+) \(size before relaxing\))?", re.M)
SOFTFLOAT = re.compile(r"(add|sub|mul|div|cmp|fix|float|extend|trunc|unord)[sd]f|_arm_.*df|_arm_.*sf|"
                       r"(adddf3|subdf3|muldf3|divdf3|eqdf2|ledf2|gedf2|floatsidf|floatdidf|"
                       r"floatunsidf|fixdfsi|fixdfdi|ltdf2|gtdf2|nedf2)")
GROUPS = ["libzxv adapter", "kernel modules", "port (zxp)", "zxe", "C library", "libgcc",
          "libgcc soft-float", "merged strings", "probe/startup"]


def group(src):
    base = os.path.basename(src)
    m = re.match(r"(.*)\((.*)\)$", base)
    arch, member = (m.group(1), m.group(2)) if m else ("", base)
    if arch == "libzxv_embedded.a":
        return "libzxv adapter" if member.startswith("zxv_") else "kernel modules"
    if arch == "libzxp.a":
        return "port (zxp)"
    if arch == "libzxe.a":
        return "zxe"
    if arch == "libgcc.a":
        return "libgcc soft-float" if SOFTFLOAT.search(member) else "libgcc"
    if arch.startswith(("libc", "libg", "libnosys", "libm", "libcrt0", "libsemihost")):
        return "C library"
    return "probe/startup"


def parse(path):
    text = open(path, encoding="utf-8", errors="replace").read()
    start = text.find("Linker script and memory map")
    text = text[start:] if start >= 0 else text
    flash = {g: 0 for g in GROUPS}
    ram = {g: 0 for g in GROUPS}
    for name, addr, size, src, before in SEC.findall(text):
        n = int(size, 16)
        if before and ".str" in name and int(before, 16) < n:
            # The linker merged every object's string literals into this
            # input section (mostly libzxv's error texts): count them apart.
            flash["merged strings"] += n - int(before, 16)
            n = int(before, 16)
        if n == 0 or int(addr, 16) == 0 and not name.startswith((".bss", "COMMON")):
            continue
        if name.startswith((".debug", ".comment", ".ARM.attributes", ".riscv.attributes", ".stab")):
            continue
        g = group(src)
        if name.startswith((".bss", ".sbss", ".tbss", "COMMON")) or name == "COMMON":
            ram[g] += n
        elif name.startswith((".data", ".sdata", ".tdata")):
            ram[g] += n
            flash[g] += n
        elif name.startswith((".text", ".rodata", ".srodata", ".init", ".fini", ".ARM.ex", ".ARM.extab",
                              ".eh_frame", ".glue", ".vfp11", ".v4_bx", ".iplt", ".rel")):
            flash[g] += n
    return flash, ram


def main():
    out, targets = sys.argv[1], sys.argv[2:]
    print("# Size report (generated by `make size`)\n")
    print("Bytes after `--gc-sections`, `-Os`, ZXE_PROFILE=%s. Flash = text + rodata + data; "
          "static RAM = data + bss. Heap is separate (see README)." % os.environ.get("ZXE_PROFILE", "exact"))
    for t in targets:
        print("\n## %s\n" % t)
        print("| probe | " + " | ".join(GROUPS) + " | total |")
        print("|---|" + "---|" * (len(GROUPS) + 1))
        for p in ("pure", "core", "ledger", "pqc"):
            path = os.path.join(out, t, "probe_%s.map" % p)
            if not os.path.exists(path):
                continue
            flash, ram = parse(path)
            cells = ["%d / %d" % (flash[g], ram[g]) for g in GROUPS]
            print("| %s (flash / RAM) | %s | **%d / %d** |" % (p, " | ".join(cells), sum(flash.values()),
                                                              sum(ram.values())))
    return 0


if __name__ == "__main__":
    sys.exit(main())
