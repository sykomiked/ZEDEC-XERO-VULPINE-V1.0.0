"""Z-Fabric generator: libzxv's tables -> synthesizable Verilog-2005 and VHDL-2008.

usage: zfab_gen.py --tables tables/zxv_tables.json --out DIR

Reads the JSON that tools/zfab_dump.c writes from the real libzxv and emits

  DIR/hdl/verilog/zxv_fabric.v      one module per function, gates only
  DIR/hdl/vhdl/zxv_fabric.vhd       the same entities in VHDL-2008
  DIR/tb/verilog/tb_zxv_fabric.v    exhaustive self-checking testbench
  DIR/tb/vhdl/tb_zxv_fabric.vhd     the same in VHDL-2008
  DIR/tb/vectors/<module>.hex       expected output for every input

Every output bit is a sum of products over the input bits it depends on
(found from the table, then minimised with Quine-McCluskey and a
deterministic cover). Before anything is written, each equation is
evaluated on every input and compared with the table; a mismatch aborts.
Python 3 standard library only; integers only.
"""
import argparse
import json
import os
import sys

HEADER_V = ("// Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC\n"
            "// SPDX-License-Identifier: Apache-2.0\n")
HEADER_VHD = ("-- Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC\n"
              "-- SPDX-License-Identifier: Apache-2.0\n")
GENERATED = "GENERATED by sdk/silicon/z-fabric/gen/zfab_gen.py from tables/zxv_tables.json. DO NOT EDIT."

# (table key, module, inputs [(name, width)], outputs [(name, width)], text).
# Inputs are listed most significant first: the table index is the
# concatenation of the inputs in this order (a * width(b) + b).
MODULES = [
    ("lp_not", "zxv_lp_not", [("a", 2)], [("y", 2)],
     "Four-valued NOT on ZXV_LP_* codes (zxv_lp_not)."),
    ("lp_and", "zxv_lp_and", [("a", 2), ("b", 2)], [("y", 2)],
     "Four-valued AND on ZXV_LP_* codes (zxv_lp_and)."),
    ("lp_or", "zxv_lp_or", [("a", 2), ("b", 2)], [("y", 2)],
     "Four-valued OR on ZXV_LP_* codes (zxv_lp_or)."),
    ("hex_from_lp", "zxv_hex_from_lp", [("lp", 2)], [("base", 2)],
     "ZXV_LP_* code -> ZXV_HEX_BASE_* code (zxv_hex_from_lp)."),
    ("hex_to_lp", "zxv_hex_to_lp", [("base", 2)], [("lp", 2)],
     "ZXV_HEX_BASE_* code -> ZXV_LP_* code (zxv_hex_to_lp)."),
    ("hex_phase_next", "zxv_hex_phase_next", [("phase", 2)], [("next_phase", 2)],
     "The next phase on the Gray cycle (zxv_hex_phase_next)."),
    ("hex_action", "zxv_hex_action", [("tag", 6)], [("action", 3)],
     "The 64-entry action table: tag -> ZXV_HEX_ACT_* (zxv_hex_action)."),
    ("hex_not", "zxv_hex_not", [("a", 6)], [("y", 6)],
     "Hexagram NOT (zxv_hex_not)."),
    ("hex_and", "zxv_hex_and", [("a", 6), ("b", 6)], [("y", 6)],
     "Hexagram AND (zxv_hex_and)."),
    ("hex_or", "zxv_hex_or", [("a", 6), ("b", 6)], [("y", 6)],
     "Hexagram OR (zxv_hex_or)."),
]


class GenError(Exception):
    pass


# ---------------------------------------------------------------- tables

def load_tables(path):
    with open(path, encoding="utf-8") as f:
        t = json.load(f)
    if t.get("format") != "zxv-fabric-tables/1":
        raise GenError("%s: format is not zxv-fabric-tables/1" % path)
    for key, mod, ins, outs, _ in MODULES:
        n = 1 << sum(w for _, w in ins)
        top = 1 << sum(w for _, w in outs)
        v = t.get(key)
        if not isinstance(v, list) or len(v) != n:
            raise GenError("%s: %s must have %d entries" % (path, key, n))
        for i, x in enumerate(v):
            if not isinstance(x, int) or isinstance(x, bool) or not 0 <= x < top:
                raise GenError("%s: %s[%d] = %r is not 0..%d" % (path, key, i, x, top - 1))
    return t


# ---------------------------------------------------------------- logic

def support(table, nin, bit):
    """Input bit positions the output bit actually depends on (ascending)."""
    sup = []
    for k in range(nin):
        m = 1 << k
        if any(((table[i] >> bit) & 1) != ((table[i ^ m] >> bit) & 1) for i in range(len(table))):
            sup.append(k)
    return sup


def primes(ones, n):
    """Prime implicants of the minterm set `ones` over n variables, as
    (value, care) pairs: the term holds when (x & care) == value."""
    full = (1 << n) - 1
    cur = {(m, full) for m in ones}
    out = set()
    while cur:
        nxt = set()
        used = set()
        lst = sorted(cur)
        for i, (v1, c1) in enumerate(lst):
            for v2, c2 in lst[i + 1:]:
                if c1 != c2:
                    continue
                d = v1 ^ v2
                if d and d & (d - 1) == 0:
                    nxt.add((v1 & ~d, c1 & ~d))
                    used.add((v1, c1))
                    used.add((v2, c2))
        out |= cur - used
        cur = nxt
    return sorted(out)


def covers(term, m):
    v, c = term
    return (m & c) == v


def cover(ones, n):
    """A deterministic cover: essential primes, then greedily the prime that
    covers most remaining minterms (fewest literals, then lowest value)."""
    if not ones:
        return []
    ps = primes(ones, n)
    left = set(ones)
    chosen = []
    for m in sorted(ones):
        hit = [p for p in ps if covers(p, m)]
        if len(hit) == 1 and hit[0] not in chosen:
            chosen.append(hit[0])
    for p in chosen:
        left -= {m for m in left if covers(p, m)}
    while left:
        best = max(ps, key=lambda p: (sum(1 for m in left if covers(p, m)),
                                      -bin(p[1]).count("1"), -p[1], -p[0]))
        chosen.append(best)
        left -= {m for m in left if covers(best, m)}
    return sorted(chosen, key=lambda p: (-bin(p[1]).count("1"), p[1], p[0]))


def minimise(table, nin, bit):
    """Sum of products for one output bit: a list of terms, each a list of
    (input bit position, required value) literals. [] = constant 0,
    [[]] = constant 1."""
    sup = support(table, nin, bit)
    ns = len(sup)
    ones = set()
    for i in range(len(table)):
        if (table[i] >> bit) & 1:
            ones.add(sum(((i >> k) & 1) << j for j, k in enumerate(sup)))
    if not ones:
        return []
    if len(ones) == 1 << ns:
        return [[]]
    terms = []
    for v, c in cover(ones, ns):
        lits = [(sup[j], (v >> j) & 1) for j in reversed(range(ns)) if (c >> j) & 1]
        terms.append(lits)
    return terms


def evaluate(terms, x):
    return int(any(all(((x >> k) & 1) == want for k, want in lits) for lits in terms))


def build(tables):
    """Equations for every module, each checked against its table."""
    mods = []
    for key, name, ins, outs, text in MODULES:
        table = tables[key]
        nin = sum(w for _, w in ins)
        nout = sum(w for _, w in outs)
        eqs = [minimise(table, nin, b) for b in range(nout)]
        for i in range(len(table)):
            got = sum(evaluate(eqs[b], i) << b for b in range(nout))
            if got != table[i]:
                raise GenError("%s: equation gives %d for input %d, table says %d"
                               % (name, got, i, table[i]))
        mods.append({"key": key, "name": name, "ins": ins, "outs": outs, "text": text,
                     "nin": nin, "nout": nout, "eqs": eqs, "table": table})
    return mods


# ---------------------------------------------------------------- naming

def bit_names(ports):
    """Global bit position (LSB = 0 of the concatenation) -> (port, index)."""
    names = {}
    pos = sum(w for _, w in ports)
    for p, w in ports:
        pos -= w
        for j in range(w):
            names[pos + j] = (p, j)
    return names


def v_expr(terms, inb):
    if not terms:
        return "1'b0"
    if terms == [[]]:
        return "1'b1"
    out = []
    for lits in terms:
        ls = [("" if want else "~") + "%s[%d]" % inb[k] for k, want in lits]
        out.append(ls[0] if len(ls) == 1 else "(" + " & ".join(ls) + ")")
    return " | ".join(out)


def vhd_expr(terms, inb):
    if not terms:
        return "'0'"
    if terms == [[]]:
        return "'1'"
    out = []
    for lits in terms:
        ls = [("" if want else "not ") + "%s(%d)" % inb[k] for k, want in lits]
        out.append(ls[0] if len(ls) == 1 else "(" + " and ".join(ls) + ")")
    return " or ".join(out)


def outbit(outs, b):
    return bit_names(outs)[b]


def wrap(line, width=100, indent="    "):
    """Break a long `lhs = a | b | ...;` line after operators."""
    if len(line) <= width:
        return [line]
    for sep in (" | ", " or "):
        if sep in line:
            break
    else:
        return [line]
    parts = line.split(sep)
    lines, cur = [], parts[0]
    for p in parts[1:]:
        if len(cur) + len(sep) + len(p) > width:
            lines.append(cur + sep.rstrip())
            cur = indent + p
        else:
            cur += sep + p
    lines.append(cur)
    return lines


# ---------------------------------------------------------------- emitters

def emit_verilog(mods):
    o = [HEADER_V, "// %s\n" % GENERATED,
         "//\n// Z-Fabric: combinational reference logic for libzxv's four-valued logic\n"
         "// and 64-state hexagram tags. Verilog-2005, gates only (no tables, no\n"
         "// latches, no clocks). Not timing-closed for any FPGA or ASIC.\n"
         "// Bit layout of a tag: [5:4] base, [3:2] polarity, [1:0] phase.\n\n"
         "`timescale 1ns / 1ps\n`default_nettype none\n"]
    for m in mods:
        inb = bit_names(m["ins"])
        ports = ["    input  wire [%d:0] %s" % (w - 1, p) for p, w in m["ins"]]
        ports += ["    output wire [%d:0] %s" % (w - 1, p) for p, w in m["outs"]]
        o.append("\n// %s\nmodule %s (\n%s\n);\n" % (m["text"], m["name"], ",\n".join(ports)))
        for b in range(m["nout"]):
            p, j = outbit(m["outs"], b)
            o.extend(l + "\n" for l in wrap("    assign %s[%d] = %s;" % (p, j, v_expr(m["eqs"][b], inb)),
                                            indent="        "))
        o.append("endmodule\n")
    o.append("\n`default_nettype wire\n")
    return "".join(o)


def emit_vhdl(mods):
    o = [HEADER_VHD, "-- %s\n" % GENERATED,
         "--\n-- Z-Fabric: combinational reference logic for libzxv's four-valued logic\n"
         "-- and 64-state hexagram tags. VHDL-2008, gates only (no tables, no\n"
         "-- latches, no clocks). Not timing-closed for any FPGA or ASIC.\n"
         "-- Bit layout of a tag: (5 downto 4) base, (3 downto 2) polarity, (1 downto 0) phase.\n"]
    for m in mods:
        inb = bit_names(m["ins"])
        ports = ["    %s : in  std_logic_vector(%d downto 0)" % (p, w - 1) for p, w in m["ins"]]
        ports += ["    %s : out std_logic_vector(%d downto 0)" % (p, w - 1) for p, w in m["outs"]]
        o.append("\n-- %s\nlibrary ieee;\nuse ieee.std_logic_1164.all;\n\n"
                 "entity %s is\n  port (\n%s\n  );\nend entity %s;\n\n"
                 "architecture gates of %s is\nbegin\n"
                 % (m["text"], m["name"], ";\n".join(ports), m["name"], m["name"]))
        for b in range(m["nout"]):
            p, j = outbit(m["outs"], b)
            o.extend(l + "\n" for l in wrap("    %s(%d) <= %s;" % (p, j, vhd_expr(m["eqs"][b], inb)),
                                            indent="        "))
        o.append("end architecture gates;\n")
    return "".join(o)


def hexw(bits):
    return (bits + 3) // 4


def emit_vectors(m):
    d = hexw(m["nout"])
    return "".join("%0*x\n" % (d, v) for v in m["table"])


def emit_tb_verilog(mods):
    o = [HEADER_V, "// %s\n" % GENERATED,
         "//\n// Exhaustive self-checking testbench. Every input of every module is\n"
         "// driven and the output compared (!==, so X or Z fails) with\n"
         "// vectors/<module>.hex, the libzxv table. Run from the directory that\n"
         "// holds vectors/. Prints ALL PASS or FAIL; FAIL ends with $fatal.\n\n"
         "`timescale 1ns/1ps\n`default_nettype none\n\nmodule tb_zxv_fabric;\n"
         "    integer i;\n    integer errors;\n    integer checks;\n"]
    for m in mods:
        n, ni, no = m["name"], m["nin"], m["nout"]
        o.append("\n    reg  [%d:0] %s_in;\n    wire [%d:0] %s_out;\n    reg  [%d:0] %s_exp [0:%d];\n"
                 % (ni - 1, n, no - 1, n, hexw(no) * 4 - 1, n, (1 << ni) - 1))
        conns, pos = [], ni
        for p, w in m["ins"]:
            conns.append(".%s(%s_in[%d:%d])" % (p, n, pos - 1, pos - w))
            pos -= w
        pos = no
        for p, w in m["outs"]:
            conns.append(".%s(%s_out[%d:%d])" % (p, n, pos - 1, pos - w))
            pos -= w
        o.append("    %s u_%s (%s);\n" % (n, n, ", ".join(conns)))
    o.append("\n    initial begin\n        errors = 0;\n        checks = 0;\n")
    for m in mods:
        n, ni, no = m["name"], m["nin"], m["nout"]
        o.append('        $readmemh("vectors/%s.hex", %s_exp);\n' % (n, n))
        o.append("        for (i = 0; i < %d; i = i + 1) begin\n"
                 "            %s_in = i;\n            #1;\n            checks = checks + 1;\n"
                 "            if (%s_out !== %s_exp[i][%d:0]) begin\n"
                 "                errors = errors + 1;\n"
                 "                if (errors <= 20)\n"
                 '                    $display("FAIL %s input %%0d: got %%b, libzxv says %%b", i, %s_out, %s_exp[i][%d:0]);\n'
                 "            end\n        end\n"
                 '        $display("%s: %d vectors checked");\n'
                 % (1 << ni, n, n, n, no - 1, n, n, n, no - 1, n, 1 << ni))
    o.append("        if (errors == 0) begin\n"
             '            $display("ALL PASS: %0d vectors, %0d modules", checks, ' + str(len(mods)) + ");\n"
             "            $finish;\n        end else begin\n"
             '            $display("FAIL: %0d of %0d vectors differ from libzxv", errors, checks);\n'
             '            $fatal(1, "Z-Fabric Verilog testbench failed");\n'
             "        end\n    end\nendmodule\n\n`default_nettype wire\n")
    return "".join(o)


def emit_tb_vhdl(mods):
    o = [HEADER_VHD, "-- %s\n" % GENERATED,
         "--\n-- Exhaustive self-checking testbench (VHDL-2008). Every input of every\n"
         "-- module is driven and the output compared with vectors/<module>.hex, the\n"
         "-- libzxv table; a short or long vector file fails too. Run from the\n"
         "-- directory that holds vectors/. Ends with ALL PASS or a failure assertion.\n\n"
         "library ieee;\nuse ieee.std_logic_1164.all;\nuse ieee.numeric_std.all;\nuse std.textio.all;\n\n"
         "entity tb_zxv_fabric is\nend entity tb_zxv_fabric;\n\narchitecture sim of tb_zxv_fabric is\n"]
    for m in mods:
        n, ni, no = m["name"], m["nin"], m["nout"]
        o.append("    signal %s_in  : std_logic_vector(%d downto 0) := (others => '0');\n"
                 "    signal %s_out : std_logic_vector(%d downto 0);\n" % (n, ni - 1, n, no - 1))
    o.append("begin\n")
    for m in mods:
        n, ni, no = m["name"], m["nin"], m["nout"]
        conns, pos = [], ni
        for p, w in m["ins"]:
            conns.append("%s => %s_in(%d downto %d)" % (p, n, pos - 1, pos - w))
            pos -= w
        pos = no
        for p, w in m["outs"]:
            conns.append("%s => %s_out(%d downto %d)" % (p, n, pos - 1, pos - w))
            pos -= w
        o.append("    u_%s : entity work.%s port map (%s);\n" % (n, n, ", ".join(conns)))
    o.append("\n    check : process\n        file f : text;\n        variable l : line;\n"
             "        variable v : std_logic_vector(23 downto 0);\n        variable good : boolean;\n"
             "        variable status : file_open_status;\n"
             "        variable errors : natural := 0;\n        variable checks : natural := 0;\n"
             "    begin\n")
    for m in mods:
        n, ni, no = m["name"], m["nin"], m["nout"]
        d = hexw(no) * 4
        o.append('        file_open(status, f, "vectors/%s.hex", read_mode);\n'
                 '        assert status = open_ok report "cannot open vectors/%s.hex" severity failure;\n'
                 "        for i in 0 to %d loop\n"
                 '            assert not endfile(f) report "%s: vector file too short" severity failure;\n'
                 "            readline(f, l);\n"
                 "            hread(l, v(%d downto 0), good);\n"
                 '            assert good report "%s: bad hex at input " & integer\'image(i) severity failure;\n'
                 "            %s_in <= std_logic_vector(to_unsigned(i, %d));\n"
                 "            wait for 1 ns;\n"
                 "            checks := checks + 1;\n"
                 "            if %s_out /= v(%d downto 0) then\n"
                 "                errors := errors + 1;\n"
                 "                if errors <= 20 then\n"
                 '                    report "FAIL %s input " & integer\'image(i) & ": got " & to_string(%s_out)\n'
                 '                        & ", libzxv says " & to_string(v(%d downto 0)) severity error;\n'
                 "                end if;\n            end if;\n        end loop;\n"
                 '        assert endfile(f) report "%s: vector file too long" severity failure;\n'
                 "        file_close(f);\n"
                 '        report "%s: %d vectors checked" severity note;\n'
                 % (n, n, (1 << ni) - 1, n, d - 1, n, n, ni, n, no - 1, n, n, no - 1, n, n, 1 << ni))
    o.append("        if errors = 0 then\n"
             '            report "ALL PASS: " & integer\'image(checks) & " vectors, ' + str(len(mods))
             + ' modules" severity note;\n'
             "        else\n"
             '            report "FAIL: " & integer\'image(errors) & " of " & integer\'image(checks)\n'
             '                & " vectors differ from libzxv" severity failure;\n'
             "        end if;\n        wait;\n    end process check;\nend architecture sim;\n")
    return "".join(o)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--tables", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args(argv)
    try:
        mods = build(load_tables(a.tables))
    except (GenError, OSError, ValueError) as e:
        print("zfab_gen: %s" % e, file=sys.stderr)
        return 1
    write(os.path.join(a.out, "hdl/verilog/zxv_fabric.v"), emit_verilog(mods))
    write(os.path.join(a.out, "hdl/vhdl/zxv_fabric.vhd"), emit_vhdl(mods))
    write(os.path.join(a.out, "tb/verilog/tb_zxv_fabric.v"), emit_tb_verilog(mods))
    write(os.path.join(a.out, "tb/vhdl/tb_zxv_fabric.vhd"), emit_tb_vhdl(mods))
    for m in mods:
        write(os.path.join(a.out, "tb/vectors/%s.hex" % m["name"]), emit_vectors(m))
    terms = sum(len(e) for m in mods for e in m["eqs"])
    print("zfab_gen: %d modules, %d output bits, %d product terms, %d vectors; "
          "every equation checked against the table"
          % (len(mods), sum(m["nout"] for m in mods), terms, sum(len(m["table"]) for m in mods)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
