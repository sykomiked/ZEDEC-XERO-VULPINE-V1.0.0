using System;
using System.Runtime.InteropServices;
using System.Security.Cryptography;
using Zxv.Interop;

namespace Zxv;

/// <summary>What a <see cref="SecretKey"/> holds.</summary>
public enum SecretKeyKind
{
    /// <summary>Raw secret bytes imported by the caller.</summary>
    Raw = 0,

    /// <summary>An Ed25519 private key (the 32-byte RFC 8032 seed).</summary>
    Ed25519 = 1,

    /// <summary>An ML-DSA-87 secret key (4896 bytes).</summary>
    MlDsa87 = 2,

    /// <summary>An ML-KEM-1024 decapsulation key (3168 bytes).</summary>
    MlKem1024 = 3,

    /// <summary>An ML-KEM shared secret (32 bytes).</summary>
    SharedSecret = 4,
}

/// <summary>
/// Secret key material kept outside the garbage-collected heap, in memory
/// from <see cref="NativeMemory.AllocZeroed(nuint)"/>, and wiped with
/// <c>zxv_secure_zero</c> when disposed. The crypto calls read it in place:
/// keys generated by the SDK never exist as a managed array.
/// </summary>
/// <remarks>
/// <para>
/// A finalizer backstop (the critical finalizer of the internal
/// <see cref="SafeHandle"/>) wipes and frees the memory if the key is never
/// disposed, but call <see cref="Dispose"/> (or <c>using</c>) so the secret
/// lives no longer than needed.
/// </para>
/// <para>
/// What cannot be guaranteed: bytes you import with
/// <see cref="Import(ReadOnlySpan{byte}, SecretKeyKind)"/> already existed in
/// your memory (wipe them yourself, e.g. with
/// <see cref="CryptographicOperations.ZeroMemory(Span{byte})"/>; the GC may
/// have copied a managed array before that); the operating system may page
/// the memory to swap or include it in a core dump.
/// </para>
/// </remarks>
public sealed class SecretKey : IDisposable
{
    private readonly Buffer _buffer;

    private SecretKey(int length, SecretKeyKind kind)
    {
        _buffer = new Buffer(length);
        Kind = kind;
    }

    /// <summary>Gets what the key holds.</summary>
    public SecretKeyKind Kind { get; }

    /// <summary>Gets the length in bytes.</summary>
    public int Length => _buffer.Length;

    /// <summary>Gets a value indicating whether the key has been disposed (and wiped).</summary>
    public bool IsDisposed => _buffer.IsClosed;

    /// <summary>
    /// Copies caller-held secret bytes into off-heap memory. The source is not
    /// wiped by this call: wipe it yourself.
    /// </summary>
    /// <param name="secret">The secret bytes.</param>
    /// <param name="kind">What they are.</param>
    /// <returns>The key; dispose it when done.</returns>
    public static unsafe SecretKey Import(ReadOnlySpan<byte> secret, SecretKeyKind kind = SecretKeyKind.Raw)
    {
        if (secret.IsEmpty)
        {
            throw new ArgumentException("A secret key must not be empty.", nameof(secret));
        }

        var key = new SecretKey(secret.Length, kind);
        secret.CopyTo(new Span<byte>(key._buffer.DangerousGetHandle().ToPointer(), secret.Length));
        return key;
    }

    /// <summary>
    /// Copies the secret into a new managed array. This DEFEATS the wiping:
    /// the copy lives on the GC heap, which may move and duplicate it. Use it
    /// only to hand the key to a system that needs bytes, and wipe the array
    /// with <see cref="CryptographicOperations.ZeroMemory(Span{byte})"/> afterwards.
    /// </summary>
    /// <returns>A copy of the secret.</returns>
    public unsafe byte[] ExportBytesUnsafe()
    {
        var copy = new byte[Length];
        Use(p =>
        {
            unsafe
            {
                new ReadOnlySpan<byte>(p, Length).CopyTo(copy);
            }
        });
        return copy;
    }

    /// <summary>Compares two secrets in constant time.</summary>
    /// <param name="other">The other key.</param>
    /// <returns><see langword="true"/> if the bytes are equal.</returns>
    public unsafe bool FixedTimeEquals(SecretKey other)
    {
        ArgumentNullException.ThrowIfNull(other);
        bool equal = false;
        Use(a => other.Use(b =>
        {
            equal = Length == other.Length &&
                CryptographicOperations.FixedTimeEquals(new ReadOnlySpan<byte>(a, Length), new ReadOnlySpan<byte>(b, other.Length));
        }));
        return equal;
    }

    /// <summary>Wipes and frees the memory. Safe to call more than once.</summary>
    public void Dispose() => _buffer.Dispose();

    /// <summary>Allocates a zeroed key of <paramref name="length"/> bytes for a native call to fill.</summary>
    internal static SecretKey Allocate(int length, SecretKeyKind kind) => new(length, kind);

    /// <summary>Runs <paramref name="action"/> with the key's address, keeping the memory alive meanwhile.</summary>
    internal unsafe void Use(PointerAction action)
    {
        ObjectDisposedException.ThrowIf(_buffer.IsClosed, this);
        bool added = false;
        try
        {
            _buffer.DangerousAddRef(ref added);
            action((byte*)_buffer.DangerousGetHandle());
        }
        finally
        {
            if (added)
            {
                _buffer.DangerousRelease();
            }
        }
    }

    /// <summary>Requires the key to have <paramref name="length"/> bytes.</summary>
    internal void RequireLength(int length, string paramName)
    {
        ObjectDisposedException.ThrowIf(_buffer.IsClosed, this);
        if (Length != length)
        {
            throw new ArgumentException($"Expected a {length}-byte secret key, got {Length} bytes.", paramName);
        }
    }

    /// <summary>Receives the address of the key.</summary>
    internal unsafe delegate void PointerAction(byte* pointer);

    /// <summary>Off-heap storage; its critical finalizer is the backstop that wipes an undisposed key.</summary>
    private sealed class Buffer : SafeHandle
    {
        internal unsafe Buffer(int length)
            : base(IntPtr.Zero, ownsHandle: true)
        {
            Length = length;
            SetHandle((IntPtr)NativeMemory.AllocZeroed((nuint)length));
        }

        internal int Length { get; }

        public override bool IsInvalid => handle == IntPtr.Zero;

        protected override unsafe bool ReleaseHandle()
        {
            void* p = handle.ToPointer();
            if (NativeMethods.SecureZero(p, (nuint)Length) != (int)ZxvStatus.Ok)
            {
                // The native wipe is unavailable: fall back to the managed one.
                CryptographicOperations.ZeroMemory(new Span<byte>(p, Length));
            }

            NativeMemory.Free(p);
            return true;
        }
    }
}
