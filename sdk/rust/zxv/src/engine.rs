/// KV-cache precision.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, Default)]
pub enum KvCache {
    /// Exact Q16 cache (4 bytes per value).
    #[default]
    Q16,
    /// 8-bit cache (about 1.16 bytes per value).
    Q8,
}

/// Why generation stopped.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum StopReason {
    /// End-of-sequence token.
    Eos,
    /// `max_tokens` reached.
    MaxTokens,
    /// Your callback (or a dropped stream) asked to stop.
    Callback,
    /// The context window is full.
    ContextFull,
    /// The bound budget ran out.
    Budget,
    /// A reason added by a newer library.
    Other(i32),
}

impl StopReason {
    fn from_raw(v: i32) -> StopReason {
        match v {
            sys::ZXV_STOP_EOS => StopReason::Eos,
            sys::ZXV_STOP_MAX => StopReason::MaxTokens,
            sys::ZXV_STOP_CALLBACK => StopReason::Callback,
            sys::ZXV_STOP_CTX => StopReason::ContextFull,
            sys::ZXV_STOP_BUDGET => StopReason::Budget,
            other => StopReason::Other(other),
        }
    }
}

/// Sampling options. All parameters are exact: rationals are converted to
/// the engine's Q16.16 with [`Rational::to_q16`].
///
/// ```
/// use zxv::{GenerateOptions, Rational};
/// let greedy = GenerateOptions::greedy(16);
/// let sampled = GenerateOptions::greedy(12)
///     .temperature(Rational::new(7, 10)?)
///     .top_k(40)
///     .top_p(Rational::new(95, 100)?)
///     .seed(42);
/// # let _ = (greedy, sampled);
/// # Ok::<(), zxv::Error>(())
/// ```
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct GenerateOptions {
    /// Maximum tokens to generate.
    pub max_tokens: u32,
    /// Temperature; zero is greedy.
    pub temperature: Rational,
    /// Top-k; zero is off.
    pub top_k: u32,
    /// Top-p; zero is off.
    pub top_p: Rational,
    /// Repeat penalty; zero is off.
    pub repeat_penalty: Rational,
    /// Window of the repeat penalty.
    pub repeat_last_n: u32,
    /// Sampling seed: the same seed and inputs give the same tokens on
    /// every machine.
    pub seed: u64,
}

impl GenerateOptions {
    /// Greedy decoding of at most `max_tokens` tokens.
    pub fn greedy(max_tokens: u32) -> GenerateOptions {
        GenerateOptions {
            max_tokens,
            temperature: Rational::ZERO,
            top_k: 0,
            top_p: Rational::ZERO,
            repeat_penalty: Rational::ZERO,
            repeat_last_n: 0,
            seed: 0,
        }
    }

    /// Sets the temperature.
    pub fn temperature(mut self, t: Rational) -> Self {
        self.temperature = t;
        self
    }

    /// Sets top-k.
    pub fn top_k(mut self, k: u32) -> Self {
        self.top_k = k;
        self
    }

    /// Sets top-p.
    pub fn top_p(mut self, p: Rational) -> Self {
        self.top_p = p;
        self
    }

    /// Sets the repeat penalty and its window.
    pub fn repeat_penalty(mut self, penalty: Rational, last_n: u32) -> Self {
        self.repeat_penalty = penalty;
        self.repeat_last_n = last_n;
        self
    }

    /// Sets the seed.
    pub fn seed(mut self, seed: u64) -> Self {
        self.seed = seed;
        self
    }
}

/// One generated token.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Token {
    /// The token id.
    pub id: i32,
    /// Its bytes (UTF-8, possibly part of a character).
    pub piece: Vec<u8>,
}

/// The result of a generation.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Generation {
    /// Generated token ids, in order.
    pub tokens: Vec<i32>,
    /// The generated bytes, decoded as UTF-8 (invalid sequences replaced).
    pub text: String,
    /// Prompt tokens evaluated.
    pub prompt_tokens: u32,
    /// Why it stopped.
    pub stop: StopReason,
}

/// A model property key for [`Model::info`].
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub enum ModelInfo {
    /// Architecture: 1 qwen2, 2 qwen3, 3 llama.
    Arch,
    /// Vocabulary size.
    VocabSize,
    /// Training context length.
    TrainContext,
    /// Layers.
    Layers,
    /// Embedding width.
    Embedding,
    /// Attention heads.
    Heads,
    /// KV heads.
    KvHeads,
    /// End-of-sequence token id.
    Eos,
}

/// A loaded GGUF model. Read-only after loading: `Send + Sync`, shareable
/// by sessions on any threads. Opening needs
/// [`Caps::AI_INFERENCE`](crate::Caps::AI_INFERENCE).
pub struct Model {
    raw: NonNull<sys::zxv_model>,
}

// SAFETY: the C ABI states a model is read-only after loading and may be
// shared by sessions on any threads.
unsafe impl Send for Model {}
// SAFETY: as above.
unsafe impl Sync for Model {}

impl std::fmt::Debug for Model {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Model")
            .field("vocab", &self.info(ModelInfo::VocabSize).ok())
            .finish()
    }
}

impl Model {
    /// Opens a GGUF file; `tokenizer` `None` uses the model's own tokenizer.
    /// A missing file is `Error::System` (`ZXV_E_IO`).
    pub fn open(
        cap: &Capability<'_>,
        path: impl AsRef<Path>,
        tokenizer: Option<&Path>,
    ) -> Result<Model> {
        let p = ffi::cstr(&path.as_ref().to_string_lossy())?;
        let t = tokenizer
            .map(|t| ffi::cstr(&t.to_string_lossy()))
            .transpose()?;
        let mut raw = std::ptr::null_mut();
        cap.call(|c| unsafe {
            sys::zxv_model_open(
                c,
                p.as_ptr(),
                t.as_ref().map_or(std::ptr::null(), |t| t.as_ptr()),
                &mut raw,
            )
        })?;
        Model::wrap(raw)
    }

    /// Opens a model from memory (the bytes are copied).
    pub fn open_memory(
        cap: &Capability<'_>,
        model: &[u8],
        tokenizer: Option<&[u8]>,
    ) -> Result<Model> {
        let (tp, tl) = tokenizer.map_or((std::ptr::null(), 0), |t| (t.as_ptr(), t.len()));
        let mut raw = std::ptr::null_mut();
        cap.call(|c| unsafe {
            sys::zxv_model_open_memory(c, model.as_ptr(), model.len(), tp, tl, &mut raw)
        })?;
        Model::wrap(raw)
    }

    fn wrap(raw: *mut sys::zxv_model) -> Result<Model> {
        let raw = NonNull::new(raw)
            .ok_or_else(|| Error::with_detail(sys::ZXV_E_INTERNAL, "NULL model"))?;
        Ok(Model { raw })
    }

    /// A model property.
    pub fn info(&self, key: ModelInfo) -> Result<i64> {
        let k = match key {
            ModelInfo::Arch => sys::ZXV_MODEL_ARCH,
            ModelInfo::VocabSize => sys::ZXV_MODEL_N_VOCAB,
            ModelInfo::TrainContext => sys::ZXV_MODEL_N_CTX_TRAIN,
            ModelInfo::Layers => sys::ZXV_MODEL_N_LAYER,
            ModelInfo::Embedding => sys::ZXV_MODEL_N_EMBD,
            ModelInfo::Heads => sys::ZXV_MODEL_N_HEAD,
            ModelInfo::KvHeads => sys::ZXV_MODEL_N_HEAD_KV,
            ModelInfo::Eos => sys::ZXV_MODEL_EOS,
        };
        let mut v = 0i64;
        // SAFETY: valid model; out pointer valid.
        crate::error::check(unsafe { sys::zxv_model_info(self.raw.as_ptr(), k, &mut v) })?;
        Ok(v)
    }

    /// Token ids of `text`. With `parse_special`, special-token text (such
    /// as `<|im_start|>`) maps to its id.
    pub fn tokenize(&self, text: &str, parse_special: bool) -> Result<Vec<i32>> {
        let mut n = 0usize;
        let m = self.raw.as_ptr();
        // SAFETY: valid model and text; R4 size query.
        let rc = unsafe {
            sys::zxv_tokenize(
                m,
                text.as_ptr(),
                text.len(),
                parse_special as i32,
                std::ptr::null_mut(),
                0,
                &mut n,
            )
        };
        if rc != sys::ZXV_E_BUFFER && rc != sys::ZXV_OK {
            return Err(Error::from_status(rc));
        }
        let mut ids = vec![0i32; n];
        // SAFETY: ids has room for n ids.
        let rc = unsafe {
            sys::zxv_tokenize(
                m,
                text.as_ptr(),
                text.len(),
                parse_special as i32,
                ids.as_mut_ptr(),
                ids.len(),
                &mut n,
            )
        };
        crate::error::check(rc)?;
        ids.truncate(n);
        Ok(ids)
    }

    /// Text of token ids (`ZXV_E_UTF8` if the bytes are not valid UTF-8).
    pub fn detokenize(&self, ids: &[i32]) -> Result<String> {
        let m = self.raw.as_ptr();
        // SAFETY: R4 closure; ids valid for its length.
        ffi::read_string(|b, c, l| unsafe {
            sys::zxv_detokenize(m, ids.as_ptr(), ids.len(), b, c, l)
        })
    }

    /// A new session (KV cache) over this model, generating through `cap`.
    /// `n_ctx` 0 means `min(n_ctx_train, 4096)`.
    pub fn new_session<'a>(
        &'a self,
        cap: &'a Capability<'a>,
        n_ctx: u32,
        kv: KvCache,
    ) -> Result<Session<'a>> {
        let kv = match kv {
            KvCache::Q16 => sys::ZXV_KV_Q16,
            KvCache::Q8 => sys::ZXV_KV_Q8,
        };
        let mut raw = std::ptr::null_mut();
        cap.context().guard()?;
        // SAFETY: valid model; out pointer valid.
        crate::error::check(unsafe {
            sys::zxv_session_create(self.raw.as_ptr(), n_ctx, kv, &mut raw)
        })?;
        let raw = NonNull::new(raw)
            .ok_or_else(|| Error::with_detail(sys::ZXV_E_INTERNAL, "NULL session"))?;
        Ok(Session {
            raw,
            model: PhantomData,
            cap,
            bound: false,
            _not_sync: PhantomData,
        })
    }

    /// LoRA adapters are declared by the ABI but not built into the engine
    /// yet: this always returns `Refused(NotImplemented)` while
    /// [`Features::LORA`](crate::Features::LORA) is off.
    pub fn load_lora(
        &self,
        cap: &Capability<'_>,
        path: impl AsRef<Path>,
        scale: Rational,
    ) -> Result<()> {
        let p = ffi::cstr(&path.as_ref().to_string_lossy())?;
        let q = scale.to_q16()?;
        let mut raw = std::ptr::null_mut();
        cap.call(|c| unsafe { sys::zxv_lora_load(c, self.raw.as_ptr(), p.as_ptr(), q, &mut raw) })?;
        // Unreachable with this library; free anything returned.
        // SAFETY: on success raw is an owned adapter.
        unsafe { sys::zxv_lora_destroy(raw) };
        Err(Error::with_detail(
            sys::ZXV_E_NOTIMPL,
            "LoRA is not supported by this SDK version",
        ))
    }
}

impl Drop for Model {
    fn drop(&mut self) {
        // SAFETY: every Session borrows the model, so all were dropped first.
        unsafe { sys::zxv_model_destroy(self.raw.as_ptr()) }
    }
}

/// A conversation (KV cache) over a [`Model`].
///
/// `Send` but not `Sync`: one thread at a time. It borrows its model and
/// capability, and any budget bound to it, so they outlive it. Generation
/// appends to the session, so a chat continues turn after turn;
/// [`reset`](Self::reset) forgets it.
pub struct Session<'a> {
    raw: NonNull<sys::zxv_session>,
    model: PhantomData<&'a Model>,
    cap: &'a Capability<'a>,
    bound: bool,
    _not_sync: PhantomData<std::cell::Cell<()>>,
}

// SAFETY: a session may move between threads; it is used by one at a time.
unsafe impl Send for Session<'_> {}

impl std::fmt::Debug for Session<'_> {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Session")
            .field("budget_bound", &self.bound)
            .finish()
    }
}

struct Bridge<'f> {
    f: &'f mut dyn FnMut(Token) -> bool,
    tokens: Vec<i32>,
    bytes: Vec<u8>,
    panic: Option<Box<dyn Any + Send>>,
}

unsafe extern "C" fn on_token(user: *mut c_void, token: i32, piece: *const u8, len: usize) -> i32 {
    // SAFETY: user is the &mut Bridge passed to zxv_generate on this thread.
    let b = unsafe { &mut *(user as *mut Bridge<'_>) };
    if b.panic.is_some() {
        return 0;
    }
    let bytes = if piece.is_null() || len == 0 {
        Vec::new()
    } else {
        // SAFETY: the engine passes `len` valid bytes for the call.
        unsafe { std::slice::from_raw_parts(piece, len) }.to_vec()
    };
    b.tokens.push(token);
    b.bytes.extend_from_slice(&bytes);
    let tok = Token {
        id: token,
        piece: bytes,
    };
    match catch_unwind(AssertUnwindSafe(|| (b.f)(tok))) {
        Ok(true) => 1,
        Ok(false) => 0,
        Err(p) => {
            b.panic = Some(p);
            0
        }
    }
}

impl<'a> Session<'a> {
    /// Forgets the conversation (empty KV cache).
    pub fn reset(&mut self) -> Result<()> {
        // SAFETY: valid session, exclusive access.
        crate::error::check(unsafe { sys::zxv_session_reset(self.raw.as_ptr()) })
    }

    /// Tokens currently in the KV cache.
    pub fn position(&self) -> Result<u32> {
        let mut p = 0u32;
        // SAFETY: valid session; out pointer valid.
        crate::error::check(unsafe { sys::zxv_session_position(self.raw.as_ptr(), &mut p) })?;
        Ok(p)
    }

    /// Charges `budget` one unit per prompt and generated token. Prompt
    /// tokens are charged up front: if they do not fit, generation returns
    /// `Refused(BudgetExhausted)` and runs nothing; mid-generation
    /// exhaustion stops with [`StopReason::Budget`].
    pub fn bind_budget(&mut self, budget: Budget<'a>) -> Result<()> {
        // SAFETY: the budget set outlives 'a, hence this session.
        let rc = unsafe {
            sys::zxv_session_bind_budget(self.raw.as_ptr(), budget_raw(&budget), budget.id())
        };
        crate::error::check(rc)?;
        self.bound = true;
        Ok(())
    }

    /// Removes the bound budget.
    pub fn unbind_budget(&mut self) -> Result<()> {
        // SAFETY: valid session; NULL unbinds.
        crate::error::check(unsafe {
            sys::zxv_session_bind_budget(self.raw.as_ptr(), std::ptr::null_mut(), 0)
        })?;
        self.bound = false;
        Ok(())
    }

    /// Generates from `prompt` and returns everything at the end.
    pub fn generate(&mut self, prompt: &str, opts: &GenerateOptions) -> Result<Generation> {
        self.generate_with(prompt, opts, |_| true)
    }

    /// Generates, calling `on_token` for each token as it is produced (on
    /// this thread). Return `false` to stop ([`StopReason::Callback`]). A
    /// panic in the callback stops generation and is resumed here.
    pub fn generate_with(
        &mut self,
        prompt: &str,
        opts: &GenerateOptions,
        mut on_token_cb: impl FnMut(Token) -> bool,
    ) -> Result<Generation> {
        let (t, p, r) = (
            opts.temperature.to_q16()?,
            opts.top_p.to_q16()?,
            opts.repeat_penalty.to_q16()?,
        );
        let mut bridge = Bridge {
            f: &mut on_token_cb,
            tokens: Vec::new(),
            bytes: Vec::new(),
            panic: None,
        };
        let (mut np, mut ng, mut stop) = (0u32, 0u32, 0i32);
        let sess = self.raw.as_ptr();
        let user = &mut bridge as *mut Bridge<'_> as *mut c_void;
        let res = self.cap.call(|cap| unsafe {
            sys::zxv_generate(
                cap,
                sess,
                prompt.as_ptr(),
                prompt.len(),
                opts.max_tokens,
                t,
                opts.top_k,
                p,
                r,
                opts.repeat_last_n,
                opts.seed,
                Some(on_token),
                user,
                &mut np,
                &mut ng,
                &mut stop,
            )
        });
        if let Some(p) = bridge.panic.take() {
            resume_unwind(p);
        }
        res?;
        Ok(Generation {
            text: String::from_utf8_lossy(&bridge.bytes).into_owned(),
            tokens: bridge.tokens,
            prompt_tokens: np,
            stop: StopReason::from_raw(stop),
        })
    }

    /// Generates on a helper thread and hands `consume` an iterator over
    /// the tokens as they arrive. Generation proceeds in step with the
    /// iterator, and dropping it early stops generation. Returns what `consume` returned and the full result.
    ///
    /// ```no_run
    /// # fn demo(session: &mut zxv::Session<'_>) -> zxv::Result<()> {
    /// let (_, result) = session.stream("Hello", &zxv::GenerateOptions::greedy(16), |tokens| {
    ///     for t in tokens {
    ///         print!("{}", String::from_utf8_lossy(&t.piece));
    ///     }
    /// })?;
    /// println!("\nstopped: {:?}", result.stop);
    /// # Ok(()) }
    /// ```
    pub fn stream<R>(
        &mut self,
        prompt: &str,
        opts: &GenerateOptions,
        consume: impl FnOnce(TokenStream) -> R,
    ) -> Result<(R, Generation)> {
        // A rendezvous channel: the engine waits for each token to be taken,
        // so dropping the iterator stops generation after at most one more
        // token, however fast the model is.
        let (tx, rx) = mpsc::sync_channel::<Token>(0);
        std::thread::scope(|s| {
            let worker =
                s.spawn(move || self.generate_with(prompt, opts, move |t| tx.send(t).is_ok()));
            let r = consume(TokenStream { rx });
            match worker.join() {
                Ok(g) => g.map(|g| (r, g)),
                Err(p) => resume_unwind(p),
            }
        })
    }
}

fn budget_raw(b: &Budget<'_>) -> *mut sys::zxv_rmag {
    b.set_raw()
}

impl Drop for Session<'_> {
    fn drop(&mut self) {
        // SAFETY: owned handle destroyed once, before its model.
        unsafe { sys::zxv_session_destroy(self.raw.as_ptr()) }
    }
}

/// Tokens of a running [`Session::stream`], in order.
#[derive(Debug)]
pub struct TokenStream {
    rx: mpsc::Receiver<Token>,
}

impl Iterator for TokenStream {
    type Item = Token;

    fn next(&mut self) -> Option<Token> {
        self.rx.recv().ok()
    }
}
