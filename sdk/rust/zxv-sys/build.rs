//! Locates and links libzxv.
//!
//! Search order for the library directory:
//! 1. `ZXV_LIB_DIR` (a directory holding `libzxv.so` / `libzxv.a`);
//! 2. the repository build output, `sdk/libzxv/build`.
//!
//! With the `regenerate` feature, `src/bindings.rs` is regenerated from
//! `zxv_api.h` (found through `ZXV_INCLUDE_DIR` or `sdk/libzxv/include`).

use std::env;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let lib_dir = env::var_os("ZXV_LIB_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| manifest.join("../../libzxv/build"));
    let lib_dir = lib_dir.canonicalize().unwrap_or(lib_dir);
    println!("cargo:rerun-if-env-changed=ZXV_LIB_DIR");
    println!("cargo:rerun-if-env-changed=ZXV_INCLUDE_DIR");
    println!("cargo:rustc-link-search=native={}", lib_dir.display());
    if env::var_os("CARGO_FEATURE_STATIC").is_some() {
        println!("cargo:rustc-link-lib=static=zxv");
        println!("cargo:rustc-link-lib=dylib=pthread");
        println!("cargo:rustc-link-lib=dylib=m");
    } else {
        println!("cargo:rustc-link-lib=dylib=zxv");
    }
    // Exposed to dependents as DEP_ZXV_LIB_DIR (used for an rpath).
    println!("cargo:lib_dir={}", lib_dir.display());

    #[cfg(feature = "regenerate")]
    regenerate(&manifest);
}

#[cfg(feature = "regenerate")]
fn regenerate(manifest: &std::path::Path) {
    let include = env::var_os("ZXV_INCLUDE_DIR")
        .map(PathBuf::from)
        .unwrap_or_else(|| manifest.join("../../libzxv/include"));
    let header = include.join("zxv_api.h");
    println!("cargo:rerun-if-changed={}", header.display());
    let bindings = bindgen::Builder::default()
        .header(header.to_string_lossy())
        .allowlist_function("zxv_.*")
        .allowlist_type("zxv_.*")
        .allowlist_var("ZXV_.*")
        .default_enum_style(bindgen::EnumVariation::Consts)
        .prepend_enum_name(false)
        .layout_tests(false)
        .use_core()
        .parse_callbacks(Box::new(MacroTypes))
        .generate_comments(true)
        .raw_line("// Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC")
        .raw_line("// SPDX-License-Identifier: Apache-2.0")
        .raw_line("// Generated by bindgen from sdk/libzxv/include/zxv_api.h.")
        .raw_line("// Regenerate: cargo build -p zxv-sys --features regenerate")
        .generate()
        .expect("bindgen failed on zxv_api.h");
    bindings
        .write_to_file(manifest.join("src/bindings.rs"))
        .expect("cannot write src/bindings.rs");
}

/// Status codes and enum-like macros are `i32` (they meet `int32_t`
/// parameters); masks, sizes and counts are `u32`.
#[cfg(feature = "regenerate")]
#[derive(Debug)]
struct MacroTypes;

/// ABI 1.4: classes, capability keys, function ids, flags and image kinds
/// meet `uint32_t` / `uint64_t` parameters; kinds, states, events and the
/// pairing result meet `int32_t` ones.
#[cfg(feature = "regenerate")]
fn is_hw_unsigned(name: &str) -> bool {
    [
        "ZXV_HW_CLASS_",
        "ZXV_HW_CAP_",
        "ZXV_HW_ISA_",
        "ZXV_HW_FN_",
        "ZXV_HW_POLICY_",
        "ZXV_HW_PF_",
        "ZXV_HW_POWER_",
        "ZXV_HW_IMG_",
    ]
    .iter()
    .any(|p| name.starts_with(p))
        || name == "ZXV_HW_ROOT"
        || name == "ZXV_HW_EXT_MAX"
        || name == "ZXV_HW_RES_HOST"
}

#[cfg(feature = "regenerate")]
impl bindgen::callbacks::ParseCallbacks for MacroTypes {
    fn int_macro(&self, name: &str, _value: i64) -> Option<bindgen::callbacks::IntKind> {
        use bindgen::callbacks::IntKind;
        let unsigned = name.starts_with("ZXV_FEAT_")
            || name.starts_with("ZXV_CCYF_")
            || name.starts_with("ZXV_STEP_")
            || name.starts_with("ZXV_ABI_VERSION_")
            || name.ends_with("_BYTES")
            || name == "ZXV_MLDSA_CTX_MAX"
            || name == "ZXV_PHASE_CYCLE"
            || name == "ZXV_MINOR_NA"
            || name == "ZXV_HEX_STATES"
            || name == "ZXV_HEXLOG_MAX_RECORDS"
            || is_hw_unsigned(name);
        Some(if unsigned { IntKind::U32 } else { IntKind::I32 })
    }
}
