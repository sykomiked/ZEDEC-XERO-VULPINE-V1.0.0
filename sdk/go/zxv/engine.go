// KVCache selects the KV-cache precision.
type KVCache int32

// KV-cache kinds.
const (
	KVQ16 KVCache = 0 // exact, 4 bytes per value
	KVQ8  KVCache = 1 // 8-bit, about 1.16 bytes per value
)

// StopReason says why generation stopped.
type StopReason int32

// Stop reasons.
const (
	StopEOS      StopReason = 1 // end-of-sequence token
	StopMax      StopReason = 2 // MaxTokens reached
	StopCallback StopReason = 4 // the callback, a cancelled context or a closed stream stopped it
	StopContext  StopReason = 5 // the context window is full
	StopBudget   StopReason = 6 // the bound budget ran out
)

// String names the stop reason.
func (s StopReason) String() string {
	switch s {
	case StopEOS:
		return "EOS"
	case StopMax:
		return "MAX_TOKENS"
	case StopCallback:
		return "CALLBACK"
	case StopContext:
		return "CONTEXT_FULL"
	case StopBudget:
		return "BUDGET"
	}
	return fmt.Sprintf("StopReason(%d)", int32(s))
}

// ModelInfoKey selects a model property.
type ModelInfoKey int32

// Model properties.
const (
	InfoArch      ModelInfoKey = 1 // 1 qwen2, 2 qwen3, 3 llama
	InfoVocab     ModelInfoKey = 2
	InfoTrainCtx  ModelInfoKey = 3
	InfoLayers    ModelInfoKey = 4
	InfoEmbedding ModelInfoKey = 5
	InfoHeads     ModelInfoKey = 6
	InfoKVHeads   ModelInfoKey = 7
	InfoEOS       ModelInfoKey = 8
)

// GenerateOptions are exact sampling options; Rationals are converted to
// the engine's Q16.16 by the library. The zero value of a Rational turns
// that knob off (Temperature zero = greedy).
type GenerateOptions struct {
	MaxTokens     uint32
	Temperature   Rational
	TopK          uint32
	TopP          Rational
	RepeatPenalty Rational
	RepeatLastN   uint32
	Seed          uint64 // the same seed and inputs give the same tokens everywhere
}

// Greedy returns options for greedy decoding of at most maxTokens.
func Greedy(maxTokens uint32) GenerateOptions { return GenerateOptions{MaxTokens: maxTokens} }

// Token is one generated token.
type Token struct {
	ID    int32
	Piece []byte // UTF-8 bytes, possibly part of a character
}

// Generation is the result of a generation.
type Generation struct {
	Tokens       []int32
	Text         string // the generated bytes as a string (may hold partial UTF-8)
	PromptTokens uint32
	Stop         StopReason
}

// Model is a loaded GGUF model. It is read-only after loading and safe for
// concurrent use by many sessions. Close it after its sessions.
type Model struct {
	h *handle
}

// OpenModel opens a GGUF file through a capability with CapAIInference.
// tokenizerPath "" uses the model's own tokenizer. A missing file matches
// ErrSystem (ZXV_E_IO).
func OpenModel(cap *Capability, path, tokenizerPath string) (*Model, error) {
	p, err := cstring(path)
	if err != nil {
		return nil, err
	}
	defer freeC(p)
	var tp *C.char
	if tokenizerPath != "" {
		if tp, err = cstring(tokenizerPath); err != nil {
			return nil, err
		}
		defer freeC(tp)
	}
	var m *C.zxv_model
	if err := cap.gated(func(cp *C.zxv_cap) C.int32_t { return C.zxv_model_open(cp, p, tp, &m) }); err != nil {
		return nil, err
	}
	return wrapModel(m), nil
}

// OpenModelMemory opens a model from bytes (copied; tokenizer may be nil).
func OpenModelMemory(cap *Capability, model, tokenizer []byte) (*Model, error) {
	if len(model) == 0 {
		return nil, newError(StatusArg, "empty model")
	}
	cm := C.CBytes(model)
	defer C.free(cm)
	var ct unsafe.Pointer
	if len(tokenizer) > 0 {
		ct = C.CBytes(tokenizer)
		defer C.free(ct)
	}
	var m *C.zxv_model
	err := cap.gated(func(cp *C.zxv_cap) C.int32_t {
		return C.zxv_model_open_memory(cp, (*C.uint8_t)(cm), C.size_t(len(model)), (*C.uint8_t)(ct), C.size_t(len(tokenizer)), &m)
	})
	if err != nil {
		return nil, err
	}
	return wrapModel(m), nil
}

func wrapModel(m *C.zxv_model) *Model {
	mod := &Model{}
	mod.h = newHandle("model", unsafe.Pointer(m), func(p unsafe.Pointer) { C.zxv_model_destroy((*C.zxv_model)(p)) })
	runtime.SetFinalizer(mod, func(m *Model) { _ = m.h.close() })
	return mod
}

// Close frees the model. It fails while sessions are open.
func (m *Model) Close() error { return m.h.close() }

// Info returns a model property.
func (m *Model) Info(key ModelInfoKey) (int64, error) {
	var v C.int64_t
	err := m.h.use(func(p unsafe.Pointer) error {
		return call(func() C.int32_t { return C.zxv_model_info((*C.zxv_model)(p), C.int32_t(key), &v) })
	})
	return int64(v), err
}

// Tokenize returns the token ids of text. With parseSpecial, special-token
// text maps to its id.
func (m *Model) Tokenize(text string, parseSpecial bool) ([]int32, error) {
	ps := C.int32_t(0)
	if parseSpecial {
		ps = 1
	}
	b := []byte(text)
	var out []int32
	err := m.h.use(func(p unsafe.Pointer) error {
		var n C.size_t
		runtime.LockOSThread()
		defer runtime.UnlockOSThread()
		rc := C.zxv_tokenize((*C.zxv_model)(p), bytePtr(b), C.size_t(len(b)), ps, nil, 0, &n)
		if rc != C.ZXV_OK && rc != C.ZXV_E_BUFFER {
			return newError(int32(rc), lastError())
		}
		ids := make([]C.int32_t, int(n)+1)
		rc = C.zxv_tokenize((*C.zxv_model)(p), bytePtr(b), C.size_t(len(b)), ps, &ids[0], C.size_t(len(ids)), &n)
		if rc != C.ZXV_OK {
			return newError(int32(rc), lastError())
		}
		out = make([]int32, int(n))
		for i := range out {
			out[i] = int32(ids[i])
		}
		return nil
	})
	return out, err
}

// Detokenize returns the text of token ids.
func (m *Model) Detokenize(ids []int32) (string, error) {
	if len(ids) == 0 {
		return "", nil
	}
	cids := make([]C.int32_t, len(ids))
	for i, id := range ids {
		cids[i] = C.int32_t(id)
	}
	var s string
	err := m.h.use(func(p unsafe.Pointer) error {
		var e error
		s, e = readString(func(b *C.char, c C.size_t, n *C.size_t) C.int32_t {
			return C.zxv_detokenize((*C.zxv_model)(p), &cids[0], C.size_t(len(cids)), b, c, n)
		})
		return e
	})
	return s, err
}

// LoadLoRA is declared by the ABI but not built into the engine: it always
// returns an error matching ErrNotImplemented while FeatLoRA is off.
func (m *Model) LoadLoRA(cap *Capability, path string, scale Rational) error {
	p, err := cstring(path)
	if err != nil {
		return err
	}
	defer freeC(p)
	q, err := scale.ToQ16()
	if err != nil {
		return err
	}
	var l *C.zxv_lora
	err = m.h.use(func(mp unsafe.Pointer) error {
		return cap.gated(func(cp *C.zxv_cap) C.int32_t { return C.zxv_lora_load(cp, (*C.zxv_model)(mp), p, C.int32_t(q), &l) })
	})
	if err != nil {
		return err
	}
	C.zxv_lora_destroy(l)
	return newError(StatusNotImpl, "LoRA is not supported by this SDK version")
}

// Session is a conversation (KV cache) over a Model. Calls are serialized
// (the C session is used by one thread at a time). Generation appends to
// the session; Reset forgets it. Close it before its model and capability.
type Session struct {
	h      *handle
	model  *Model
	cap    *Capability
	budget *Budgets
}

// NewSession creates a session generating through cap (CapAIInference).
// nCtx 0 means min(n_ctx_train, 4096).
func (m *Model) NewSession(cap *Capability, nCtx uint32, kv KVCache) (*Session, error) {
	if err := cap.ctx.guard(); err != nil {
		return nil, err
	}
	var s *C.zxv_session
	err := m.h.use(func(p unsafe.Pointer) error {
		return call(func() C.int32_t { return C.zxv_session_create((*C.zxv_model)(p), C.uint32_t(nCtx), C.int32_t(kv), &s) })
	})
	if err != nil {
		return nil, err
	}
	ses := &Session{model: m, cap: cap}
	ses.h = newHandle("session", unsafe.Pointer(s), func(p unsafe.Pointer) { C.zxv_session_destroy((*C.zxv_session)(p)) }, m.h, cap.h)
	ses.h.exclusive = true
	runtime.SetFinalizer(ses, func(s *Session) { _ = s.Close() })
	return ses, nil
}

// Close frees the session (and releases a bound budget set).
func (s *Session) Close() error {
	if err := s.h.close(); err != nil {
		return err
	}
	if s.budget != nil {
		s.budget.h.release()
		s.budget = nil
	}
	return nil
}

func (s *Session) local(f func(p *C.zxv_session) C.int32_t) error {
	return s.h.use(func(p unsafe.Pointer) error { return call(func() C.int32_t { return f((*C.zxv_session)(p)) }) })
}

// Reset forgets the conversation.
func (s *Session) Reset() error {
	return s.local(func(p *C.zxv_session) C.int32_t { return C.zxv_session_reset(p) })
}

// Position returns the number of tokens in the KV cache.
func (s *Session) Position() (uint32, error) {
	var n C.uint32_t
	err := s.local(func(p *C.zxv_session) C.int32_t { return C.zxv_session_position(p, &n) })
	return uint32(n), err
}

// BindBudget charges b one unit per prompt and generated token. Prompt
// tokens are charged up front: if they do not fit, generation fails with
// ErrBudgetExhausted and runs nothing; mid-generation exhaustion stops with
// StopBudget. The budget set cannot be closed while bound.
func (s *Session) BindBudget(b *Budget) error {
	err := b.set.h.use(func(r unsafe.Pointer) error {
		return s.local(func(p *C.zxv_session) C.int32_t {
			return C.zxv_session_bind_budget(p, (*C.zxv_rmag)(r), C.uint32_t(b.id))
		})
	})
	if err != nil {
		return err
	}
	if s.budget != b.set {
		if s.budget != nil {
			s.budget.h.release()
		}
		b.set.h.retain()
		s.budget = b.set
	}
	return nil
}

// UnbindBudget removes the bound budget.
func (s *Session) UnbindBudget() error {
	err := s.local(func(p *C.zxv_session) C.int32_t { return C.zxv_session_bind_budget(p, nil, 0) })
	if err == nil && s.budget != nil {
		s.budget.h.release()
		s.budget = nil
	}
	return err
}

// genState is what the token callback reaches through a cgo.Handle.
type genState struct {
	ctx    context.Context
	fn     func(Token) bool
	tokens []int32
	bytes  []byte
	panic  any
}

func (g *genState) onToken(t Token) (cont bool) {
	if g.panic != nil {
		return false
	}
	g.tokens = append(g.tokens, t.ID)
	g.bytes = append(g.bytes, t.Piece...)
	if g.ctx.Err() != nil {
		return false
	}
	defer func() {
		if r := recover(); r != nil {
			g.panic = r
			cont = false
		}
	}()
	return g.fn == nil || g.fn(t)
}

// Generate runs a generation to the end and returns the result.
func (s *Session) Generate(ctx context.Context, prompt string, opts GenerateOptions) (*Generation, error) {
	return s.GenerateFunc(ctx, prompt, opts, nil)
}

// GenerateFunc calls fn for each token as it is produced (on this
// goroutine); return false to stop (StopCallback). Cancelling ctx stops
// generation at the next token: the partial result is returned with
// ctx.Err(). A panic in fn stops generation and is re-raised here.
func (s *Session) GenerateFunc(ctx context.Context, prompt string, opts GenerateOptions, fn func(Token) bool) (*Generation, error) {
	if err := ctx.Err(); err != nil {
		return nil, err
	}
	t, err := opts.Temperature.ToQ16()
	if err != nil {
		return nil, err
	}
	tp, err := opts.TopP.ToQ16()
	if err != nil {
		return nil, err
	}
	rp, err := opts.RepeatPenalty.ToQ16()
	if err != nil {
		return nil, err
	}
	st := &genState{ctx: ctx, fn: fn}
	h := cgo.NewHandle(st)
	defer h.Delete()
	pb := C.CBytes([]byte(prompt))
	defer C.free(pb)
	var np, ng C.uint32_t
	var stop C.int32_t
	err = s.h.use(func(sp unsafe.Pointer) error {
		return s.cap.gated(func(cp *C.zxv_cap) C.int32_t {
			return C.zxv_go_generate(cp, (*C.zxv_session)(sp), (*C.uint8_t)(pb), C.size_t(len(prompt)),
				C.uint32_t(opts.MaxTokens), C.int32_t(t), C.uint32_t(opts.TopK), C.int32_t(tp), C.int32_t(rp),
				C.uint32_t(opts.RepeatLastN), C.uint64_t(opts.Seed), C.uintptr_t(h), &np, &ng, &stop)
		})
	})
	if st.panic != nil {
		panic(st.panic)
	}
	if err != nil {
		return nil, err
	}
	g := &Generation{Tokens: st.tokens, Text: string(st.bytes), PromptTokens: uint32(np), Stop: StopReason(stop)}
	return g, ctx.Err()
}

// Stream generates in a goroutine and delivers tokens on a channel.
type Stream struct {
	tokens chan Token
	done   chan struct{}
	cancel context.CancelFunc
	result *Generation
	err    error
}

// Tokens returns the channel of tokens; it is closed when generation ends.
func (st *Stream) Tokens() <-chan Token { return st.tokens }

// Wait blocks until generation ends and returns the result.
func (st *Stream) Wait() (*Generation, error) {
	<-st.done
	return st.result, st.err
}

// Close stops generation early (StopCallback) and waits for it to end.
func (st *Stream) Close() {
	st.cancel()
	for range st.tokens {
	}
	<-st.done
}

// GenerateStream starts a generation whose tokens arrive on Stream.Tokens.
// The channel is unbuffered, so generation runs in step with the reader.
// Cancel ctx or call Stream.Close to stop early. Do not use the session
// until Wait returns.
func (s *Session) GenerateStream(ctx context.Context, prompt string, opts GenerateOptions) *Stream {
	cctx, cancel := context.WithCancel(ctx)
	st := &Stream{tokens: make(chan Token), done: make(chan struct{}), cancel: cancel}
	go func() {
		defer close(st.done)
		defer cancel()
		defer close(st.tokens)
		st.result, st.err = s.GenerateFunc(cctx, prompt, opts, func(t Token) bool {
			select {
			case st.tokens <- t:
				return true
			case <-cctx.Done():
				return false
			}
		})
		if st.err == context.Canceled && ctx.Err() == nil {
			st.err = nil // stopped by Stream.Close, not by the caller's context
		}
	}()
	return st
}
