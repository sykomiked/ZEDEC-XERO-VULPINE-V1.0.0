/* zaero_geo.c — WGS-84 geodetic <-> ECEF in integer fixed point.
 *
 * Representation:
 *   angles     internal unit 2^-24 nano-degree (180 degrees = 3.02e18, fits
 *              an int64); inputs and outputs in nano- or pico-degrees
 *   lengths    internal unit 2^-20 mm (110,000 km = 1.15e17)
 *   sin, cos   Q61 (1.0 = 2^61)
 * Products go through a portable 64x64->128-bit multiply with rounding
 * (mulq), so nothing depends on __int128 or on the host's float unit.
 *
 * sin/cos come from CORDIC rotation and atan2/hypot from CORDIC vectoring,
 * 62 steps each, with one table of atan(2^-i) in internal angle units and
 * the inverse gain in Q61. Both were generated by tools/gen_geo.py from an
 * 80-digit decimal computation.
 *
 * ECEF -> geodetic iterates phi <- atan2(Z + e^2 N(phi) sin(phi), p) from
 * phi0 = atan2(Z, p (1 - e^2)) until it moves by less than 2^12 internal
 * units (2.4e-4 nano-degree); the contraction factor is about e^2 = 0.0067,
 * so this takes 6 to 9 steps. h = p cos(phi) + (Z + e^2 N sin(phi)) sin(phi)
 * - N, which is well conditioned at every latitude. Integer code only (R11). */
#include "zaero.h"

/* generated by tools/gen_geo.py --constants */
#define Q61_ONE  (INT64_C(1) << 61)
#define E2_Q61   INT64_C(15436189301287393)   /* e^2     */
#define OME2_Q61 INT64_C(2290406819912406559) /* 1 - e^2 */
#define INVK_Q61 INT64_C(1400229935014726477) /* 1 / CORDIC gain, 62 steps */
/* atan(2^-i) in units of 2^-24 nano-degree */
static const int64_t k_atan[62] = {
    INT64_C(754974720000000000), INT64_C(445687601648891676), INT64_C(235489088489991603),
    INT64_C(119537938289056820), INT64_C(60000934297555558), INT64_C(30029716895235686),
    INT64_C(15018522693732599), INT64_C(7509719629188405), INT64_C(3754917107751043),
    INT64_C(1877465715765999), INT64_C(938733753126993), INT64_C(469366988469236),
    INT64_C(234683508222843), INT64_C(117341755859950), INT64_C(58670878148541),
    INT64_C(29335439101591), INT64_C(14667719554211), INT64_C(7333859777532),
    INT64_C(3666929888819), INT64_C(1833464944416), INT64_C(916732472209),
    INT64_C(458366236105), INT64_C(229183118052), INT64_C(114591559026),
    INT64_C(57295779513), INT64_C(28647889757), INT64_C(14323944878),
    INT64_C(7161972439), INT64_C(3580986220), INT64_C(1790493110),
    INT64_C(895246555), INT64_C(447623277), INT64_C(223811639),
    INT64_C(111905819), INT64_C(55952910), INT64_C(27976455),
    INT64_C(13988227), INT64_C(6994114), INT64_C(3497057),
    INT64_C(1748528), INT64_C(874264), INT64_C(437132),
    INT64_C(218566), INT64_C(109283), INT64_C(54642),
    INT64_C(27321), INT64_C(13660), INT64_C(6830),
    INT64_C(3415), INT64_C(1708), INT64_C(854),
    INT64_C(427), INT64_C(213), INT64_C(107),
    INT64_C(53), INT64_C(27), INT64_C(13),
    INT64_C(7), INT64_C(3), INT64_C(2),
    INT64_C(1), INT64_C(0),
};

#define ANG_FRAC 24
#define LEN_FRAC 20
#define ANG_ONE (INT64_C(1) << ANG_FRAC)
#define LEN_ONE (INT64_C(1) << LEN_FRAC)
#define DEG90  (INT64_C(90000000000) << ANG_FRAC)
#define DEG180 (INT64_C(180000000000) << ANG_FRAC)
#define A_Q20  (INT64_C(6378137000) << LEN_FRAC)

/* ===== fixed-point helpers ===== */

/* floor(v / 2^s) without relying on the sign behaviour of >> */
static int64_t asr(int64_t v, unsigned s) {
    if (v >= 0) return (int64_t) ((uint64_t) v >> s);
    return -(int64_t) (((uint64_t) (-(v + 1))) >> s) - 1;
}

static void mul_u64(uint64_t a, uint64_t b, uint64_t *hi, uint64_t *lo) {
    uint64_t a0 = a & 0xFFFFFFFFu, a1 = a >> 32, b0 = b & 0xFFFFFFFFu, b1 = b >> 32;
    uint64_t p00 = a0 * b0, p01 = a0 * b1, p10 = a1 * b0, p11 = a1 * b1;
    uint64_t mid = (p00 >> 32) + (p01 & 0xFFFFFFFFu) + (p10 & 0xFFFFFFFFu);
    *lo = (mid << 32) | (p00 & 0xFFFFFFFFu);
    *hi = p11 + (p01 >> 32) + (p10 >> 32) + (mid >> 32);
}

/* round(a * b / 2^s), half away from zero, s in 1..63. The callers' ranges
 * keep the result below 2^62. */
static int64_t mulq(int64_t a, int64_t b, unsigned s) {
    int neg = (a < 0) != (b < 0);
    uint64_t ua = a < 0 ? 0u - (uint64_t) a : (uint64_t) a;
    uint64_t ub = b < 0 ? 0u - (uint64_t) b : (uint64_t) b;
    uint64_t hi, lo, half = UINT64_C(1) << (s - 1), q;
    mul_u64(ua, ub, &hi, &lo);
    lo += half;
    if (lo < half) hi++;
    q = (lo >> s) | (hi << (64 - s));
    return neg ? -(int64_t) q : (int64_t) q;
}

/* round(v / 2^s), half away from zero */
static int64_t rshr(int64_t v, unsigned s) {
    int64_t half = INT64_C(1) << (s - 1);
    return v >= 0 ? (v + half) >> s : -((-v + half) >> s);
}

/* ===== CORDIC ===== */

/* cos and sin (Q61) of an angle in internal units, |angle| <= 180 deg. */
static void sincos_u(int64_t ang, int64_t *s_out, int64_t *c_out) {
    int64_t x = INVK_Q61, y = 0, z = ang;
    int flip = 0;
    if (z > DEG90) {
        z -= DEG180;
        flip = 1;
    } else if (z < -DEG90) {
        z += DEG180;
        flip = 1;
    }
    for (unsigned i = 0; i < 62; i++) {
        int64_t xs = asr(x, i), ys = asr(y, i);
        if (z >= 0) {
            x -= ys;
            y += xs;
            z -= k_atan[i];
        } else {
            x += ys;
            y -= xs;
            z += k_atan[i];
        }
    }
    *s_out = flip ? -y : y;
    *c_out = flip ? -x : x;
}

/* atan2(y, x) in internal angle units, (-180, 180] deg, and hypot(x, y) in
 * the inputs' unit (may be NULL). |x|, |y| < 2^61. */
static void atan2_u(int64_t y, int64_t x, int64_t *ang_out, int64_t *mag_out) {
    int64_t z = 0, off = 0, m;
    unsigned sh = 0;
    if (x < 0) {
        off = y >= 0 ? DEG180 : -DEG180;
        x = -x;
        y = -y;
    }
    m = x > (y < 0 ? -y : y) ? x : (y < 0 ? -y : y);
    if (m == 0) {
        *ang_out = 0;
        if (mag_out) *mag_out = 0;
        return;
    }
    while (m < (INT64_C(1) << 59)) {
        m <<= 1;
        sh++;
    }
    x *= INT64_C(1) << sh;
    y *= INT64_C(1) << sh;
    for (unsigned i = 0; i < 62; i++) {
        int64_t xs = asr(x, i), ys = asr(y, i);
        if (y > 0) {
            x += ys;
            y -= xs;
            z += k_atan[i];
        } else {
            x -= ys;
            y += xs;
            z -= k_atan[i];
        }
    }
    z += off;
    if (z <= -DEG180) z += 2 * DEG180;
    if (z > DEG180) z -= 2 * DEG180;
    *ang_out = z;
    if (mag_out) {
        int64_t r = mulq(x, INVK_Q61, 61);
        *mag_out = sh ? rshr(r, sh) : r;
    }
}

/* 1/sqrt(w) in Q61 for w in Q61 near 1 (0.99..1.0): Newton from 1. */
static int64_t invsqrt_q61(int64_t w) {
    int64_t y = Q61_ONE;
    for (int i = 0; i < 6; i++) {
        int64_t y2 = mulq(y, y, 61);
        int64_t t = 3 * Q61_ONE - mulq(w, y2, 61);
        y = mulq(y, t, 62);
    }
    return y;
}

/* prime vertical radius N (Q20 mm) from sin(phi) */
static int64_t radius_n(int64_t s) {
    int64_t w = Q61_ONE - mulq(E2_Q61, mulq(s, s, 61), 61);
    return mulq(A_Q20, invsqrt_q61(w), 61);
}

/* ===== forward ===== */

static int32_t check_geo(const zao_geo *g) {
    if (g->lat_nd < -ZAO_LAT_MAX || g->lat_nd > ZAO_LAT_MAX || g->lon_nd < -ZAO_LON_MAX ||
        g->lon_nd > ZAO_LON_MAX || g->h_mm < ZAO_H_MIN || g->h_mm > ZAO_H_MAX) {
        zind_set_error("zao: latitude, longitude or height outside the supported range");
        return ZAO_E_RANGE;
    }
    return ZXV_OK;
}

static void fwd_q20(const zao_geo *g, int64_t *x, int64_t *y, int64_t *z) {
    int64_t s, c, sl, cl, n, t;
    sincos_u(g->lat_nd * ANG_ONE, &s, &c);
    sincos_u(g->lon_nd * ANG_ONE, &sl, &cl);
    n = radius_n(s);
    t = mulq(n + g->h_mm * LEN_ONE, c, 61);
    *x = mulq(t, cl, 61);
    *y = mulq(t, sl, 61);
    *z = mulq(mulq(n, OME2_Q61, 61) + g->h_mm * LEN_ONE, s, 61);
}

int32_t zao_geo_to_ecef(const zao_geo *g, zao_ecef *out) {
    int64_t x, y, z;
    int32_t st;
    if (!g || !out) return ZXV_E_ARG;
    st = check_geo(g);
    if (st != ZXV_OK) return st;
    fwd_q20(g, &x, &y, &z);
    out->x_mm = rshr(x, LEN_FRAC);
    out->y_mm = rshr(y, LEN_FRAC);
    out->z_mm = rshr(z, LEN_FRAC);
    return ZXV_OK;
}

int32_t zao_geo_to_ecef_um(const zao_geo *g, zao_ecef_um *out) {
    int64_t x, y, z;
    int32_t st;
    if (!g || !out) return ZXV_E_ARG;
    st = check_geo(g);
    if (st != ZXV_OK) return st;
    fwd_q20(g, &x, &y, &z);
    out->x_um = mulq(x, 1000, LEN_FRAC);
    out->y_um = mulq(y, 1000, LEN_FRAC);
    out->z_um = mulq(z, 1000, LEN_FRAC);
    return ZXV_OK;
}

/* ===== inverse ===== */

static int32_t inv_q(const zao_ecef *e, int64_t *lat_u, int64_t *lon_u, int64_t *h_q20) {
    int64_t X, Y, Z, p, phi, s = 0, c = 0, n = 0, zz = 0, h;
    if (e->x_mm < -ZAO_ECEF_MAX || e->x_mm > ZAO_ECEF_MAX || e->y_mm < -ZAO_ECEF_MAX ||
        e->y_mm > ZAO_ECEF_MAX || e->z_mm < -ZAO_ECEF_MAX || e->z_mm > ZAO_ECEF_MAX) {
        zind_set_error("zao_ecef_to_geo: an ECEF axis is beyond +-110,000 km");
        return ZAO_E_RANGE;
    }
    X = e->x_mm * LEN_ONE;
    Y = e->y_mm * LEN_ONE;
    Z = e->z_mm * LEN_ONE;
    atan2_u(Y, X, lon_u, &p);
    atan2_u(Z, mulq(p, OME2_Q61, 61), &phi, NULL);
    for (int i = 0; i < 40; i++) {
        int64_t nxt, d;
        sincos_u(phi, &s, &c);
        n = radius_n(s);
        zz = Z + mulq(E2_Q61, mulq(n, s, 61), 61);
        atan2_u(zz, p, &nxt, NULL);
        d = nxt - phi;
        phi = nxt;
        if (d >= -4096 && d <= 4096) break;
    }
    sincos_u(phi, &s, &c);
    n = radius_n(s);
    zz = Z + mulq(E2_Q61, mulq(n, s, 61), 61);
    h = mulq(p, c, 61) + mulq(zz, s, 61) - n;
    if (rshr(h, LEN_FRAC) < ZAO_H_MIN || rshr(h, LEN_FRAC) > ZAO_H_MAX) {
        zind_set_error("zao_ecef_to_geo: the point is %s the supported height range",
                       h < 0 ? "below" : "above");
        return ZAO_E_RANGE;
    }
    *lat_u = phi;
    *h_q20 = h;
    return ZXV_OK;
}

int32_t zao_ecef_to_geo(const zao_ecef *e, zao_geo *out) {
    int64_t lat, lon, h;
    int32_t st;
    if (!e || !out) return ZXV_E_ARG;
    st = inv_q(e, &lat, &lon, &h);
    if (st != ZXV_OK) return st;
    out->lat_nd = rshr(lat, ANG_FRAC);
    out->lon_nd = rshr(lon, ANG_FRAC);
    if (out->lon_nd == -ZAO_LON_MAX) out->lon_nd = ZAO_LON_MAX;
    out->h_mm = rshr(h, LEN_FRAC);
    return ZXV_OK;
}

int32_t zao_ecef_to_geo_fine(const zao_ecef *e, zao_geo_fine *out) {
    int64_t lat, lon, h;
    int32_t st;
    if (!e || !out) return ZXV_E_ARG;
    st = inv_q(e, &lat, &lon, &h);
    if (st != ZXV_OK) return st;
    out->lat_pd = mulq(lat, 1000, ANG_FRAC);
    out->lon_pd = mulq(lon, 1000, ANG_FRAC);
    if (out->lon_pd == -ZAO_LON_MAX * 1000) out->lon_pd = ZAO_LON_MAX * 1000;
    out->h_um = mulq(h, 1000, LEN_FRAC);
    return ZXV_OK;
}
