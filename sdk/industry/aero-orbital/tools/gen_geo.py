"""Generate the integer constants and the high-precision reference vectors
for aero-orbital's fixed-point WGS-84 conversions.

Everything is computed with Python's decimal module at 80 significant
digits (sin, cos, atan by series, sqrt by Decimal.sqrt), never with binary
floating point, so the reference is independent of the C code under test.

  python3 tools/gen_geo.py > test/geo_vectors.h      (the reference vectors)
  python3 tools/gen_geo.py --constants               (the C constants)

The vectors are deterministic (a fixed xorshift stream), so regenerating
them gives the same file.
"""
import sys
from decimal import Decimal as D, getcontext

getcontext().prec = 80

A_MM = D(6378137000)                       # WGS-84 semi-major axis, mm
F = D(1) / D("298.257223563")              # flattening
E2 = F * (2 - F)                           # first eccentricity squared
ANG_FRAC = 24                              # internal angle unit: 2^-24 nano-degree
Q = 61                                     # trig values are Q61


def pi():
    # Machin: pi = 16 atan(1/5) - 4 atan(1/239)
    def atan_inv(n):
        x = D(1) / n
        x2 = x * x
        s, t, k = D(0), x, 0
        while True:
            term = t / (2 * k + 1)
            if abs(term) < D(10) ** -78:
                break
            s += term if k % 2 == 0 else -term
            t *= x2
            k += 1
        return s
    return 16 * atan_inv(5) - 4 * atan_inv(239)


PI = pi()


def sin(x):
    x = x % (2 * PI)
    s, t, k = D(0), x, 1
    while abs(t) > D(10) ** -78:
        s += t
        t = -t * x * x / ((k + 1) * (k + 2))
        k += 2
    return s


def cos(x):
    return sin(x + PI / 2)


def atan(x):
    # reduce |x| below 0.1 by halving the angle three times
    halvings = 0
    while abs(x) > D("0.1"):
        x = x / (1 + (1 + x * x).sqrt())
        halvings += 1
    s, t, k = D(0), x, 0
    while abs(t) > D(10) ** -78:
        s += t / (2 * k + 1) if k % 2 == 0 else -t / (2 * k + 1)
        t *= x * x
        k += 1
    return s * (2 ** halvings)


def atan2(y, x):
    if x > 0:
        return atan(y / x)
    if x < 0:
        return atan(y / x) + (PI if y >= 0 else -PI)
    if y > 0:
        return PI / 2
    if y < 0:
        return -PI / 2
    return D(0)


def rad(nd):
    return D(nd) / D(10) ** 9 * PI / 180


def to_ecef(lat_nd, lon_nd, h_mm):
    p, l = rad(lat_nd), rad(lon_nd)
    s, c = sin(p), cos(p)
    n = A_MM / (1 - E2 * s * s).sqrt()
    h = D(h_mm)
    return ((n + h) * c * cos(l), (n + h) * c * sin(l), (n * (1 - E2) + h) * s)


def to_geo(x, y, z):
    x, y, z = D(x), D(y), D(z)
    lon = atan2(y, x)
    p = (x * x + y * y).sqrt()
    phi = atan2(z, p * (1 - E2))
    for _ in range(200):
        s = sin(phi)
        n = A_MM / (1 - E2 * s * s).sqrt()
        nxt = atan2(z + E2 * n * s, p)
        if abs(nxt - phi) < D(10) ** -70:
            phi = nxt
            break
        phi = nxt
    s, c = sin(phi), cos(phi)
    n = A_MM / (1 - E2 * s * s).sqrt()
    h = p * c + (z + E2 * n * s) * s - n
    deg = D(180) / PI
    return phi * deg, lon * deg, h


def rnd(d):
    return int(d.to_integral_value(rounding="ROUND_HALF_EVEN"))


def constants():
    print("/* generated by tools/gen_geo.py --constants */")
    print("#define Q61_ONE  (INT64_C(1) << 61)")
    print("#define E2_Q61   INT64_C(%d) /* e^2 */" % rnd(E2 * 2 ** Q))
    print("#define OME2_Q61 INT64_C(%d) /* 1 - e^2 */" % rnd((1 - E2) * 2 ** Q))
    k = D(1)
    for i in range(62):
        k *= (1 + D(2) ** (-2 * i)).sqrt()
    print("#define INVK_Q61 INT64_C(%d) /* 1 / CORDIC gain, 62 steps */" % rnd(2 ** Q / k))
    print("/* atan(2^-i) in units of 2^-24 nano-degree */")
    print("static const int64_t k_atan[62] = {")
    vals = []
    for i in range(62):
        a = atan(D(2) ** -i) * D(180) / PI * D(10) ** 9 * 2 ** ANG_FRAC
        vals.append("INT64_C(%d)" % rnd(a))
    for i in range(0, 62, 3):
        print("    " + ", ".join(vals[i:i + 3]) + ",")
    print("};")


class Rng:
    def __init__(self, s):
        self.s = s

    def next(self):
        x = self.s
        x ^= x >> 12
        x ^= (x << 25) & 0xFFFFFFFFFFFFFFFF
        x ^= x >> 27
        self.s = x
        return (x * 2685821657736338717) & 0xFFFFFFFFFFFFFFFF


def heights(r):
    # spread over -10 km .. 100,000 km, dense near the surface and LEO
    k = r.next() % 6
    if k == 0:
        return -10_000_000 + int(r.next() % 20_000_001)                 # -10 km .. +10 km
    if k == 1:
        return int(r.next() % 2_000_000_001)                            # 0 .. 2,000 km
    if k == 2:
        return 35_786_000_000 + int(r.next() % 2_000_001) - 1_000_000   # GEO
    if k == 3:
        return int(r.next() % 100_000_000_001)                          # anywhere
    if k == 4:
        return int(r.next() % 10_000_001)
    return 400_000_000 + int(r.next() % 200_000_001)                    # ISS-like


def geo_inputs():
    pts = [
        (0, 0, 0), (90_000_000_000, 0, 0), (-90_000_000_000, 0, 0),
        (0, 180_000_000_000, 0), (0, -180_000_000_000, 0), (0, 90_000_000_000, 0),
        (45_000_000_000, 45_000_000_000, 0), (-33_868_820_000, 151_209_296_000, 58_000),
        (51_477_928_000, -1_000, 45_000), (89_999_999_999, 123_456_789_012, 1_000),
        (-89_999_999_999, -179_999_999_999, -10_000_000), (0, 0, 100_000_000_000),
        (0, 0, -10_000_000), (1, 1, 1), (-1, -1, -1),
        (37_427_500_000, -122_169_700_000, 30_000), (28_524_058_000, -80_650_849_000, 3_000),
        (5_239_000_000, -52_768_000_000, 0), (45_920_000_000, 63_342_000_000, 90_000),
        (0, 75_000_000_000, 35_786_000_000), (0, -135_000_000_000, 35_786_000_000),
    ]
    r = Rng(0x5EEDA3)
    while len(pts) < 256:
        lat = int(r.next() % 180_000_000_001) - 90_000_000_000
        lon = int(r.next() % 360_000_000_001) - 180_000_000_000
        pts.append((lat, lon, heights(r)))
    return pts


def vectors():
    print("/* Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC */")
    print("/* SPDX-License-Identifier: Apache-2.0 */")
    print("/* geo_vectors.h — generated by tools/gen_geo.py (decimal, 80 digits). Do")
    print(" * not edit. fwd: geodetic (nano-degrees, mm) -> exact ECEF in micrometres.")
    print(" * inv: ECEF in whole mm -> latitude and longitude in pico-degrees and the")
    print(" * height in micrometres. Values are rounded half-even at that resolution. */")
    print("#ifndef GEO_VECTORS_H")
    print("#define GEO_VECTORS_H")
    print("#include <stdint.h>")
    print("typedef struct { int64_t lat_nd, lon_nd, h_mm, x_um, y_um, z_um; } geo_fwd_vec;")
    print("typedef struct { int64_t x_mm, y_mm, z_mm, lat_pd, lon_pd, h_um; } geo_inv_vec;")
    pts = geo_inputs()
    print("static const geo_fwd_vec k_fwd[%d] = {" % len(pts))
    inv = []
    for (lat, lon, h) in pts:
        x, y, z = to_ecef(lat, lon, h)
        print("    {%d, %d, %d, %d, %d, %d}," % (lat, lon, h, rnd(x * 1000), rnd(y * 1000),
                                                rnd(z * 1000)))
        inv.append((rnd(x), rnd(y), rnd(z)))
    print("};")
    print("static const geo_inv_vec k_inv[%d] = {" % len(inv))
    for (x, y, z) in inv:
        la, lo, h = to_geo(x, y, z)
        if lo <= -180 and lo > D(-180) - D(10) ** -20:
            lo = D(180)
        print("    {%d, %d, %d, %d, %d, %d}," % (x, y, z, rnd(la * D(10) ** 12),
                                                rnd(lo * D(10) ** 12), rnd(h * 1000)))
    print("};")
    print("#endif")


if __name__ == "__main__":
    if "--constants" in sys.argv:
        constants()
    else:
        vectors()
