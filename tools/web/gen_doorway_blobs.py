"""gen_doorway_blobs.py — the doorway files as C bytes for the seed's door.

The seed's plain-http door (kernel/src/vinea/vna_door.c) serves the small,
committed doorway files from compiled-in blobs; boot.json and boot.pack
are seal-time artifacts and stay on the gateways (the browser fetches them
cross-origin — https from an http origin is allowed and the gateways send
Access-Control-Allow-Origin: *).

Usage: gen_doorway_blobs.py <src_root> <out.h>
"""
import sys
import os

# (path the door answers, source file, Content-Type)
FILES = [
    ("/index.html", "web/intro/index.html", "text/html; charset=utf-8"),
    ("/boot.html", "web/boot/boot.html", "text/html; charset=utf-8"),
    ("/boot.js", "web/boot/boot.js", "text/javascript; charset=utf-8"),
    ("/zxv.css", "web/zxv.css", "text/css; charset=utf-8"),
    ("/zxv_boot.wasm", "web/boot/zxv_boot.wasm", "application/wasm"),
    ("/exchange.json", "docs/curriculum/EXCHANGE.json", "application/json"),
]


def main():
    if len(sys.argv) != 3:
        sys.stderr.write("usage: gen_doorway_blobs.py <src_root> <out.h>\n")
        return 2
    root, out = sys.argv[1], sys.argv[2]
    parts = [
        "/* generated by tools/web/gen_doorway_blobs.py — do not edit */",
        "#ifndef ZXV_DOORWAY_BLOBS_H",
        "#define ZXV_DOORWAY_BLOBS_H",
        "#include <stdint.h>",
        "",
    ]
    names = []
    for i, (path, rel, ctype) in enumerate(FILES):
        with open(os.path.join(root, rel), "rb") as f:
            data = f.read()
        name = f"door_blob_{i}"
        names.append((path, name, len(data), ctype))
        parts.append(f"static const uint8_t {name}[] = {{")
        for j in range(0, len(data), 16):
            parts.append("    " + ",".join(str(b) for b in data[j : j + 16]) + ",")
        parts.append("};")
    parts += [
        "",
        "typedef struct { const char *path; const uint8_t *bytes; uint32_t len; "
        "const char *type; } zxv_door_file_t;",
        "static const zxv_door_file_t zxv_door_files[] = {",
    ]
    for path, name, ln, ctype in names:
        parts.append(f'    {{"{path}", {name}, {ln}u, "{ctype}"}},')
    parts += ["};", "#define ZXV_DOOR_FILE_N (sizeof zxv_door_files / sizeof zxv_door_files[0])",
              "", "#endif /* ZXV_DOORWAY_BLOBS_H */", ""]
    with open(out, "w") as f:
        f.write("\n".join(parts))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
