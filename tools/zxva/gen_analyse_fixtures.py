"""gen_analyse_fixtures.py - fixtures for kernel/src/vaudio/test_zxva_analyse.c.

    python3 tools/zxva/gen_analyse_fixtures.py [out.inc]

Five short recordings (16 kHz, 0.4 s; the signals of tools/zxva/fidelity.py
scaled to that rate, plus a stereo pair and a 24-bit one), each written as
integer PCM together with what tools/zxva/wav2zxva.py makes of it (the
parametric file, no residual). The C test analyses the same PCM with the
kernel analyser and measures both files against the source with one
definition (zxva_measure), so the comparison is like for like. Needs numpy
and a C compiler (wav2zxva.py builds the kernel renderer).
"""
import math
import os
import sys
import tempfile

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, "..", ".."))
sys.path.insert(0, HERE)
import wav2zxva as A  # noqa: E402

RATE = 16000
DUR = 0.4
OUT = os.path.join(ROOT, "kernel", "src", "vaudio", "test", "zxva_analyse_fixtures.inc")


def q(x, bits, peak=0.8):
    x = x / np.max(np.abs(x)) * peak
    top = (1 << (bits - 1)) - 1
    return np.clip(np.round(x * top), -top - 1, top).astype(np.int64)


def t():
    return np.arange(int(DUR * RATE)) / RATE


def piano():
    tt, x = t(), 0
    for k in range(1, 25):
        fk = k * 220.0 * math.sqrt(1 + 0.0004 * k * k)
        if fk > 7000:
            break
        env = np.minimum(1, tt / 0.003) * np.exp(-tt * (0.7 + 0.25 * k) * 3)
        x = x + k ** -1.2 * env * np.sin(2 * np.pi * fk * tt + 0.3 * k)
    return x


def vowel():
    tt = t()
    f0 = 130 * (1 + 0.01 * np.sin(2 * np.pi * 5 * tt))
    ph = 2 * np.pi * np.cumsum(f0) / RATE
    x = np.zeros_like(tt)
    for k in range(1, int(5000 / 130)):
        fk = k * f0
        g = sum(a / np.sqrt((1 - (fk / F) ** 2) ** 2 + (fk * bw / F ** 2) ** 2)
                for F, bw, a in [(700, 130, 1.0), (1220, 70, 0.5), (2600, 160, 0.25)])
        x += g / k * np.sin(k * ph)
    return x * np.minimum(1, tt / 0.02) * np.minimum(1, (DUR - tt) / 0.05)


def burst():
    rng = np.random.default_rng(1)
    n = int(DUR * RATE)
    x = np.zeros(n)
    a, b, r = int(0.1 * RATE), int(0.3 * RATE), int(0.01 * RATE)
    env = np.ones(b - a)
    env[:r] = np.linspace(0, 1, r)
    env[-r:] = np.linspace(1, 0, r)
    x[a:b] = rng.standard_normal(b - a) * env
    return x * 0.5 / 0.8


def clicks():
    n = int(DUR * RATE)
    x = np.zeros(n)
    tc = np.arange(int(0.004 * RATE)) / RATE
    c = np.exp(-tc / 0.0005) * np.sin(2 * np.pi * 3000 * tc)
    c[0] += 0.5
    for i in range(4):
        p = int((0.05 + 0.1 * i) * RATE)
        x[p:p + len(c)] += c * (1 - 0.05 * i)
    return x


def chord(fs):
    tt, x = t(), 0
    for j, f in enumerate(fs):
        for k in range(1, 6):
            x = x + (1.0 / k) * np.exp(-tt * (0.5 + 0.2 * k)) * np.sin(2 * np.pi * f * k * tt + j + k)
    return x * np.minimum(1, tt / 0.01)


def analyse(pcm, bits):
    d = tempfile.mkdtemp()
    p = os.path.join(d, "a.wav")
    A.write_wav(p, RATE, bits, pcm)
    w, _, _ = A.analyse(p, residual=False)
    os.remove(p)
    os.rmdir(d)
    return w.bytes()


def arr(name, ctype, vals, per=16):
    out = ["static const %s %s[%d] = {" % (ctype, name, len(vals))]
    for i in range(0, len(vals), per):
        out.append("    " + ",".join(str(int(v)) for v in vals[i:i + per]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else OUT
    sigs = [("piano", 16, q(piano(), 16)[:, None]),
            ("vowel24", 24, q(vowel(), 24)[:, None]),
            ("burst", 16, q(burst(), 16, 0.5)[:, None]),
            ("clicks", 16, q(clicks(), 16)[:, None]),
            ("stereo", 16, np.stack([q(chord((261.63, 392.0)), 16), q(chord((329.63, 523.25)), 16)], 1))]
    body = ["/* Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC */",
            "/* SPDX-License-Identifier: Apache-2.0 */",
            "/* Generated by tools/zxva/gen_analyse_fixtures.py; do not edit. */"]
    rows = []
    for name, bits, pcm in sigs:
        ref = analyse(pcm, bits)
        body.append(arr("an_pcm_" + name, "int32_t", pcm.reshape(-1).tolist()))
        body.append(arr("an_py_" + name, "uint8_t", list(ref), 24))
        rows.append('    {"%s", an_pcm_%s, %d, %d, %d, an_py_%s, %d},' %
                    (name, name, pcm.shape[0], pcm.shape[1], bits, name, len(ref)))
    body.append("typedef struct {\n    const char *name;\n    const int32_t *pcm;\n    uint32_t frames, nch, "
                "bits;\n    const uint8_t *py;\n    uint32_t py_len;\n} an_fx_t;")
    body.append("#define AN_RATE %d" % RATE)
    body.append("static const an_fx_t AN_FX[] = {\n" + "\n".join(rows) + "\n};")
    open(out, "w").write("\n".join(body) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
