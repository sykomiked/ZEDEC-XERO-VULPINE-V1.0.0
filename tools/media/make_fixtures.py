def jpeg_ref(d):
    im = ImageOps.exif_transpose(Image.open(io.BytesIO(d)))
    return pil_rgba(im.convert("RGB")), im.size


def strip_dht(d):
    out, i = bytearray(d[:2]), 2
    while True:
        assert d[i] == 0xFF
        m = d[i + 1]
        if m == 0xDA:
            return bytes(out + d[i:])
        ln = struct.unpack(">H", d[i + 2:i + 4])[0]
        if m != 0xC4:
            out += d[i:i + 2 + ln]
        i += 2 + ln


