    src = picture(W, H, 3)
    pal = [((i * 53) & 255, (i * 101) & 255, (i * 197) & 255) for i in range(256)]

    def samples(ctype, depth):
        mx = (1 << depth) - 1
        out = []
        for i, (r, g, b, a) in enumerate(src):
            if depth == 16:  # use the low byte too
                r, g, b, a = [(v << 8) | ((v * 7 + i) & 255) for v in (r, g, b, a)]
            elif depth < 8:
                r, g, b, a = [v >> (8 - depth) for v in (r, g, b, a)]
            grey = (r + g + b) // 3
            if ctype == 0:
                out.append((grey,))
            elif ctype == 2:
                out.append((r, g, b))
            elif ctype == 3:
                out.append((((r ^ (g >> 1)) + i) & mx,))
            elif ctype == 4:
                out.append((grey, a))
            else:
                out.append((r, g, b, a))
        return out

    def add(name, ctype, depth, **kw):
        pix = samples(ctype, depth)
        plte = pal[:1 << depth] if ctype == 3 else None
        tk = kw.pop("trns_key", None)
        tp = kw.pop("trns_pal", None)
        trns = None
        if tk is not None:
            tk = pix[tk]  # a colour that occurs, so the key matters
            trns = b"".join(struct.pack(">H", v) for v in tk)
        if tp is not None:
            trns = bytes(tp)
        d = png(W, H, ctype, depth, pix, plte=plte, trns=trns, **kw)
        model = png_model(W, H, ctype, depth, pix, plte, tk, tp)
