def lzw(indices, mcs):
    clear, eoi = 1 << mcs, (1 << mcs) + 1
    out, acc, nacc = bytearray(), 0, 0
    size = mcs + 1

    def emit(c):
        nonlocal acc, nacc
        acc |= c << nacc
        nacc += size
        while nacc >= 8:
            out.append(acc & 255)
            acc >>= 8
            nacc -= 8

    table = {(i,): i for i in range(clear)}
    nxt = eoi + 1
    emit(clear)
    cur = ()
    for v in indices:
        t = cur + (v,)
        if t in table:
            cur = t
            continue
        emit(table[cur])
        if nxt < 4096:
            table[t] = nxt
            nxt += 1
            if nxt > (1 << size) and size < 12:
                size += 1
        else:
            emit(clear)
            table = {(i,): i for i in range(clear)}
            nxt, size = eoi + 1, mcs + 1
        cur = (v,)
    if cur:
        emit(table[cur])
    emit(eoi)
    if nacc:
        out.append(acc & 255)
    return bytes(out)


def subblocks(data):
    out = bytearray()
    for i in range(0, len(data), 255):
        out += bytes([len(data[i:i + 255])]) + data[i:i + 255]
    return bytes(out) + b"\0"


def gif(w, h, gpal, frames, loops=None, version=b"89a"):
    """frames: dicts with x y w h idx (row-major indices) and optional
    pal, trans, dispose, delay, interlace."""
    def palbytes(p):
        n = 2
        while n < len(p):
            n *= 2
        p = list(p) + [(0, 0, 0)] * (n - len(p))
        return bytes(c for rgb in p for c in rgb), n.bit_length() - 2

    out = b"GIF" + version + struct.pack("<HH", w, h)
    if gpal:
        pb, sz = palbytes(gpal)
        out += bytes([0x80 | 0x70 | sz, 0, 0]) + pb
    else:
        out += bytes([0, 0, 0])
    if loops is not None:
        out += b"\x21\xff\x0bNETSCAPE2.0\x03\x01" + struct.pack("<H", loops) + b"\0"
    out += b"\x21\xfe" + subblocks(b"zedec test") # a comment
    for f in frames:
        tr = f.get("trans")
        packed = (f.get("dispose", 0) << 2) | (1 if tr is not None else 0)
        out += b"\x21\xf9\x04" + bytes([packed]) + struct.pack("<H", f.get("delay", 0)) + bytes([tr or 0, 0])
        lp = f.get("pal")
        flags = 0
        pb = b""
        if lp:
            pb, sz = palbytes(lp)
            flags |= 0x80 | sz
        if f.get("interlace"):
            flags |= 0x40
        out += b"\x2c" + struct.pack("<HHHH", f["x"], f["y"], f["w"], f["h"]) + bytes([flags]) + pb
        idx = f["idx"]
        if f.get("interlace"):
            rows = [idx[r * f["w"]:(r + 1) * f["w"]] for r in range(f["h"])]
            order = list(range(0, f["h"], 8)) + list(range(4, f["h"], 8)) + list(range(2, f["h"], 4)) + \
                list(range(1, f["h"], 2))
            idx = [v for r in order for v in rows[r]]
        npal = len(lp or gpal)
        mcs = max(2, (npal - 1).bit_length())
        out += bytes([mcs]) + subblocks(lzw(idx, mcs))
    return out + b"\x3b"


def gif_model(w, h, gpal, frames):
    canvas = [0] * (w * h)
    shots, prev, saved = [], None, None
    for f in frames:
        if prev is not None:
            if prev.get("dispose", 0) == 2 or (prev.get("dispose", 0) == 3 and saved is None):
                for y in range(prev["y"], min(prev["y"] + prev["h"], h)):
                    for x in range(prev["x"], min(prev["x"] + prev["w"], w)):
                        canvas[y * w + x] = 0
            elif prev.get("dispose", 0) == 3:
                canvas = list(saved)
        saved = list(canvas) if f.get("dispose", 0) == 3 else None
        pal = f.get("pal") or gpal
        for j, v in enumerate(f["idx"]):
            x, y = f["x"] + j % f["w"], f["y"] + j // f["w"]
            if v != f.get("trans") and x < w and y < h:
                canvas[y * w + x] = argb(255, *pal[v]) if v < len(pal) else 0xFF000000
        shots.append((list(canvas), f.get("delay", 0)))
        prev = f
    return shots


