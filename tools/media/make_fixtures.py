def y4m_frames(w, h, n, cs):
    """Planes per frame for colour space cs (420, 422, 444, mono)."""
    frames = []
    for k in range(n):
        Y = bytes(16 + ((x * 3 + y * 2 + k * 20) % 220) for y in range(h) for x in range(w))
        cw, ch = {"420": ((w + 1) // 2, (h + 1) // 2), "422": ((w + 1) // 2, h), "444": (w, h),
                  "mono": (0, 0)}[cs]
        U = bytes(16 + ((x * 11 + k * 30) % 225) for y in range(ch) for x in range(cw))
        V = bytes(16 + ((y * 13 + 100 + k * 7) % 225) for y in range(ch) for x in range(cw))
        frames.append((Y, U, V, cw, ch))
    return frames


def bt601(Y, U, V):
    c, d, e = Y - 16, U - 128, V - 128
    cl = lambda v: 0 if v < 0 else 255 if v > 255 else v
    return (cl((298 * c + 409 * e + 128) >> 8), cl((298 * c - 100 * d - 208 * e + 128) >> 8),
            cl((298 * c + 516 * d + 128) >> 8))


def y4m(w, h, cs, frames, fps=(30000, 1001), tag=None):
    tags = {"420": "C420jpeg", "422": "C422", "444": "C444", "mono": "Cmono"}
    out = b"YUV4MPEG2 W%d H%d F%d:%d Ip A1:1 %s XYSCSS=%s\n" % (w, h, fps[0], fps[1],
                                                               (tag or tags[cs]).encode(), b"420JPEG")
    model = []
    for Y, U, V, cw, ch in frames:
        out += b"FRAME\n" + Y + U + V
        fx = (w + cw - 1) // cw if cw else 1
        fy = (h + ch - 1) // ch if ch else 1
        px = []
        for y in range(h):
            for x in range(w):
                if cs == "mono":
                    u = v = 128
                else:
                    u, v = U[(y // fy) * cw + x // fx], V[(y // fy) * cw + x // fx]
                px.append(argb(255, *bt601(Y[y * w + x], u, v)))
        model.append(px)
    return out, model


def riff_chunk(fcc, data):
    return fcc + struct.pack("<I", len(data)) + data + (b"\0" if len(data) & 1 else b"")


def riff_list(kind, data):
    return riff_chunk(b"LIST", kind + data)


def avi(w, h, frames, fourcc=b"MJPG", rate=(25, 1), idx=True, junk_between=False):
    us = 1000000 * rate[1] // rate[0]
    avih = struct.pack("<IIIIIIIIII", us, 0, 0, 0x10, len(frames), 0, 1, 0, w, h) + bytes(16)
    strh = b"vids" + fourcc + struct.pack("<IHHIIIIIIIIhhhh", 0, 0, 0, 0, rate[1], rate[0], 0, len(frames), 0,
                                          0xFFFFFFFF, 0, 0, 0, w, h)
    bih = struct.pack("<IiiHH4sIiiII", 40, w, h, 1, 24, fourcc, w * h * 3, 0, 0, 0, 0)
    hdrl = riff_list(b"hdrl", riff_chunk(b"avih", avih) + riff_list(b"strl", riff_chunk(b"strh", strh) +
                                                                     riff_chunk(b"strf", bih)))
    movi, index, off = b"", b"", 4
    for k, f in enumerate(frames):
        if junk_between and k == 1:
            j = riff_chunk(b"JUNK", b"pad!")
            movi += j
            off += len(j)
        c = riff_chunk(b"00dc", f)
        index += b"00dc" + struct.pack("<III", 0x10, off, len(f))
        movi += c
        off += len(c)
    body = b"AVI " + hdrl + riff_list(b"movi", movi)
    if idx:
        body += riff_chunk(b"idx1", index)
    return b"RIFF" + struct.pack("<I", len(body)) + body


def box(t, data):
    return struct.pack(">I", 8 + len(data)) + t + data


def fullbox(t, v, flags, data):
    return box(t, struct.pack(">I", (v << 24) | flags) + data)


def mp4(w, h, samples, durations, timescale, entry, extra=b"", brand=b"isom", stsc_chunks=None):
    """One video track. entry: the sample entry fourcc (b'jpeg', b'avc1', ...)."""
    mdat_payload = b"".join(samples)
    ftyp = box(b"ftyp", brand + struct.pack(">I", 0x200) + brand + b"mp41")
    # chunk layout: samples grouped per stsc_chunks (list of counts)
    groups = stsc_chunks or [len(samples)]
    vse = bytes(6) + struct.pack(">H", 1) + bytes(16) + struct.pack(">HHIIIH", w, h, 0x480000, 0x480000, 0, 1)
    vse += bytes(32) + struct.pack(">Hh", 24, -1) + extra
    stsd = fullbox(b"stsd", 0, 0, struct.pack(">I", 1) + box(entry, vse))
    runs = []
    for dur in durations:
        if runs and runs[-1][1] == dur:
            runs[-1][0] += 1
        else:
            runs.append([1, dur])
    stts = fullbox(b"stts", 0, 0, struct.pack(">I", len(runs)) + b"".join(struct.pack(">II", c, d) for c, d in runs))
    stsc = fullbox(b"stsc", 0, 0, struct.pack(">I", len(groups)) +
                   b"".join(struct.pack(">III", i + 1, g, 1) for i, g in enumerate(groups)))
    stsz = fullbox(b"stsz", 0, 0, struct.pack(">II", 0, len(samples)) +
                   b"".join(struct.pack(">I", len(s)) for s in samples))

    def build(base):
        offs, pos, k = [], base, 0
        for g in groups:
            offs.append(pos)
            for _ in range(g):
                pos += len(samples[k])
                k += 1
        stco = fullbox(b"stco", 0, 0, struct.pack(">I", len(offs)) + b"".join(struct.pack(">I", o) for o in offs))
        stbl = box(b"stbl", stsd + stts + stsc + stsz + stco)
        dinf = box(b"dinf", fullbox(b"dref", 0, 0, struct.pack(">I", 1) + fullbox(b"url ", 0, 1, b"")))
        minf = box(b"minf", fullbox(b"vmhd", 0, 1, bytes(8)) + dinf + stbl)
        hdlr = fullbox(b"hdlr", 0, 0, bytes(4) + b"vide" + bytes(12) + b"video\0")
        mdhd = fullbox(b"mdhd", 0, 0, struct.pack(">IIIIHH", 0, 0, timescale, sum(durations), 0x55c4, 0))
        tkhd = fullbox(b"tkhd", 0, 3, struct.pack(">IIIII", 0, 0, 1, 0, sum(durations)) + bytes(8) +
                       struct.pack(">hhhH", 0, 0, 0, 0) + struct.pack(">9I", 0x10000, 0, 0, 0, 0x10000, 0, 0, 0,
                                                                     0x40000000) + struct.pack(">II", w << 16, h << 16))
        trak = box(b"trak", tkhd + box(b"mdia", mdhd + hdlr + minf))
        mvhd = fullbox(b"mvhd", 0, 0, struct.pack(">IIII", 0, 0, timescale, sum(durations)) +
                       struct.pack(">IH", 0x10000, 0x100) + bytes(10) +
                       struct.pack(">9I", 0x10000, 0, 0, 0, 0x10000, 0, 0, 0, 0x40000000) + bytes(24) +
                       struct.pack(">I", 2))
        return box(b"moov", mvhd + trak)

    # mdat first, then moov (offsets known)
    mdat = box(b"mdat", mdat_payload)
    moov = build(len(ftyp) + 8)
    return ftyp + mdat + moov


def ffprobe_ok(name, data, ext):
    if not HAVE_FFMPEG:
        return
    with tempfile.NamedTemporaryFile(suffix=ext, delete=False) as f:
        f.write(data)
        path = f.name
    try:
        r = subprocess.run(["ffprobe", "-v", "error", "-count_frames", "-select_streams", "v:0", "-show_entries",
                            "stream=codec_name,width,height,nb_read_frames", "-of", "csv=p=0", path],
                           capture_output=True, text=True)
        if r.returncode != 0 or not r.stdout.strip():
            sys.exit("%s: ffprobe rejects the container: %s" % (name, r.stderr.strip()))
        print("  ffprobe %s: %s" % (name, r.stdout.strip()))
    finally:
        os.unlink(path)


def ffmpeg_make(args, ext):
    with tempfile.TemporaryDirectory() as t:
        out = os.path.join(t, "o" + ext)
        subprocess.run(["ffmpeg", "-v", "error", "-y"] + args + [out], check=True)
        return open(out, "rb").read()


