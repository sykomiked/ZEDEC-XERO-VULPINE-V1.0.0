def qoi_encode(w, h, px, channels):
    out = bytearray(b"qoif" + struct.pack(">II", w, h) + bytes([channels, 0]))
    index = [(0, 0, 0, 0)] * 64
    prev, run = (0, 0, 0, 255), 0
    for i, p in enumerate(px):
        if p == prev:
            run += 1
            if run == 62 or i == len(px) - 1:
                out.append(0xC0 | (run - 1))
                run = 0
            continue
        if run:
            out.append(0xC0 | (run - 1))
            run = 0
        r, g, b, a = p
        h_ = (r * 3 + g * 5 + b * 7 + a * 11) % 64
        if index[h_] == p:
            out.append(h_)
        else:
            index[h_] = p
            if a == prev[3]:
                dr, dg, db = (r - prev[0] + 128) % 256 - 128, (g - prev[1] + 128) % 256 - 128, (
                    b - prev[2] + 128) % 256 - 128
                drg, dbg = dr - dg, db - dg
                if -2 <= dr <= 1 and -2 <= dg <= 1 and -2 <= db <= 1:
                    out.append(0x40 | (dr + 2) << 4 | (dg + 2) << 2 | (db + 2))
                elif -32 <= dg <= 31 and -8 <= drg <= 7 and -8 <= dbg <= 7:
                    out += bytes([0x80 | (dg + 32), (drg + 8) << 4 | (dbg + 8)])
                else:
                    out += bytes([0xFE, r, g, b])
            else:
                out += bytes([0xFF, r, g, b, a])
        prev = p
    return bytes(out + b"\0" * 7 + b"\1")


