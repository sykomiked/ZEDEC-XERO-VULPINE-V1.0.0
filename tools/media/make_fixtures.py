def tga(w, h, itype, bpp, data, desc=0, cmap=None, cmbits=24, idfield=b"ZX"):
    cm = b""
    if cmap is not None:
        cm = cmap
    hdr = struct.pack("<BBBHHBHHHHBB", len(idfield), 1 if cmap is not None else 0, itype, 0,
                      (len(cm) // ((cmbits + 7) // 8)) if cmap is not None else 0,
                      cmbits if cmap is not None else 0, 0, 0, w, h, bpp, desc)
    return hdr + idfield + cm + data


def tga_rle(pixels, bpp_bytes):
    """pixels: list of byte strings; greedy runs, raw packets otherwise."""
    out, i = bytearray(), 0
    while i < len(pixels):
        j = i
        while j + 1 < len(pixels) and pixels[j + 1] == pixels[i] and j - i < 127:
            j += 1
        if j > i:
            out += bytes([0x80 | (j - i)]) + pixels[i]
            i = j + 1
            continue
        j = i
        while j + 1 < len(pixels) and pixels[j + 1] != pixels[j] and j - i < 127:
            j += 1
        out += bytes([j - i]) + b"".join(pixels[i:j + 1])
        i = j + 1
    return bytes(out)


