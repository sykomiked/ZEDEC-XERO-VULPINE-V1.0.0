def bmp(w, h, bpp, rows_bytes, pal=None, comp=0, masks=None, dib=40, top=False, core=False):
    """rows_bytes: the pixel array exactly as stored (already padded / RLE)."""
    palb = b""
    if pal:
        palb = b"".join(bytes((b, g, r)) + (b"" if core else b"\0") for (r, g, b) in pal)
    if core:
        hdr = struct.pack("<IHHHH", 12, w, h, 1, bpp)
    else:
        hh = -h if top else h
        hdr = struct.pack("<IiiHHIIiiII", dib, w, hh, 1, bpp, comp, len(rows_bytes), 2835, 2835,
                          len(pal) if pal else 0, 0)
        if dib >= 52:
            m = list(masks or [0, 0, 0, 0]) + [0]
            hdr += struct.pack("<III", *m[:3])
            if dib >= 56:
                hdr += struct.pack("<I", m[3])
            hdr += bytes(dib - len(hdr))
        elif masks:
            hdr += b"".join(struct.pack("<I", m) for m in masks)
    off = 14 + len(hdr) + len(palb)
    return b"BM" + struct.pack("<IHHI", off + len(rows_bytes), 0, 0, off) + hdr + palb + rows_bytes


def pad4(b):
    return b + bytes((-len(b)) % 4)


