def lcg_text(n, seed):
    words = [b"zedec ", b"vulpine ", b"kernel ", b"vector ", b"the ", b"of ", b"\n", b"0123456789",
             b"inflate ", b"\x00\x00\x00\x00", b"\xff"]
    r, out = Lcg(seed), bytearray()
    while len(out) < n:
        v = r.next()
        if v % 17 == 0:
            out += bytes([r.next() & 255])
        else:
            out += words[v % len(words)]
    return bytes(out[:n])


def bitw():
    st = {"acc": 0, "n": 0, "out": bytearray()}

    def put(v, n):
        st["acc"] |= v << st["n"]
        st["n"] += n
        while st["n"] >= 8:
            st["out"].append(st["acc"] & 255)
            st["acc"] >>= 8
            st["n"] -= 8

    def huff(code, n):  # Huffman codes go MSB first
        put(int(format(code, "0%db" % n)[::-1], 2), n)

    def done():
        if st["n"]:
            st["out"].append(st["acc"] & 255)
        return bytes(st["out"])
    return put, huff, done


def fixed_sym(huff, s):
    if s < 144:
        huff(0x30 + s, 8)
    elif s < 256:
        huff(0x190 + s - 144, 9)
    elif s < 280:
        huff(s - 256, 7)
    else:
        huff(0xC0 + s - 280, 8)


