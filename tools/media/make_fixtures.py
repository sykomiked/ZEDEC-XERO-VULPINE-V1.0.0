# C output helpers


def c_bytes(name, data):
    lines = []
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join("%d" % b for b in data[i:i + 24]) + ",")
    return "static const uint8_t %s[%d] = {\n%s\n};\n" % (name, max(len(data), 1), "\n".join(lines) or "    0")


def c_u32(name, vals):
    lines = []
    for i in range(0, len(vals), 8):
        lines.append("    " + ", ".join("0x%08xu" % v for v in vals[i:i + 8]) + ",")
    return "static const uint32_t %s[%d] = {\n%s\n};\n" % (name, max(len(vals), 1), "\n".join(lines) or "    0")


class Inc:
    """One .inc file: arrays plus a table of fixtures."""

    def __init__(self, path, table, head):
        self.path, self.table, self.head = path, table, head
        self.body, self.rows = [], []

    def add(self, name, data, w=0, h=0, ref=None, tol=0, rc=0, fmt=0, flags=0):
        cname = "fx_" + name
        self.body.append(c_bytes(cname, data))
        rname = "0"
        if ref is not None:
            rname = cname + "_ref"
            self.body.append(c_u32(rname, ref))
        self.rows.append('    {"%s", %s, %d, %d, %d, %s, %d, %d, %d, %d},' %
                         (name, cname, len(data), w, h, rname, tol, rc, fmt, flags))

    def raw(self, text):
        self.body.append(text)

    def write(self):
        with open(self.path, "w") as f:
            f.write("/* Generated by tools/media/make_fixtures.py; do not edit. */\n")
            f.write("/* SPDX-License-Identifier: Apache-2.0 */\n")
            f.write(self.head)
            f.write("\n".join(self.body))
            if self.table:
                f.write("\nstatic const fx_t %s[] = {\n%s\n};\n" % (self.table, "\n".join(self.rows)))
                f.write("#define %s_N %d\n" % (self.table, len(self.rows)))
        print("wrote", os.path.relpath(self.path, ROOT), "(%d table rows)" % len(self.rows) if self.table else "")


# rc values mirror zx_image.h
OK, E_FORMAT, E_UNSUP, E_DATA, E_TRUNC, E_SIZE, E_CHECK = 0, -2, -3, -4, -5, -6, -8
# fmt mirrors zui_img_format_t
F_PNG, F_JPEG, F_GIF, F_BMP, F_PNM, F_QOI, F_TGA = 1, 2, 3, 4, 5, 6, 7
FL_ASCII = 1  # no end marker: a cut inside the last number cannot be seen (IM2)
FL_NOFUZZ = 2  # too large to truncate at every length


def argb(a, r, g, b):
    return (a << 24) | (r << 16) | (g << 8) | b


class Lcg:
    def __init__(self, seed):
        self.x = seed & 0xFFFFFFFF

    def next(self):
        self.x = (self.x * 1103515245 + 12345) & 0xFFFFFFFF
        return self.x >> 16


def picture(w, h, seed=1):
    """RGBA test picture: gradients, a hard edge, a few noisy pixels."""
    r = Lcg(seed)
    px = []
    for y in range(h):
        for x in range(w):
            R = (x * 255) // max(w - 1, 1)
            G = (y * 255) // max(h - 1, 1)
            B = ((x + y) * 7) & 255
            if (x // 4 + y // 3) % 5 == 0:
                R, G, B = 255 - R, 40, 200
            A = 255 if x % 7 else (x * 37 + y * 11) & 255
            if r.next() % 13 == 0:
                R, G, B = r.next() & 255, r.next() & 255, r.next() & 255
            px.append((R, G, B, A))
    return px


def pil_rgba(im):
    b = im.convert("RGBA").tobytes()
    return [argb(b[i + 3], b[i], b[i + 1], b[i + 2]) for i in range(0, len(b), 4)]


def check(name, model, theirs):
    if model != theirs:
        bad = next(i for i in range(len(model)) if model[i] != theirs[i])
        sys.exit("%s: model and Pillow disagree at pixel %d: %08x vs %08x" % (name, bad, model[bad], theirs[bad]))


