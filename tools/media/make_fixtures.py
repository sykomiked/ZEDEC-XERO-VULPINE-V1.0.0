"""Build the test fixtures for kernel/src/media (zx_inflate, zx_image,
zui_video) as C byte arrays under kernel/src/media/test/.

Lossless formats are written by small encoders in this file, so every
feature the decoders claim (each PNG colour type and depth, every filter,
Adam7, BMP RLE, GIF disposal ...) is exercised on purpose, and the expected
pixels come from this file's own model of each format. Where Pillow can read
a fixture, the model is checked against Pillow before anything is written,
so the reference does not just restate the decoder. JPEG fixtures are made
by Pillow (libjpeg-turbo) and their reference pixels are Pillow's decode.
Video fixtures are hand-muxed (Y4M, AVI, MOV/MP4); when ffmpeg is on PATH,
ffprobe checks each container and ffmpeg adds real MJPEG and H.264 files.

    python3 tools/media/make_fixtures.py        (from the repository root)

Requires Pillow. Deterministic: the same Pillow/ffmpeg give the same bytes.
"""
