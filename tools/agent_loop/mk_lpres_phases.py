#!/usr/bin/env python3
# mk_lpres_phases.py — generate the lpres phase ladder up to 144. The
# four foundation values are frozen; the gateway is the port; the phases
# above follow the Fibonacci milestones (5, 8, 13, 21, 34, 55, 89, 144)
# with the intermediate phases available. Because the operators are
# min/max on a rank table, the whole ladder is data: one enum and one
# rank array, generated, never hand-maintained.
# Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC
# SPDX-License-Identifier: Apache-2.0
"""usage: mk_lpres_phases.py [--max 144] [--out kernel/src/lpres/lpres_phases.h]"""
import argparse
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "../.."))

# the frozen foundation and the gateway
FOUNDATION = [
    ("LPRES_STATE_NEITHER", 0, "unknown, unattested, pending"),
    ("LPRES_STATE_TRUE", 1, "attested present and valid"),
    ("LPRES_STATE_FALSE", 2, "attested absent or invalid"),
    ("LPRES_STATE_BOTH", 3, "contradictory: both true and false evidence"),
]
GATEWAY = ("LPRES_STATE_GATEWAY", 4, "the fifth: the expansion port")

# the Fibonacci milestones the phases organise around
def fibs_upto(n):
    a, b, out = 1, 2, []
    while a <= n:
        out.append(a)
        a, b = b, a + b
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--max", type=int, default=144)
    ap.add_argument("--out", default="kernel/src/lpres/lpres_phases.h")
    args = ap.parse_args()
    out = os.path.join(ROOT, args.out)
    milestones = set(fibs_upto(args.max))

    lines = [
        "/* lpres_phases.h — the phase ladder, GENERATED by",
        " * tools/agent_loop/mk_lpres_phases.py. Do not edit by hand.",
        " *",
        " * The four foundation values (0..3) are frozen. The gateway (4) is",
        " * the expansion port. The phases above follow the Fibonacci",
        " * milestones; the operators are min/max on the rank table, so a",
        " * phase is data and every table, loop and test iterates",
        " * LPRES_STATE_COUNT. See docs/agent_loop/LP_EXTENSION.md. */",
        "#ifndef ZXV_LPRES_PHASES_H",
        "#define ZXV_LPRES_PHASES_H",
        "",
        "#include <stdint.h>",
        "",
        "typedef enum {",
    ]
    for name, val, doc in FOUNDATION:
        lines.append("    %s = %d,  /* %s */" % (name, val, doc))
    lines.append("    %s = %d,  /* %s */" % GATEWAY)
    for p in range(5, args.max + 1):
        tag = "  /* the Fibonacci milestone F */" if p in milestones else ""
        lines.append("    LPRES_STATE_PHASE_%d = %d,%s" % (p, p, tag))
    lines.append("    LPRES_STATE_COUNT = %d" % (args.max + 1))
    lines += [
        "} lpres_state_t;",
        "",
        "/* The chain rank: FALSE is the bottom (the meet's dominator), TRUE",
        " * the top (the join's identity), NEITHER below BOTH. Every phase",
        " * above the gateway takes the next rank, so the operators extend",
        " * with no code change and no mix of non-TRUE values can ever yield",
        " * TRUE (the never-authorise guard). */",
        "static const uint8_t lpres_rank[LPRES_STATE_COUNT] = {",
        "    [LPRES_STATE_FALSE]   = 0,",
        "    [LPRES_STATE_NEITHER] = 1,",
        "    [LPRES_STATE_BOTH]    = 2,",
        "    [LPRES_STATE_TRUE]    = 3,",
        "    [LPRES_STATE_GATEWAY] = 4,",
    ]
    for p in range(5, args.max + 1):
        lines.append("    [LPRES_STATE_PHASE_%d] = %d," % (p, p))
    lines += [
        "};",
        "",
        "#endif /* ZXV_LPRES_PHASES_H */",
    ]
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("generated %d phases (0..%d) to %s" % (args.max + 1, args.max, args.out))
    print("  the frozen four: 0..3 | the gateway: 4 | the phases: 5..%d" % args.max)
    print("  the Fibonacci milestones present: %s" % sorted(m for m in milestones if m <= args.max))
    return 0


if __name__ == "__main__":
    sys.exit(main())