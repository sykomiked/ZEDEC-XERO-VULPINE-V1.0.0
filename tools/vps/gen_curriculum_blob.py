"""gen_curriculum_blob.py — the deterministic curriculum CAR as a C array so
the Vinea host can build, announce and serve its shard files (vna_file).

usage: gen_curriculum_blob.py <car_path> <out.h>
"""
import pathlib
import sys


def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write("usage: gen_curriculum_blob.py <car_path> <out.h>\n")
        return 2
    car = pathlib.Path(sys.argv[1]).read_bytes()
    out = pathlib.Path(sys.argv[2])
    out.parent.mkdir(parents=True, exist_ok=True)
    w = out.open("w")
    w.write("/* generated by tools/vps/gen_curriculum_blob.py — do not edit */\n")
    w.write("#ifndef ZXV_CURRICULUM_BLOB_H\n#define ZXV_CURRICULUM_BLOB_H\n")
    w.write("#include <stdint.h>\n\n")
    w.write(f"#define CUR_CAR_LEN {len(car)}u\n")
    w.write("static const uint8_t cur_car[CUR_CAR_LEN] = {\n")
    for i in range(0, len(car), 16):
        w.write("    " + ",".join(str(b) for b in car[i : i + 16]) + ",\n")
    w.write("};\n\n#endif /* ZXV_CURRICULUM_BLOB_H */\n")
    w.close()
    return 0


if __name__ == "__main__":
    sys.exit(main())
