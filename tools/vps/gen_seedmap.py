"""gen_seedmap.py — the seed static-lease map as a C table for sn_link.c.

Providers that assign fixed addresses (Contabo among them) answer no DHCP
discover, so a seed must recognise itself by NIC MAC and configure
statically. build_system/vps_seeds.conf lists `mac ip gateway cidr` per
seed; this bakes it into the kernel like the doorway blobs.

Usage: gen_seedmap.py <conf> <out.h>
"""
import sys
import os

HDR = """/* generated by tools/vps/gen_seedmap.py — do not edit */
#ifndef ZXV_SEEDMAP_H
#define ZXV_SEEDMAP_H
#include <stdint.h>
typedef struct { uint8_t mac[6]; uint8_t ip[4]; uint8_t gw[4]; uint8_t mask[4]; } zxv_seedmap_t;
"""

FOOT = "#endif /* ZXV_SEEDMAP_H */\n"


def dotted(s):
    parts = s.split(".")
    if len(parts) != 4:
        raise ValueError("bad address " + s)
    return [int(p) for p in parts]


def cidr_mask(cidr):
    n = int(cidr)
    if not 0 <= n <= 32:
        raise ValueError("bad cidr " + cidr)
    v = (0xFFFFFFFF << (32 - n)) & 0xFFFFFFFF if n else 0
    return [(v >> 24) & 255, (v >> 16) & 255, (v >> 8) & 255, v & 255]


def main():
    if len(sys.argv) != 3:
        sys.stderr.write("usage: gen_seedmap.py <conf> <out.h>\n")
        return 2
    conf, out = sys.argv[1], sys.argv[2]
    rows = []
    if os.path.exists(conf):
        for ln, line in enumerate(open(conf), 1):
            line = line.split("#", 1)[0].split()
            if not line:
                continue
            if len(line) != 4:
                sys.stderr.write("%s:%d: want 'mac ip gateway cidr'\n" % (conf, ln))
                return 1
            mac = [int(b, 16) for b in line[0].split(":")]
            if len(mac) != 6 or any(b > 255 for b in mac):
                sys.stderr.write("%s:%d: bad mac\n" % (conf, ln))
                return 1
            try:
                ip, gw, mask = dotted(line[1]), dotted(line[2]), cidr_mask(line[3])
            except ValueError as e:
                sys.stderr.write("%s:%d: %s\n" % (conf, ln, e))
                return 1
            rows.append((mac, ip, gw, mask))
    parts = [HDR, "#define ZXV_SEEDMAP_N %du\n" % len(rows)]
    if rows:
        parts.append("static const zxv_seedmap_t zxv_seedmap[ZXV_SEEDMAP_N] = {\n")
        for mac, ip, gw, mask in rows:
            fmt = lambda a: ",".join(str(b) for b in a)
            parts.append("    {{%s},{%s},{%s},{%s}},\n" % (fmt(mac), fmt(ip), fmt(gw), fmt(mask)))
        parts.append("};\n")
    parts.append(FOOT)
    body = "".join(parts)
    # Rewritten only when the bytes change, so make re-runs do not dirty it.
    if os.path.exists(out) and open(out).read() == body:
        return 0
    with open(out, "w") as f:
        f.write(body)
    return 0


if __name__ == "__main__":
    sys.exit(main())
