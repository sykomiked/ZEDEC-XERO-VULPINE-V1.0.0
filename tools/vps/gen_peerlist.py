"""gen_peerlist.py — the armada's peer list as a C table for hw_models.c.

THE GATE THIS CLOSES. kernel/arch/x86_64/kernel_main_x86_64.c brings the
link up only when `models.npeer` is non-zero -- the peer seeds read from the
core disc's /ZXV/UPSTREAM.CID. On a provider whose disk controller the
image's mount path does not match (Contabo presents virtio-scsi), that read
yields nothing, npeer stays 0, and the NIC is never asked for a lease: the
OS is silent, the ports never open, and nothing is wrong with the image.

This bakes the same list into the kernel, so the gate opens whether or not
the disc was read. build_system/vps_seeds.conf lists `mac ip gateway cidr`
per seed; the VNA port is 8724. The six-byte form is exactly what
peer_addr() emits: four IP octets, then the port big-endian.

Usage: gen_peerlist.py <conf> <out.h> [port]
"""
import sys

HDR = """/* generated by tools/vps/gen_peerlist.py — do not edit */
#ifndef ZXV_PEERLIST_H
#define ZXV_PEERLIST_H
#include <stdint.h>
/* The nine seeds' VNA addresses, baked so the network bring-up does not
 * depend on the core disc being readable. Same six-byte form as
 * peer_addr(): four IP octets, then the port big-endian. */
#define ZXV_PEERLIST_N %du
static const uint8_t zxv_peerlist[ZXV_PEERLIST_N][6] = {
"""


def main():
    if len(sys.argv) < 3:
        print(__doc__)
        return 1
    conf, out = sys.argv[1], sys.argv[2]
    port = int(sys.argv[3]) if len(sys.argv) > 3 else 8724

    rows = []
    seen = set()
    with open(conf) as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) < 2:
                continue
            ip = parts[1]
            octets = ip.split(".")
            if len(octets) != 4:
                continue
            if ip in seen:
                continue
            seen.add(ip)
            o = [int(x) for x in octets]
            if any(x < 0 or x > 255 for x in o):
                continue
            rows.append((ip, o + [port >> 8, port & 0xFF]))

    with open(out, "w") as f:
        f.write(HDR % len(rows))
        for ip, b in rows:
            f.write("    {%s},  /* %s */\n"
                    % (",".join(str(x) for x in b), ip))
        f.write("};\n#endif /* ZXV_PEERLIST_H */\n")
    print("gen_peerlist: %d peers (port %d) -> %s" % (len(rows), port, out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
