"""gen_theme_tokens.py: write the SwiftUI shells' colour and type tokens from
kernel/src/zui/zui_tokens.h, so Studio (macOS) and the phone kit draw the same
#002911 green and #F2C230 gold as zui, the bare-metal desktop and the boot.

    tools/zui/gen_theme_tokens.py            write the Swift file
    tools/zui/gen_theme_tokens.py --check    exit 1 when the file is stale

zui_tokens.h is the one source. Edit it, then run this script.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HDR = os.path.join(ROOT, "kernel", "src", "zui", "zui_tokens.h")
OUT = os.path.join(ROOT, "macos", "studio", "Sources", "ZXVStudio", "ThemeTokens.swift")

# Swift name <- zui token, in the order they are written.
COLOURS = [
    ("ground", "ZUI_VOID"), ("panel", "ZUI_PANEL"), ("raised", "ZUI_RAISED"),
    ("hairline", "ZUI_HAIRLINE"), ("edge", "ZUI_EDGE"),
    ("engraveHi", "ZUI_ENGRAVE_HI"), ("engraveLo", "ZUI_ENGRAVE_LO"),
    ("text", "ZUI_TEXT"), ("text2", "ZUI_TEXT_2"), ("muted", "ZUI_MUTED"),
    ("faint", "ZUI_FAINT"), ("gold", "ZUI_GOLD"), ("goldHi", "ZUI_GOLD_HI"),
    ("goldGlow", "ZUI_GOLD_GLOW"), ("ok", "ZUI_OK"), ("info", "ZUI_INFO"),
    ("alert", "ZUI_ALERT"),
]
NUMBERS = [
    ("s1", "ZUI_S1"), ("s2", "ZUI_S2"), ("s3", "ZUI_S3"), ("s4", "ZUI_S4"),
    ("s5", "ZUI_S5"), ("s6", "ZUI_S6"), ("s7", "ZUI_S7"),
    ("radiusControl", "ZUI_R_CONTROL"), ("radiusPanel", "ZUI_R_PANEL"),
    ("caption", "ZUI_T_CAPTION"), ("label", "ZUI_T_LABEL"), ("body", "ZUI_T_BODY"),
    ("title", "ZUI_T_TITLE"), ("headline", "ZUI_T_HEADLINE"), ("display", "ZUI_T_DISPLAY"),
    ("motionMs", "ZUI_MOTION_MS"),
]


def read_tokens(path):
    vals = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            m = re.match(r"\s*#define\s+(ZUI_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+)u?\b", line)
            if m:
                vals[m.group(1)] = int(m.group(2), 0)
    return vals


def render(vals):
    missing = [t for _, t in COLOURS + NUMBERS if t not in vals]
    if missing:
        raise SystemExit("zui_tokens.h lacks: " + ", ".join(missing))
    out = [
        "// GENERATED by tools/zui/gen_theme_tokens.py from kernel/src/zui/zui_tokens.h.",
        "// Do not edit: change zui_tokens.h and run the script.",
        "// Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC",
        "// SPDX-License-Identifier: Apache-2.0",
        "import SwiftUI",
        "",
        "/// The zui design tokens, the same values every ZXV screen draws with.",
        "enum ZUIToken {",
    ]
    for name, tok in COLOURS:
        v = vals[tok]
        out.append("    static let %s = Color(red: 0x%02X / 255, green: 0x%02X / 255, blue: 0x%02X / 255) // %s #%06X"
                   % (name, (v >> 16) & 255, (v >> 8) & 255, v & 255, tok, v))
    out.append("")
    for name, tok in NUMBERS:
        out.append("    static let %s: CGFloat = %d // %s" % (name, vals[tok], tok))
    out.append("}")
    return "\n".join(out) + "\n"


def main():
    text = render(read_tokens(HDR))
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        try:
            with open(OUT, encoding="utf-8") as f:
                cur = f.read()
        except OSError:
            cur = ""
        if cur != text:
            print("[FAIL] %s is stale: run tools/zui/gen_theme_tokens.py" % os.path.relpath(OUT, ROOT))
            return 1
        print("[PASS] Studio theme tokens match zui_tokens.h")
        return 0
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote", os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
