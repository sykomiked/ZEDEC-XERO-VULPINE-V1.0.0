"""Generate zui_shape's Brahmic tables (zui_shape.h S7, S8) from the UCD.

    python3 tools/zui/gen_indic.py [--ucd DIR]

Reads IndicSyllabicCategory.txt and IndicPositionalCategory.txt (Unicode
15.1, downloaded from unicode.org unless --ucd names a folder holding them)
and Python's unicodedata (decompositions; it must be Unicode 15.1 too), and
writes kernel/src/zui/zui_shape_indic.inc:

  INDIC_RANGES  code point ranges -> zui_indic_cat_t, for the scripts whose
                vowels are drawn before their consonant: the nine Indic
                scripts of India, Sinhala, Myanmar and Khmer
  INDIC_SPLIT   two-part vowels -> the part drawn before the consonant and the
                part after (the full canonical decomposition; for Khmer, whose split
                vowels do not decompose, the pre-base E U+17C1 and the vowel)

The UCD is under the Unicode License v3.
"""
import argparse
import os
import sys
import unicodedata
import urllib.request

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
OUT = os.path.join(ROOT, "kernel", "src", "zui", "zui_shape_indic.inc")
UCD = "15.1.0"
BLOCKS = [(0x0900, 0x0DFF), (0x1000, 0x109F), (0x1780, 0x17FF)]
CAT = {
    "Consonant": "C", "Consonant_Dead": "C", "Consonant_With_Stacker": "C",
    "Consonant_Head_Letter": "C", "Consonant_Prefixed": "C",
    "Vowel_Independent": "V", "Nukta": "N", "Virama": "H", "Invisible_Stacker": "H",
    "Vowel_Dependent": "M", "Pure_Killer": "M", "Consonant_Medial": "M",
    "Consonant_Subjoined": "M", "Consonant_Succeeding_Repha": "M",
    "Bindu": "VM", "Visarga": "VM", "Tone_Mark": "VM", "Syllable_Modifier": "VM",
    "Gemination_Mark": "VM", "Register_Shifter": "VM", "Consonant_Final": "VM",
    "Cantillation_Mark": "A",
}
ENUM = {"C": "ZUI_INDIC_C", "V": "ZUI_INDIC_V", "N": "ZUI_INDIC_N", "H": "ZUI_INDIC_H",
        "M": "ZUI_INDIC_M", "MPRE": "ZUI_INDIC_MPRE", "VM": "ZUI_INDIC_VM", "A": "ZUI_INDIC_A"}


def read(path):
    m = {}
    with open(path, encoding="utf-8") as f:
        for line in f:
            line = line.split("#")[0].strip()
            if not line:
                continue
            r, v = [x.strip() for x in line.split(";")]
            lo, _, hi = r.partition("..")
            for cp in range(int(lo, 16), int(hi or lo, 16) + 1):
                m[cp] = v
    return m


def fetch(ucd, name):
    if ucd:
        return os.path.join(ucd, name)
    cache = os.path.expanduser(f"~/.cache/zxv-ucd-{UCD}")
    os.makedirs(cache, exist_ok=True)
    path = os.path.join(cache, name)
    if not os.path.exists(path):
        url = f"https://www.unicode.org/Public/{UCD}/ucd/{name}"
        print("fetching", url, file=sys.stderr)
        with open(path, "wb") as f:
            f.write(urllib.request.urlopen(url).read())
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ucd")
    a = ap.parse_args()
    if unicodedata.unidata_version != UCD:
        sys.exit(f"Python's unicodedata is {unicodedata.unidata_version}, need {UCD}")
    insc = read(fetch(a.ucd, "IndicSyllabicCategory.txt"))
    inpc = read(fetch(a.ucd, "IndicPositionalCategory.txt"))
    cats, split = {}, []
    for lo, hi in BLOCKS:
        for cp in range(lo, hi + 1):
            c = CAT.get(insc.get(cp, ""))
            if not c:
                continue
            pos = inpc.get(cp, "")
            if c == "M" and pos == "Left":
                c = "MPRE"
            elif c == "M" and "Left" in pos:
                d = [ord(ch) for ch in unicodedata.normalize("NFD", chr(cp))]
                if len(d) >= 2:
                    left, right = d[0], (d[1:] + [0])[:2]
                elif 0x1780 <= cp <= 0x17FF:
                    left, right = 0x17C1, [cp, 0]
                else:  # Myanmar medial ra wraps the consonant: drawn from before it
                    cats[cp] = "MPRE"
                    continue
                split.append((cp, left, right))
            cats[cp] = c
    ranges = []
    for cp in sorted(cats):
        if ranges and ranges[-1][1] == cp - 1 and ranges[-1][2] == cats[cp]:
            ranges[-1][1] = cp
        else:
            ranges.append([cp, cp, cats[cp]])
    o = ["/* Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC */",
         "/* SPDX-License-Identifier: Apache-2.0 */",
         f"/* Generated by tools/zui/gen_indic.py from Unicode {UCD} IndicSyllabicCategory.txt,",
         " * IndicPositionalCategory.txt and UnicodeData.txt (Unicode License v3). Do not edit. */",
         "// clang-format off",
         "static const struct { uint32_t lo, hi; uint8_t cat; } INDIC_RANGES[] = {"]
    for lo, hi, c in ranges:
        o.append(f"    {{0x{lo:04X}u, 0x{hi:04X}u, {ENUM[c]}}},")
    o.append("};")
    o.append("/* a two-part vowel: the part before the consonant, the part after (one or")
    o.append(" * two code points, 0 when one) */")
    o.append("static const struct { uint32_t cp, pre, post[2]; } INDIC_SPLIT[] = {")
    for cp, l, r in split:
        o.append(f"    {{0x{cp:04X}u, 0x{l:04X}u, {{0x{r[0]:04X}u, 0x{r[1]:04X}u}}}},")
    o.append("};")
    o.append("// clang-format on")
    with open(OUT, "w", encoding="utf-8") as f:
        f.write("\n".join(o) + "\n")
    print(f"{len(ranges)} ranges, {len(split)} split vowels")


if __name__ == "__main__":
    main()
