def entry(r, meta, metas):
    cd = meta.get("cardData") or {}
    lic = cd.get("license")
    if lic != "apache-2.0":
        raise SystemExit(f"{r['id']}: card licence is {lic!r}, not apache-2.0")
    files = files_of(meta, r["weights"])
    if not files:
        raise SystemExit(f"{r['id']}: no weight files match {r['weights']} at {meta.get('sha')}")
    bases = []
    for b in base_chain(meta):
        bl = ((metas.get(b) or {}).get("cardData") or {}).get("license")
        bases.append({"model_id": b, "license": bl})
    arch = ((meta.get("config") or {}).get("architectures") or [None])[0]
    return {
        "model_id": r["id"],
        "developer": r["developer"],
        "license": "Apache-2.0",
        "license_checked": {"card": lic, "bases": bases, "mit_base": r["mit_base"]},
        "params": r["params"],
        "capabilities": r["caps"],
        "architecture": arch,
        "engine": r["runtime"],
        "zt_runs_today": arch in ZT_ARCH and r["runtime"].startswith("zt"),
        "zero_float_verified": False,
        "runtime_gated": not (arch in ZT_ARCH and r["runtime"].startswith("zt")),
        "advisory_only": r["advisory"],
        "planning_only": r["planning_only"],
        "placement": "anchor_or_agora",
        "iso_seed": False,
        "revision": meta["sha"],
        "source_url": f"{HUB}/{r['id']}/tree/{meta['sha']}",
        "weight_files": [{"path": f["path"], "size": f["size"], "sha256": f["sha256"],
                          "url": f"{HUB}/{r['id']}/resolve/{meta['sha']}/{f['path']}"}
                         for f in files],
        "source_bytes": sum(f["size"] or 0 for f in files),
        "quant_target": "Q4_K_M" if r["runtime"].startswith("zt") else None,
        "quant_sha256": None,
        "quant_status": "built on the server from the pinned sources" if r["runtime"].startswith("zt")
                        else "not quantised: runs under its own runtime",
        "note": r["note"],
        "data_note": r["data"],
        "verified": True,
    }


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--fetch", action="store_true")
    g.add_argument("--meta")
    ap.add_argument("--out", default=str(OUT))
    ap.add_argument("--save-meta", help="write the fetched metadata here")
    a = ap.parse_args()
    ids = sorted({r["id"] for r in ADMITTED})
    metas = fetch(ids) if a.fetch else json.load(open(a.meta))
    bases = sorted({b for i in ids for b in base_chain(metas[i])} - metas.keys())
    if a.fetch and bases:
        try:
            metas |= fetch(bases)
        except Exception as e:  # a base that is gated or gone is recorded as unknown, not guessed
            print(f"note: some base cards could not be read ({e})", file=sys.stderr)
    if a.save_meta:
        json.dump(metas, open(a.save_meta, "w"))
    models = [entry(r, metas[r["id"]], metas) for r in ADMITTED]
    doc = {
        "schema": "zxv.tiamat.swarm_model_large_manifest/1",
        "generated": "2026-10-15",
        "brand": "Tiamat Productive Agency AI",
        "scope": "Large peers for the Sovereign Anchor and Swarm Agora tiers (docs/spec/GOSSIP_TOPOLOGY.md). "
                 "Not on the disc, not in the first root's weights; called by peers through zxvd.",
        "rules": "Apache-2.0 checkpoints, checked on the card; bases checked on their own cards; "
                 "SafeTensors, GGUF or ONNX only. zero_float_verified is false for every row until "
                 "the integer engine passes parity tests at that exact quantisation.",
        "attribution": "Every model carries its developer and source URL; every creator is credited.",
        "conflicts_for_the_owner": CONFLICTS,
        "models": models,
        "excluded": [{"model_id": i, "reason_kind": k, "reason": why, "replacement": rep}
                     for i, k, why, rep in EXCLUDED],
        "in_the_small_roster": SMALL_ROSTER,
        "small_for_the_small_roster_review": [{"model_id": i, "note": n} for i, n in SMALL_TO_REVIEW],
    }
    pathlib.Path(a.out).write_text(json.dumps(doc, indent=2, ensure_ascii=False) + "\n")
    runs = sum(m["zt_runs_today"] for m in models)
    print(f"{len(models)} large models verified ({runs} on the integer engine's architectures), "
          f"{len(EXCLUDED)} excluded -> {a.out}")


if __name__ == "__main__":
    main()
