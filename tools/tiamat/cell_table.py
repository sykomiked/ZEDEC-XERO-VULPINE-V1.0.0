"""The kernel's model-cell table (kernel/src/chiglet/chg_cells_table.c,
chg_cells.h C1) from tools/tiamat/cell_coords.json.

    python3 tools/tiamat/cell_table.py --write   regenerate the C table
    python3 tools/tiamat/cell_table.py --check   fail if the C table differs

One row per cell, sorted by coordinate, retired cells kept. A cell is
runnable (chg_cells.h C3) when its engine text starts "runs now",
"zt_vision" or "zt_whisper"; every other engine text names a path this
build lacks. The C file is the only output and is never edited by hand.
"""
import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SRC = HERE / "cell_coords.json"
OUT = ROOT / "kernel" / "src" / "chiglet" / "chg_cells_table.c"
RUNNABLE = ("runs now", "zt_vision", "zt_whisper")
PLACEMENT = {"disc": "CHG_CELL_DISC", "disc_gated": "CHG_CELL_DISC_GATED", "server": "CHG_CELL_SERVER",
             "pack_laptop": "CHG_CELL_PACK_LAPTOP", "pack_workstation": "CHG_CELL_PACK_WORKSTATION"}


def cstr(s):
    if any(ord(ch) < 0x20 or ord(ch) > 0x7E or ch in '"\\' for ch in s):
        raise SystemExit(f"cell_table: {s!r} is not plain printable ASCII")
    return f'"{s}"'


def render(doc):
    if doc.get("domain") != "0x60":
        raise SystemExit("cell_table: the domain is not 0x60")
    cells = sorted(doc["cells"], key=lambda e: int(e["coord"], 16))
    lines = [
        "/* Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC */",
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* chg_cells_table.c — generated by tools/tiamat/cell_table.py from",
        " * tools/tiamat/cell_coords.json (chg_cells.h C1). Do not edit. */",
        '#include "chg_cells.h"',
        "",
        "/* clang-format off */",
        "const char *const chg_cell_organs[] = {",
    ]
    lines += [f"    {cstr(o)}," for o in doc["organs"]]
    lines += ["};", f"const uint32_t chg_cell_organs_n = {len(doc['organs'])}u;", "",
              "const chg_cell_t chg_cells[] = {"]
    prev = None
    for e in cells:
        coord = int(e["coord"], 16)
        if coord >> 56 != 0x60 or coord & 0xFFFFFFFF or (coord >> 40) & 0xFFFF != e["place"] \
                or (coord >> 32) & 0xFF != e["item"]:
            raise SystemExit(f"cell_table: {e['name']}: coord does not match place and item")
        if not 1 <= e["place"] <= len(doc["organs"]) or doc["organs"][e["place"] - 1] != e["organ"]:
            raise SystemExit(f"cell_table: {e['name']}: place does not name its organ")
        if coord == prev:
            raise SystemExit(f"cell_table: {e['name']}: coordinate used twice")
        prev = coord
        run = "true" if e["engine"].startswith(RUNNABLE) else "false"
        ret = "true" if e.get("retired") else "false"
        lines += [f"    {{0x{coord:016x}ull, {PLACEMENT[e['placement']]}, {run}, {ret}, {cstr(e['name'])},",
                  f"     {cstr(e['engine'])}}},"]
    lines += ["};", f"const uint32_t chg_cells_n = {len(cells)}u;", "/* clang-format on */", ""]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render(json.loads(SRC.read_text()))
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"cell_table: {OUT.name} differs from {SRC.name} (run --write)", file=sys.stderr)
            raise SystemExit(1)
        print(f"cell_table: {OUT.name} matches {SRC.name}")
        return
    OUT.write_text(text)
    print(f"cell_table: wrote {OUT.name}")


if __name__ == "__main__":
    main()
