"""Embed the agreement text into kernel/src/terms/terms_text.c.

    python3 tools/terms/embed_terms.py VERSION [LANG=FILE ...]

The first LANG is the reference (English) text; every other language points
at it. A LANG written with a trailing '!' (e.g. 'id!=id.txt') is marked
controlling, for markets whose law makes the local-language version govern.
Prints each text's SHA-256, which is the fingerprint the accept screen
records. test_terms checks the embedded bytes still match the files.
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "kernel/src/terms/terms_text.c"


def c_string(data: bytes) -> str:
    lines, cur = [], ""
    for b in data:
        if b == 0x0A:
            cur += "\\n"
            lines.append(cur)
            cur = ""
            continue
        if b in (0x22, 0x5C):
            cur += "\\" + chr(b)
        elif 0x20 <= b < 0x7F and b != 0x3F:   # '?' escaped: no trigraphs
            cur += chr(b)
        else:
            cur += "\\%03o" % b
    if cur:
        lines.append(cur)
    return "\n".join('    "%s"' % s for s in lines)


def main(argv):
    if len(argv) < 3:
        sys.exit(__doc__)
    version, specs = argv[1], argv[2:]
    docs = []
    for spec in specs:
        lang, path = spec.split("=", 1)
        ctl = lang.endswith("!")
        lang = lang.rstrip("!")
        data = Path(path).read_bytes()
        data.decode("utf-8")
        docs.append((lang, ctl, data))
        print(f"{lang}: {hashlib.sha256(data).hexdigest()}  {path}")
    ident = lambda lang: "doc_" + lang.replace("-", "_")
    out = [
        "/* Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC */",
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* terms_text.c: GENERATED by tools/terms/embed_terms.py; do not edit.",
        " * Source: kernel/src/terms/agreement/. */",
        '#include "terms.h"',
        "",
    ]
    for i, (lang, ctl, data) in enumerate(docs):
        ref = "0" if i == 0 else "&" + ident(docs[0][0])
        out.append(f"static const char text_{ident(lang)}[] =\n{c_string(data)};\n")
        out.append(f"static const terms_doc_t {ident(lang)} = {{\n"
                   f'    "{version}", "{lang}", text_{ident(lang)}, sizeof text_{ident(lang)} - 1,\n'
                   f"    {1 if (ctl or i == 0) else 0}, {ref}\n}};\n")
    table = ", ".join("&" + ident(lang) for lang, _, _ in docs)
    out.append(f"static const terms_doc_t *const all[] = {{ {table} }};\n")
    out.append("const terms_doc_t *terms_builtin_lang(const char *lang)\n{\n"
               "    size_t i, n;\n"
               "    for (i = 0; lang && i < sizeof all / sizeof all[0]; i++) {\n"
               "        for (n = 0; all[i]->lang[n] && all[i]->lang[n] == lang[n]; n++) {}\n"
               "        if (!all[i]->lang[n] && (!lang[n] || lang[n] == '-')) return all[i];\n"
               "    }\n"
               "    return all[0];\n}\n")
    out.append("const terms_doc_t *terms_builtin(void)\n{\n"
               f"    return &{ident(docs[0][0])};\n}}\n")
    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main(sys.argv)
