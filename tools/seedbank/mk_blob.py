"""usage: mk_blob.py <bank.bin> <out.h>"""
import sys


def main():
    if len(sys.argv) != 3:
        print(__doc__)
        return 1
    bank, out = sys.argv[1], sys.argv[2]
    with open(bank, "rb") as f:
        data = f.read()
    with open(out, "w") as f:
        f.write("/* generated by tools/seedbank/mk_blob.py — do not edit */\n")
        f.write("#ifndef ZXV_SEEDBANK_BLOB_H\n#define ZXV_SEEDBANK_BLOB_H\n")
        f.write("#include <stdint.h>\n")
        f.write("static const uint8_t zxv_seedbank_blob[%d] = {\n" % len(data))
        for i in range(0, len(data), 24):
            row = ", ".join("0x%02x" % b for b in data[i:i + 24])
            f.write("    " + row + ",\n")
        f.write("};\n")
        f.write("static const uint32_t zxv_seedbank_blob_len = %d;\n" % len(data))
        f.write("#endif /* ZXV_SEEDBANK_BLOB_H */\n")
    print("blob: %d bytes -> %s" % (len(data), out))
    return 0


if __name__ == "__main__":
    sys.exit(main())