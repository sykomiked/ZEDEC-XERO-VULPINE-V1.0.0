"""gen_seed_blob.py — the fractal seed of the release, embedded in the ELF
(zxv_seed_blob.h) the way a seed carries the whole plant as a blueprint.

A seed is a compact self-referential digest chain that commits the whole
release and unfolds into the next generation:

    seed_digest = sha256(upstream_cid || cur_digest || lattice_digest
                         || prev_seed_digest)

  * upstream_cid    the master bucket CID of the release tree
                    (build_system/zxv_upstream.cid, the "cid" line);
  * cur_digest      sha256 of the embedded curriculum CAR, the knowledge
                    tree every node slices and serves;
  * lattice_digest  the 144-dimensional Zeckendorf-Casimir lattice ROM
                    digest (gen_scp144_blob.py);
  * prev_seed       the previous release's seed_digest (from
                    build/seed.prev if present; all zeros for the first
                    generation).

scp144_boot_selfcheck recomputes the chain before [BOOT_OK] on every
architecture, so the ELF's seed verifies the release it belongs to and the
next release's seed commits this one — the recursion of the fractal.

Usage: gen_seed_blob.py <upstream.cid> <curriculum.car> [<prev_seed.bin>] <out header>
"""
import hashlib
import pathlib
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from gen_scp144_blob import build as lattice_build  # noqa: E402


def upstream_cid(path: pathlib.Path) -> bytes:
    for line in path.read_text().splitlines():
        line = line.strip()
        if line.startswith("cid "):
            return line.split()[1].encode()
    raise SystemExit(f"{path}: no 'cid <v>' line")


def sign_seed(seed_digest: bytes, key_path: str) -> tuple[bytes, bytes]:
    """Ed25519 root seal (the rollback invariant): sign the 32-byte seed
    digest with the owner's Ed25519 key via openssl. Returns (pubkey, sig),
    each 32/64 bytes, or (zeros, zeros) when no key is given (unsigned seed).
    Signing is deterministic, so a fixed key keeps the build reproducible."""
    import subprocess
    if not key_path:
        return b"\0" * 32, b"\0" * 64
    try:
        pub = subprocess.run(
            ["openssl", "pkey", "-in", key_path, "-pubout", "-outform", "DER"],
            check=True, capture_output=True).stdout[-32:]
        sig = subprocess.run(
            ["openssl", "pkeyutl", "-sign", "-rawin", "-inkey", key_path,
             "-in", "/dev/stdin"],
            input=seed_digest, check=True, capture_output=True).stdout
        if len(pub) != 32 or len(sig) != 64:
            raise SystemExit(f"{key_path}: openssl produced pub={len(pub)} sig={len(sig)}")
        return pub, sig
    except FileNotFoundError:
        raise SystemExit("openssl is required to seal the seed (or omit --sign for an unsigned seed)")


def main() -> int:
    if len(sys.argv) not in (4, 5, 6, 7):
        sys.stderr.write("usage: gen_seed_blob.py <upstream.cid> <curriculum.car> [prev_seed.bin] [--sign key.pem] <out.h>\n")
        return 2
    args = sys.argv[1:]
    key_path = None
    if "--sign" in args:
        i = args.index("--sign")
        key_path = args[i + 1]
        del args[i:i + 2]
    if len(args) == 3:
        upstream_path, car_path, out_path = map(pathlib.Path, args)
        prev = b"\0" * 32
    elif len(args) == 4:
        upstream_path, car_path, prev_path, out_path = map(pathlib.Path, args)
        prev = prev_path.read_bytes()
        if len(prev) != 32:
            raise SystemExit(f"{prev_path}: expected 32 bytes, got {len(prev)}")
    else:
        raise SystemExit("usage: gen_seed_blob.py <upstream.cid> <curriculum.car> [prev_seed.bin] [--sign key.pem] <out.h>")
    cid = upstream_cid(upstream_path)
    if len(cid) > 63:
        raise SystemExit(f"{upstream_path}: the CID is {len(cid)} bytes; the seed holds up to 63")
    car = car_path.read_bytes() if car_path.exists() else b""
    cur_digest = hashlib.sha256(car).digest()
    _, _, _, _, lattice_digest = lattice_build()
    seed_digest = hashlib.sha256(cid + cur_digest + lattice_digest + prev).digest()
    owner_pub, owner_sig = sign_seed(seed_digest, key_path)

    lines = [
        "/* Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC */",
        "/* SPDX-License-Identifier: Apache-2.0 */",
        "/* zxv_seed_blob.h — GENERATED by build_system/gen_seed_blob.py; do not edit. */",
        "/* The fractal seed: a self-referential digest chain committing the release tree,",
        " * the curriculum and the 144-dimensional lattice; scp144_boot_selfcheck verifies",
        " * it before [BOOT_OK]. */",
        "#ifndef ZXV_SEED_BLOB_H",
        "#define ZXV_SEED_BLOB_H",
        "#include <stdint.h>",
        f"#define ZXV_SEED_UPSTREAM_LEN {len(cid)}u",
        "static const uint8_t zxv_seed_upstream_cid[ZXV_SEED_UPSTREAM_LEN] = {",
        "    " + ", ".join(str(b) for b in cid) + ",",
        "};",
    ]

    def digest_arr(name, d):
        lines.append(f"static const uint8_t {name}[{len(d)}] = {{")
        lines.append("    " + ", ".join("0x%02x" % b for b in d) + ",")
        lines.append("};")

    digest_arr("zxv_seed_cur_digest", cur_digest)
    digest_arr("zxv_seed_lattice_digest", lattice_digest)
    digest_arr("zxv_seed_prev_digest", prev)
    digest_arr("zxv_seed_owner_pub", owner_pub)
    digest_arr("zxv_seed_sig", owner_sig)
    digest_arr("zxv_seed_digest", seed_digest)
    lines.append("#endif /* ZXV_SEED_BLOB_H */")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines) + "\n")
    print("seed blob: %s bytes upstream, digest %s" % (len(cid), seed_digest.hex()), file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())