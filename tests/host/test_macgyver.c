TEST(compute_triad_digest_test) {
    mcg_registry_t reg;
    mcg_registry_init(&reg);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_PLUS, "a", 0);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_MINUS, "b", 0);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_ZERO, "c", 0);
    mcg_create_triad(&reg, "t", 1, 2, 3);

    uint8_t d1[4] = {0xAA, 0xBB, 0xCC, 0xDD};
    uint8_t d2[4] = {0x11, 0x22, 0x33, 0x44};
    uint8_t d3[4] = {0x55, 0x66, 0x77, 0x88};
    mcg_set_component_digest(&reg, 0, MCG_COMPONENT_FORGE, d1, 4);
    mcg_set_component_digest(&reg, 0, MCG_COMPONENT_COUNTERFORGE, d2, 4);
    mcg_set_component_digest(&reg, 0, MCG_COMPONENT_MEDIATRIX, d3, 4);

    ASSERT(mcg_compute_triad_digest(&reg, 0), "triad digest computed");
    ASSERT(reg.triads[0].triad_digest_len == MCG_MAX_DIGEST_LEN, "digest length is max");
    /* Verify it's not all zeros */
    bool nonzero = false;
    for (uint32_t i = 0; i < MCG_MAX_DIGEST_LEN; i++) {
        if (reg.triads[0].triad_digest[i] != 0) { nonzero = true; break; }
    }
    ASSERT(nonzero, "triad digest is non-zero");
    PASS();
}

TEST(link_triad_test) {
    mcg_registry_t reg;
    mcg_registry_init(&reg);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_PLUS, "a", 0);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_MINUS, "b", 0);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_ZERO, "c", 0);
    mcg_create_triad(&reg, "t", 1, 2, 3);

    /* Can't link before complete */
    ASSERT(!mcg_link_triad(&reg, 0), "can't link incomplete triad");

    mcg_set_component_status(&reg, 0, MCG_COMPONENT_FORGE, MCG_STATUS_COMPILED);
    mcg_set_component_status(&reg, 0, MCG_COMPONENT_COUNTERFORGE, MCG_STATUS_COMPILED);
    mcg_set_component_status(&reg, 0, MCG_COMPONENT_MEDIATRIX, MCG_STATUS_COMPILED);

    uint8_t d[4] = {0x01, 0x02, 0x03, 0x04};
    mcg_set_component_digest(&reg, 0, MCG_COMPONENT_FORGE, d, 4);
    mcg_set_component_digest(&reg, 0, MCG_COMPONENT_COUNTERFORGE, d, 4);
    mcg_set_component_digest(&reg, 0, MCG_COMPONENT_MEDIATRIX, d, 4);

    ASSERT(mcg_link_triad(&reg, 0), "triad linked");
    ASSERT(reg.triads[0].linked, "linked flag set");
    ASSERT(reg.triads[0].forge_status == MCG_STATUS_LINKED, "forge is linked");
    ASSERT(reg.triads[0].counterforge_status == MCG_STATUS_LINKED, "counterforge is linked");
    ASSERT(reg.triads[0].mediatrix_status == MCG_STATUS_LINKED, "mediatrix is linked");
    ASSERT(reg.triads[0].triad_digest_len > 0, "triad digest computed");
    PASS();
}

/* ===== Build Orchestration Tests ===== */

TEST(compile_component_test) {
    mcg_registry_t reg;
    mcg_registry_init(&reg);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_PLUS, "a", 0);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_MINUS, "b", 0);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_ZERO, "c", 0);
    mcg_create_triad(&reg, "t", 1, 2, 3);

    /* Set digests on nodes */
    uint8_t d[4] = {0xDE, 0xAD, 0xBE, 0xEF};
    mcg_set_node_digest(&reg, 1, d, 4);
    mcg_set_node_digest(&reg, 2, d, 4);
    mcg_set_node_digest(&reg, 3, d, 4);

    ASSERT(mcg_compile_component(&reg, 0, MCG_COMPONENT_FORGE), "forge compiled");
    ASSERT(reg.triads[0].forge_status == MCG_STATUS_COMPILED, "forge is compiled");
    ASSERT(reg.triads[0].forge_digest_len == 4, "forge digest copied");

    /* Compile without digest fails */
    mcg_registry_t reg2;
    mcg_registry_init(&reg2);
    mcg_add_node(&reg2, MCG_NODE_MODULE, MCG_ROLE_S_PLUS, "x", 0);
    mcg_add_node(&reg2, MCG_NODE_MODULE, MCG_ROLE_S_MINUS, "y", 0);
    mcg_add_node(&reg2, MCG_NODE_MODULE, MCG_ROLE_S_ZERO, "z", 0);
    mcg_create_triad(&reg2, "t2", 1, 2, 3);
    ASSERT(!mcg_compile_component(&reg2, 0, MCG_COMPONENT_FORGE), "compile without digest fails");
    PASS();
}

