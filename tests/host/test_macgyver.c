TEST(build_triad_atomic_failure_test) {
    mcg_registry_t reg;
    mcg_registry_init(&reg);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_PLUS, "ok", 0);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_MINUS, "missing-digest", 0);
    mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_ZERO, "ok2", 0);
    mcg_create_triad(&reg, "fail-build", 1, 2, 3);

    /* Only set digest on forge node, not counterforge */
    uint8_t d[4] = {0xFF, 0xFF, 0xFF, 0xFF};
    mcg_set_node_digest(&reg, 1, d, 4);
    /* Node 2 has no digest — counterforge will fail */

    ASSERT(!mcg_build_triad(&reg, 0), "atomic build fails");
    ASSERT(reg.triads[0].forge_status == MCG_STATUS_FAILED, "forge failed (atomic rollback)");
    ASSERT(!reg.triads[0].linked, "not linked");
    PASS();
}

