/* ===== Triad Link Protocol Tests ===== */

TEST(create_triad_test) {
    mcg_registry_t reg;
    mcg_registry_init(&reg);
    int32_t forge = mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_PLUS, "app.36n9", 0);
    int32_t counter = mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_MINUS, "app.9n63", 0);
    int32_t medi = mcg_add_node(&reg, MCG_NODE_MODULE, MCG_ROLE_S_ZERO, "app.0n0", 0);

    int32_t tidx = mcg_create_triad(&reg, "app-triad",
                                    (uint32_t)forge + 1,
                                    (uint32_t)counter + 1,
                                    (uint32_t)medi + 1);
    ASSERT(tidx >= 0, "triad created");
    ASSERT(reg.triad_count == 1, "count incremented");

    mcg_triad_t *t = &reg.triads[0];
    ASSERT(strcmp(t->name, "app-triad") == 0, "name matches");
    ASSERT(t->forge_node_id == 1, "forge node is 1");
    ASSERT(t->counterforge_node_id == 2, "counterforge node is 2");
    ASSERT(t->mediatrix_node_id == 3, "mediatrix node is 3");
    ASSERT(t->forge_status == MCG_STATUS_PENDING, "forge pending");
    ASSERT(t->counterforge_status == MCG_STATUS_PENDING, "counterforge pending");
    ASSERT(t->mediatrix_status == MCG_STATUS_PENDING, "mediatrix pending");
    ASSERT(!t->linked, "not linked");
    ASSERT(t->atomic, "is atomic");
    PASS();
}

