C     THE DAYS IN A MONTH OF THE GREGORIAN CALENDAR (SOLSTICE_RULES.H
C     SO1): READS YEAR AND MONTH, PRINTS 28 TO 31. FEBRUARY HAS 29 IN A
C     YEAR DIVISIBLE BY 4, EXCEPT A CENTURY NOT DIVISIBLE BY 400. AN
C     INTEGER HERE IS 32 BITS, SO THE YEAR IS HELD TO NINE DIGITS: A YEAR
C     PAST 999999999 OR BELOW 1, OR A MONTH OUTSIDE 1 TO 12, IS REFUSED.
      PROGRAM MDAYS
      INTEGER IY, M, LAST
      READ *, IY, M
      IF (IY .LT. 1 .OR. IY .GT. 999999999) THEN
        PRINT *, 'REFUSED'
        STOP
      END IF
      IF (M .LT. 1 .OR. M .GT. 12) THEN
        PRINT *, 'REFUSED'
        STOP
      END IF
      LAST = 30 + MOD(M + M / 8, 2)
      IF (M .EQ. 2) THEN
        LAST = 28
        IF (MOD(IY, 4) .EQ. 0 .AND. MOD(IY, 100) .NE. 0) LAST = 29
        IF (MOD(IY, 400) .EQ. 0) LAST = 29
      END IF
      PRINT *, LAST
      END
