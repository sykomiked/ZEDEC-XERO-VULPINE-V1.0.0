# gen_zxva_vk_spv.sh OUT.h [OUT.spv] — builds zxva_vk.comp with
# glslangValidator into one C header holding the SPIR-V (zxva_vk_spv[]),
# which zxva_vk.c includes as ZXVA_VK_SPV_H. The shared sources
# zxva_stft_math.h and zxva_stft_kern.h are included as GLSL after their
# ZXVA_K_SRC( and ) wrapper lines are stripped. With OUT.spv it also writes
# the raw module (for spirv-val). Exits 1 without glslangValidator.
set -e
out=${1:?usage: gen_zxva_vk_spv.sh OUT.h [OUT.spv]}
dir=$(dirname "$0")
command -v glslangValidator >/dev/null 2>&1 || { echo "glslangValidator not found" >&2; exit 1; }
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
for f in zxva_stft_math zxva_stft_kern; do
    sed -e '/^ZXVA_K_SRC($/d' -e '/^)$/d' "$dir/$f.h" >"$tmp/$f.glsl"
    if grep -q '^ZXVA_K_SRC' "$tmp/$f.glsl"; then echo "$f.h: wrapper not stripped" >&2; exit 1; fi
done
cp "$dir/zxva_vk.comp" "$tmp/zxva_vk.comp"
glslangValidator -S comp --target-env vulkan1.1 -I"$tmp" --vn zxva_vk_spv \
    -o "$tmp/spv.h" "$tmp/zxva_vk.comp" >"$tmp/log" 2>&1 || { cat "$tmp/log" >&2; exit 1; }
{
    echo "/* generated by gen_zxva_vk_spv.sh from zxva_vk.comp: do not edit */"
    sed -e '/#pragma once/d' -e 's/^const uint32_t/static const uint32_t/' "$tmp/spv.h"
} >"$out"
if [ -n "$2" ]; then
    glslangValidator -S comp --target-env vulkan1.1 -I"$tmp" -o "$2" "$tmp/zxva_vk.comp" >/dev/null
fi
