"""Write test_diskcrypt_vectors.h from published test vectors.

The XChaCha12, NHPoly1305 and Adiantum vectors are the ones published with
the Adiantum design (https://github.com/google/adiantum), as carried in the
Linux kernel's crypto/testmgr.h. This script reads that file and keeps only
the bytes; no code is taken from it.

    curl -o testmgr.h https://raw.githubusercontent.com/torvalds/linux/v6.10/crypto/testmgr.h
    python3 gen_diskcrypt_vectors.py testmgr.h > test_diskcrypt_vectors.h
"""
import re
import sys

TEMPLATES = [
    ("xchacha12_tv_template", "cipher", "xchacha12_vec"),
    ("nhpoly1305_tv_template", "hash", "nhpoly_vec"),
    ("adiantum_xchacha12_aes_tv_template", "cipher", "adiantum_vec"),
]


def block_of(src, name):
    start = src.index(name + "[] = {")
    depth, i = 0, src.index("{", start)
    for j in range(i, len(src)):
        if src[j] == "{":
            depth += 1
        elif src[j] == "}":
            depth -= 1
            if depth == 0:
                return src[i + 1:j]
    raise ValueError(name)


def entries(body):
    out, depth, cur = [], 0, None
    for i, ch in enumerate(body):
        if ch == "{":
            depth += 1
            if depth == 1:
                cur = i + 1
        elif ch == "}":
            depth -= 1
            if depth == 0:
                out.append(body[cur:i])
    return out


def cbytes(text):
    """Concatenate adjacent C string literals into bytes."""
    data = b""
    for lit in re.findall(r'"((?:[^"\\]|\\.)*)"', text):
        i = 0
        while i < len(lit):
            if lit[i] == "\\" and lit[i + 1] == "x":
                m = re.match(r"[0-9a-fA-F]{1,2}", lit[i + 2:])
                data += bytes([int(m.group(0), 16)])
                i += 2 + len(m.group(0))
            elif lit[i] == "\\":
                esc = {"0": 0, "n": 10, "t": 9, "\\": 92, '"': 34}[lit[i + 1]]
                data += bytes([esc])
                i += 2
            else:
                data += lit[i].encode()
                i += 1
    return data


def fields(entry):
    f = {}
    for m in re.finditer(r"\.(\w+)\s*=\s*((?:\"(?:[^\"\\]|\\.)*\"\s*)+|[^,]+),", entry + ","):
        key, val = m.group(1), m.group(2).strip()
        f[key] = cbytes(val) if val.startswith('"') else val
    return f


def hexstr(b):
    return '"' + b.hex() + '"'


def main():
    src = open(sys.argv[1], encoding="utf-8").read()
    print("/* test_diskcrypt_vectors.h — generated by gen_diskcrypt_vectors.py. Do not edit.")
    print(" *")
    print(" * Published XChaCha12, NHPoly1305 and Adiantum test vectors from the")
    print(" * Adiantum design (https://github.com/google/adiantum). Hex strings. */")
    print("#ifndef ZXV_TEST_DISKCRYPT_VECTORS_H")
    print("#define ZXV_TEST_DISKCRYPT_VECTORS_H")
    print("/* clang-format off */")
    print("typedef struct { const char *key, *iv, *ptext, *ctext; } cipher_vec_t;")
    print("typedef struct { const char *key, *msg, *digest; } hash_vec_t;")
    for name, kind, out in TEMPLATES:
        ents = entries(block_of(src, name))
        if kind == "cipher":
            print("static const cipher_vec_t %s[] = {" % out)
            for e in ents:
                f = fields(e)
                n = int(f["len"])
                assert len(f["ptext"]) == n and len(f["ctext"]) == n, name
                print("    {%s,\n     %s,\n     %s,\n     %s}," % (
                    hexstr(f["key"]), hexstr(f["iv"]), hexstr(f["ptext"]), hexstr(f["ctext"])))
        else:
            print("static const hash_vec_t %s[] = {" % out)
            for e in ents:
                f = fields(e)
                n = int(f["psize"])
                msg = f.get("plaintext", b"")
                assert len(msg) == n, (name, len(msg), n)
                print("    {%s,\n     %s,\n     %s}," % (
                    hexstr(f["key"]), hexstr(msg), hexstr(f["digest"])))
        print("};")
    print("/* clang-format on */")
    print("#endif")


if __name__ == "__main__":
    main()
