/* the last range in a (start << shift | value) table that starts at or before cp */
static uint32_t range_value(const uint32_t *t, uint32_t n, uint32_t shift, uint32_t cp)
{
    uint32_t lo = 0, hi = n;
    while (hi - lo > 1u) {
        uint32_t mid = (lo + hi) / 2u;
        if ((t[mid] >> shift) <= cp)
            lo = mid;
        else
            hi = mid;
    }
    return t[lo] & ((1u << shift) - 1u);
}

/* ---- S1..S5: Arabic ------------------------------------------------------- */

zui_joining_t zui_shape_joining(uint32_t cp)
{
    if (cp > 0x10FFFFu) return ZUI_JOIN_U;
    return (zui_joining_t) range_value(JOIN_RANGES, sizeof JOIN_RANGES / sizeof JOIN_RANGES[0], 3,
                                       cp);
}

static bool joins_after(zui_joining_t t) /* can join the letter that follows */
{
    return t == ZUI_JOIN_D || t == ZUI_JOIN_L || t == ZUI_JOIN_C;
}
static bool joins_before(zui_joining_t t) /* can join the letter before it */
{
    return t == ZUI_JOIN_D || t == ZUI_JOIN_R || t == ZUI_JOIN_C;
}

static zui_form_t form_of(zui_joining_t t, bool prev_joins, bool next_joins)
{
    switch (t) {
    case ZUI_JOIN_D:
        if (prev_joins && next_joins) return ZUI_FORM_MEDI;
        if (prev_joins) return ZUI_FORM_FINA;
        if (next_joins) return ZUI_FORM_INIT;
        return ZUI_FORM_ISOL;
    case ZUI_JOIN_R:
        return prev_joins ? ZUI_FORM_FINA : ZUI_FORM_ISOL;
    case ZUI_JOIN_L:
        return next_joins ? ZUI_FORM_INIT : ZUI_FORM_ISOL;
    default:
        return ZUI_FORM_NONE;
    }
}

void zui_shape_forms(const uint32_t *cp, uint32_t n, uint8_t *form)
{
    zui_joining_t prev = ZUI_JOIN_U; /* the last non-transparent character */
    for (uint32_t i = 0; i < n; i++) {
        zui_joining_t t = zui_shape_joining(cp[i]);
        if (t == ZUI_JOIN_T) {
            form[i] = ZUI_FORM_NONE;
            continue;
        }
        zui_joining_t next = ZUI_JOIN_U;
        for (uint32_t j = i + 1u; j < n; j++) {
            zui_joining_t u = zui_shape_joining(cp[j]);
            if (u != ZUI_JOIN_T) {
                next = u;
                break;
            }
        }
        form[i] = (uint8_t) form_of(t, joins_after(prev), joins_before(next));
        prev = t;
    }
}

uint32_t zui_shape_presentation(uint32_t cp, zui_form_t f)
{
    if (f < ZUI_FORM_ISOL || f > ZUI_FORM_MEDI) return cp;
    uint32_t lo = 0, hi = (uint32_t) (sizeof PRES / sizeof PRES[0]);
    while (lo < hi) {
        uint32_t mid = (lo + hi) / 2u;
        if (PRES[mid][0] == cp) {
            const uint16_t *p = PRES[mid];
            uint32_t want = p[f]; /* columns: letter, isol, fina, init, medi */
            if (want) return want;
            /* a letter without that form: medial falls back to final, initial
             * to isolated (an R letter in the middle of a word) */
            if (f == ZUI_FORM_MEDI && p[ZUI_FORM_FINA]) return p[ZUI_FORM_FINA];
            if (p[ZUI_FORM_ISOL]) return p[ZUI_FORM_ISOL];
            return cp;
        }
        if (PRES[mid][0] < cp)
            lo = mid + 1u;
        else
            hi = mid;
    }
    return cp;
}

/* S4: the lam-alef ligature for an alef, isolated (fina = false) or final. */
static uint32_t lam_alef(uint32_t alef, bool fina)
{
    uint32_t base;
    switch (alef) {
    case 0x0622:
        base = 0xFEF5u;
        break; /* madda       */
    case 0x0623:
        base = 0xFEF7u;
        break; /* hamza above */
    case 0x0625:
        base = 0xFEF9u;
        break; /* hamza below */
    case 0x0627:
        base = 0xFEFBu;
        break; /* alef        */
    default:
        return 0;
    }
    return base + (fina ? 1u : 0u);
}

uint32_t zui_shape_arabic(const uint32_t *in, uint32_t n, uint32_t *out, uint16_t *map,
                          uint32_t cap)
{
    uint32_t w = 0;
    zui_joining_t prev = ZUI_JOIN_U;
    for (uint32_t i = 0; i < n && w < cap; i++) {
        zui_joining_t t = zui_shape_joining(in[i]);
        uint32_t o = in[i];
        uint32_t used = 1;
        if (t != ZUI_JOIN_T) {
            zui_joining_t next = ZUI_JOIN_U;
            for (uint32_t j = i + 1u; j < n; j++) {
                zui_joining_t u = zui_shape_joining(in[j]);
                if (u != ZUI_JOIN_T) {
                    next = u;
                    break;
                }
            }
            zui_form_t f = form_of(t, joins_after(prev), joins_before(next));
            uint32_t lig = (in[i] == 0x0644u && i + 1u < n) ? lam_alef(in[i + 1u], 0) : 0;
            if (lig) {
                o = lam_alef(in[i + 1u], joins_after(prev));
                used = 2;
                t = ZUI_JOIN_R; /* the ligature ends like an alef: joins nothing after */
            } else if (f != ZUI_FORM_NONE) {
                o = zui_shape_presentation(in[i], f);
            }
            prev = t;
        }
        out[w] = o;
        if (map) map[w] = (uint16_t) i;
        w++;
        i += used - 1u;
    }
    return w;
}

/* Joining type of the next non-transparent character at s[i..). */
static zui_joining_t next_joining(const char *s, uint32_t len, uint32_t i)
{
    while (i < len) {
        zui_joining_t t = zui_shape_joining(zui_utf8_decode(s, len, &i));
        if (t != ZUI_JOIN_T) return t;
    }
    return ZUI_JOIN_U;
}

uint32_t zui_shape_utf8(const char *in, uint32_t len, char *out, uint32_t cap)
{
    uint32_t i = 0, w = 0;
    zui_joining_t prev = ZUI_JOIN_U;
    if (!out || cap == 0) return 0;
    while (in && i < len) {
        uint32_t c = zui_utf8_decode(in, len, &i);
        zui_joining_t t = zui_shape_joining(c);
        uint32_t o = c;
        if (t != ZUI_JOIN_T) {
            zui_joining_t next = next_joining(in, len, i);
            /* lam-alef: only when the alef comes right after the lam */
            uint32_t at = i, alef = 0;
            if (c == 0x0644u && i < len) alef = zui_utf8_decode(in, len, &at);
            if (alef && lam_alef(alef, 0)) {
                o = lam_alef(alef, joins_after(prev));
                i = at;
                t = ZUI_JOIN_R;
            } else {
                zui_form_t f = form_of(t, joins_after(prev), joins_before(next));
                if (f != ZUI_FORM_NONE) o = zui_shape_presentation(c, f);
            }
            prev = t;
        }
        uint32_t k = zui_utf8_encode(o, out + w, cap - 1u - w);
        if (!k) break;
        w += k;
    }
    out[w] = 0;
    return w;
}

/* ---- S6: grapheme clusters ------------------------------------------------ */

static uint32_t gprops(uint32_t cp)
{
    if (cp > 0x10FFFFu) return ZUI_GCB_OTHER;
    if (cp >= 0xAC00u && cp <= 0xD7A3u) return (cp - 0xAC00u) % 28u == 0 ? ZUI_GCB_LV : ZUI_GCB_LVT;
    return range_value(GCB_RANGES, sizeof GCB_RANGES / sizeof GCB_RANGES[0], 8, cp);
}

zui_gcb_t zui_grapheme_break(uint32_t cp)
{
    return (zui_gcb_t) (gprops(cp) & 15u);
}
bool zui_extended_pictographic(uint32_t cp)
{
    return (gprops(cp) & 16u) != 0;
}
zui_incb_t zui_indic_conjunct_break(uint32_t cp)
{
    return (zui_incb_t) ((gprops(cp) >> 5) & 3u);
}

typedef struct {
    const char *s;
    uint32_t len, i;
    uint8_t prev; /* gcb of the character before i      */
    bool started; /* a character has been read          */
    bool ep;      /* ... ExtPict Extend* ends here       */
    bool zwj_ep;  /* the ZWJ before i followed ExtPict Extend* */
    uint32_t ri;  /* regional indicators in a row before i */
    uint8_t incb; /* 0, 1 consonant [extend|linker]*, 2 ... with a linker */
} gstate_t;

/* Is there a boundary before the character with properties p? */
static bool g_break(const gstate_t *g, uint32_t p)
{
    uint8_t a = g->prev, c = (uint8_t) (p & 15u);
    if (!g->started) return true;                                                /* GB1 */
    if (a == ZUI_GCB_CR && c == ZUI_GCB_LF) return false;                        /* GB3 */
    if (a == ZUI_GCB_CONTROL || a == ZUI_GCB_CR || a == ZUI_GCB_LF) return true; /* GB4 */
    if (c == ZUI_GCB_CONTROL || c == ZUI_GCB_CR || c == ZUI_GCB_LF) return true; /* GB5 */
    if (a == ZUI_GCB_L && (c == ZUI_GCB_L || c == ZUI_GCB_V || c == ZUI_GCB_LV || c == ZUI_GCB_LVT))
        return false; /* GB6 */
    if ((a == ZUI_GCB_LV || a == ZUI_GCB_V) && (c == ZUI_GCB_V || c == ZUI_GCB_T))
        return false;                                                         /* GB7 */
    if ((a == ZUI_GCB_LVT || a == ZUI_GCB_T) && c == ZUI_GCB_T) return false; /* GB8 */
    if (c == ZUI_GCB_EXTEND || c == ZUI_GCB_ZWJ) return false;                /* GB9 */
    if (c == ZUI_GCB_SPACINGMARK) return false;                               /* GB9a */
    if (a == ZUI_GCB_PREPEND) return false;                                   /* GB9b */
    if (g->incb == 2 && ((p >> 5) & 3u) == ZUI_INCB_CONSONANT) return false;  /* GB9c */
    if (a == ZUI_GCB_ZWJ && g->zwj_ep && (p & 16u)) return false;             /* GB11 */
    if (a == ZUI_GCB_RI && c == ZUI_GCB_RI && (g->ri & 1u)) return false;     /* GB12, GB13 */
    return true;                                                              /* GB999 */
}

static void g_take(gstate_t *g, uint32_t p)
{
    uint8_t c = (uint8_t) (p & 15u), incb = (uint8_t) ((p >> 5) & 3u);
    g->zwj_ep = c == ZUI_GCB_ZWJ && g->ep;
    if (p & 16u)
        g->ep = true;
    else if (c != ZUI_GCB_EXTEND)
        g->ep = false;
    g->ri = c == ZUI_GCB_RI ? g->ri + 1u : 0;
    if (incb == ZUI_INCB_CONSONANT)
        g->incb = 1;
    else if (incb == ZUI_INCB_LINKER && g->incb)
        g->incb = 2;
    else if (incb != ZUI_INCB_EXTEND)
        g->incb = 0;
    g->prev = c;
    g->started = true;
}

/* Read the cluster at g->i; returns its end. */
static uint32_t g_cluster(gstate_t *g)
{
    bool first = true;
    while (g->i < g->len) {
        uint32_t at = g->i;
        uint32_t cp = zui_utf8_decode(g->s, g->len, &at);
        uint32_t p = gprops(cp);
        if (!first && g_break(g, p)) break;
        g_take(g, p);
        g->i = at;
        first = false;
    }
    return g->i;
}

static void g_init(gstate_t *g, const char *s, uint32_t len)
{
    g->s = s;
    g->len = s ? len : 0;
    g->i = 0;
    g->prev = 0;
    g->started = false;
    g->ep = g->zwj_ep = false;
    g->ri = 0;
    g->incb = 0;
}

uint32_t zui_grapheme_next(const char *s, uint32_t len, uint32_t at)
{
    gstate_t g;
    g_init(&g, s, len);
    if (at >= g.len) return g.len;
    while (g.i < g.len) {
        uint32_t e = g_cluster(&g);
        if (e > at) return e;
    }
    return g.len;
}

uint32_t zui_grapheme_prev(const char *s, uint32_t len, uint32_t at)
{
    gstate_t g;
    uint32_t last = 0;
    g_init(&g, s, len);
    if (at > g.len) at = g.len;
    while (g.i < g.len) {
        uint32_t e = g_cluster(&g);
        if (e >= at) break;
        last = e;
    }
    return last;
}

bool zui_grapheme_is_boundary(const char *s, uint32_t len, uint32_t at)
{
    if (at == 0) return true;
    if (!s) return false;
    if (at >= len) return at == len;
    return zui_grapheme_next(s, len, at - 1u) == at;
}

uint32_t zui_grapheme_count(const char *s, uint32_t len)
{
    gstate_t g;
    uint32_t n = 0;
    g_init(&g, s, len);
    while (g.i < g.len) {
        g_cluster(&g);
        n++;
    }
    return n;
}

/* ---- S7, S8: Devanagari --------------------------------------------------- */

zui_indic_cat_t zui_indic_category(uint32_t cp)
{
    if (cp == 0x200Du) return ZUI_INDIC_ZWJ;
    if (cp == 0x200Cu) return ZUI_INDIC_ZWNJ;
    if (cp < 0x0900u || cp > 0x097Fu) return ZUI_INDIC_X;
    if ((cp >= 0x0915u && cp <= 0x0939u) || (cp >= 0x0958u && cp <= 0x095Fu) ||
        (cp >= 0x0978u && cp <= 0x097Fu))
        return ZUI_INDIC_C;
    if ((cp >= 0x0904u && cp <= 0x0914u) || cp == 0x0960u || cp == 0x0961u ||
        (cp >= 0x0972u && cp <= 0x0977u))
        return ZUI_INDIC_V;
    if (cp == 0x093Cu) return ZUI_INDIC_N;
    if (cp == 0x094Du) return ZUI_INDIC_H;
    if (cp == 0x093Fu || cp == 0x094Eu) return ZUI_INDIC_MPRE;
    if (cp == 0x093Au || cp == 0x093Bu || cp == 0x093Eu || (cp >= 0x0940u && cp <= 0x094Cu) ||
        cp == 0x094Fu || (cp >= 0x0955u && cp <= 0x0957u) || cp == 0x0962u || cp == 0x0963u)
        return ZUI_INDIC_M;
    if (cp <= 0x0903u) return ZUI_INDIC_VM;
    if (cp >= 0x0951u && cp <= 0x0954u) return ZUI_INDIC_A;
    return ZUI_INDIC_X;
}

static bool is_sign(zui_indic_cat_t c)
{
    return c == ZUI_INDIC_VM || c == ZUI_INDIC_A;
}
static bool is_mark(zui_indic_cat_t c)
{
    return c == ZUI_INDIC_N || c == ZUI_INDIC_H || c == ZUI_INDIC_M || c == ZUI_INDIC_MPRE ||
           is_sign(c);
}

uint32_t zui_indic_syllable(const uint32_t *cp, uint32_t n, uint32_t at, zui_indic_syllable_t *s)
{
    zui_indic_syllable_t r = {at, at, ZUI_SYL_OTHER, false, false, -1, -1, 0};
    uint32_t i = at;
#define CAT(k) ((k) < n ? zui_indic_category(cp[k]) : ZUI_INDIC_X)
    if (at >= n) {
        if (s) *s = r;
        return at;
    }
    zui_indic_cat_t c = CAT(i);
    if (c == ZUI_INDIC_C) {
        r.kind = ZUI_SYL_CONSONANT;
        for (;;) {
            r.base = (int32_t) i;
            r.consonants++;
            i++;
            if (CAT(i) == ZUI_INDIC_N) i++;
            if (CAT(i) != ZUI_INDIC_H) break;
            i++;
            if (CAT(i) == ZUI_INDIC_ZWJ || CAT(i) == ZUI_INDIC_ZWNJ) i++;
            if (CAT(i) != ZUI_INDIC_C) {
                r.dead = true;
                break;
            }
        }
        r.reph = cp[at] == 0x0930u && at + 2u < n && cp[at + 1u] == 0x094Du &&
                 zui_indic_category(cp[at + 2u]) == ZUI_INDIC_C;
        if (!r.dead) {
            for (;;) {
                zui_indic_cat_t m = CAT(i);
                if (m == ZUI_INDIC_MPRE && r.pre_matra < 0) r.pre_matra = (int32_t) i;
                if (m == ZUI_INDIC_M || m == ZUI_INDIC_MPRE || m == ZUI_INDIC_N) {
                    i++;
                    continue;
                }
                if (m == ZUI_INDIC_H) { /* a halant after a matra: keep it here */
                    i++;
                    continue;
                }
                break;
            }
        }
        while (is_sign(CAT(i))) i++;
    } else if (c == ZUI_INDIC_V) {
        r.kind = ZUI_SYL_VOWEL;
        i++;
        if (CAT(i) == ZUI_INDIC_N) i++;
        while (CAT(i) == ZUI_INDIC_M || CAT(i) == ZUI_INDIC_MPRE || CAT(i) == ZUI_INDIC_N) i++;
        while (is_sign(CAT(i))) i++;
    } else if (is_mark(c)) {
        r.kind = ZUI_SYL_BROKEN; /* marks with no base: drawn on a dotted circle */
        while (is_mark(CAT(i))) i++;
    } else {
        i++;
    }
#undef CAT
    r.end = i;
    if (s) *s = r;
    return i;
}

uint32_t zui_indic_visual(const uint32_t *in, uint32_t n, uint32_t *out, uint16_t *map,
                          uint32_t cap)
{
    uint32_t w = 0;
    for (uint32_t at = 0; at < n && w < cap;) {
        zui_indic_syllable_t s;
        uint32_t end = zui_indic_syllable(in, n, at, &s);
        if (s.pre_matra >= 0 && w < cap) {
            out[w] = in[s.pre_matra];
            if (map) map[w] = (uint16_t) s.pre_matra;
            w++;
        }
        for (uint32_t k = at; k < end && w < cap; k++) {
            if ((int32_t) k == s.pre_matra) continue;
            out[w] = in[k];
            if (map) map[w] = (uint16_t) k;
            w++;
        }
        at = end;
    }
    return w;
}
