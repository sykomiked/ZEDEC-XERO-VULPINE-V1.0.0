static void test_line_and_offsets(void)
{
    int f0 = fails, c0 = checks;
    uint16_t order[16];
    uint8_t lv[16];
    para("ab " ALEF BET " cd", ZUI_BIDI_LTR);
    CHECK(BD.n == 8 && BD.bytes == 10, "n %u bytes %u", BD.n, BD.bytes);
    CHECK(BD.off[0] == 0 && BD.off[3] == 3 && BD.off[4] == 5 && BD.off[5] == 7 && BD.off[8] == 10,
          "offsets");
    uint32_t c = zui_bidi_line(&BD, 0, BD.n, lv, order, false);
    static const uint16_t W[] = {0, 1, 2, 4, 3, 5, 6, 7};
    CHECK(c == 8 && !memcmp(order, W, sizeof W), "order");
    /* a line from the middle: indices stay absolute */
    c = zui_bidi_line(&BD, 3, 5, lv, order, false);
    CHECK(c == 2 && order[0] == 4 && order[1] == 3, "sub-line order");
    CHECK(lv[0] == 1 && lv[1] == 1, "sub-line levels");
    /* the line ends in the middle of the RTL run: L1 trailing is per line */
    para(ALEF " " BET, ZUI_BIDI_LTR);
    c = zui_bidi_line(&BD, 0, 2, lv, order, false);
    CHECK(c == 2 && lv[1] == 0 && order[0] == 0 && order[1] == 1, "space at line end resets");
    c = zui_bidi_line(&BD, 0, 3, lv, order, false);
    CHECK(lv[1] == 1 && order[0] == 2 && order[2] == 0, "space inside the run");
    CHECK(zui_bidi_line(&BD, 2, 2, lv, order, false) == 0, "empty line");
    CHECK(zui_bidi_line(&BD, 0, 3, lv, NULL, false) == 0 && lv[0] == 1, "levels only");
    /* removed characters kept */
    para("a" RLE "b" PDF, ZUI_BIDI_LTR);
    CHECK(zui_bidi_line(&BD, 0, BD.n, lv, order, false) == 2, "removed left out");
    CHECK(zui_bidi_line(&BD, 0, BD.n, lv, order, true) == 4, "removed kept");
    CHECK(BD.removed[1] && BD.removed[3] && !BD.removed[0] && !BD.removed[2], "removed flags");
    /* paragraphs */
    const char *two = "ab" PS ALEF "c";
    uint32_t used = zui_bidi_paragraph(&BD, two, (uint32_t) strlen(two), ZUI_BIDI_AUTO);
    CHECK(used == 5 && BD.n == 3 && BD.para_level == 0, "first paragraph %u", used);
    CHECK(BD.cls[2] == ZUI_BIDI_B && BD.level[2] == 0, "separator at para level");
    used = zui_bidi_paragraph(&BD, two + 5, (uint32_t) strlen(two + 5), ZUI_BIDI_AUTO);
    CHECK(used == 3 && BD.n == 2 && BD.para_level == 1, "second paragraph");
    /* truncation */
    static char big[ZUI_BIDI_MAX + 100];
    memset(big, 'a', sizeof big);
    zui_bidi_paragraph(&BD, big, sizeof big, ZUI_BIDI_AUTO);
    CHECK(BD.n == ZUI_BIDI_MAX && BD.truncated && BD.bytes == sizeof big, "truncated");
    CHECK(BD.off[BD.n] == ZUI_BIDI_MAX, "kept bytes");
    para("ab", ZUI_BIDI_AUTO);
    CHECK(!BD.truncated, "truncated cleared");
    /* bad UTF-8 is U+FFFD (ON) */
    zui_bidi_paragraph(&BD,
                       "\xFF"
                       "a",
                       2, ZUI_BIDI_AUTO);
    CHECK(BD.n == 2 && BD.cp[0] == 0xFFFD && BD.cls[0] == ZUI_BIDI_ON, "bad byte");
    printf("[%s] test_line_and_offsets: %d/%d checks\n", fails > f0 ? "FAIL" : "PASS",
           checks - c0 - (fails - f0), checks - c0);
}

/* The UCD sample: each line is three checks (paragraph level, levels, order). */
static void test_ucd_sample(void)
{
    int f0 = fails, c0 = checks;
    for (unsigned k = 0; k < sizeof UCD_SAMPLE / sizeof UCD_SAMPLE[0]; k++) {
        char line[1024];
        strncpy(line, UCD_SAMPLE[k], sizeof line - 1);
        line[sizeof line - 1] = 0;
        char *fld[5], *p = line;
        for (int j = 0; j < 5; j++) {
            fld[j] = p;
            p = strchr(p, ';');
            if (p)
                *p++ = 0;
            else
                p = line + strlen(line);
        }
        char text[1024];
        uint32_t tl = 0, ncp = 0;
        for (char *s = fld[0]; *s;) {
            while (*s == ' ') s++;
            if (!*s) break;
            tl += zui_utf8_encode((uint32_t) strtoul(s, &s, 16), text + tl, sizeof text - tl);
            ncp++;
        }
        int dir = atoi(fld[1]);
        zui_bidi_paragraph(&BD, text, tl,
                           dir == 0   ? ZUI_BIDI_LTR
                           : dir == 1 ? ZUI_BIDI_RTL
                                      : ZUI_BIDI_AUTO);
        CHECK(BD.para_level == atoi(fld[2]) && BD.n == ncp, "line %u: paragraph level", k);
        uint8_t lv[ZUI_BIDI_MAX];
        uint16_t ord[ZUI_BIDI_MAX];
        uint32_t c = zui_bidi_line(&BD, 0, BD.n, lv, ord, false);
        int ok = 1;
        char *t = fld[3];
        for (uint32_t i = 0; i < ncp && ok; i++) {
            while (*t == ' ') t++;
            if (*t == 'x') {
                ok = BD.removed[i];
                t++;
            } else {
                ok = !BD.removed[i] && strtol(t, &t, 10) == lv[i];
            }
        }
        CHECK(ok, "line %u: levels (%s)", k, UCD_SAMPLE[k]);
        uint32_t j = 0;
        ok = 1;
        for (t = fld[4]; ok;) {
            while (*t == ' ') t++;
            if (!*t) break;
            long v = strtol(t, &t, 10);
            ok = j < c && ord[j] == v;
            j++;
        }
        CHECK(ok && j == c, "line %u: order (%s)", k, UCD_SAMPLE[k]);
    }
    printf("[%s] test_ucd_sample: %d/%d checks\n", fails > f0 ? "FAIL" : "PASS",
           checks - c0 - (fails - f0), checks - c0);
}

