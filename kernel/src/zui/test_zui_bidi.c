{
    return zui_bidi_paragraph(&BD, s, (uint32_t) strlen(s), d);
}

/* levels of the whole paragraph after L1, as a digit string ('x' removed) */
static const char *levels(void)
{
    static char out[ZUI_BIDI_MAX + 1];
    uint8_t lv[ZUI_BIDI_MAX];
    zui_bidi_line(&BD, 0, BD.n, lv, NULL, false);
    for (uint32_t i = 0; i < BD.n; i++) out[i] = BD.removed[i] ? 'x' : (char) ('0' + lv[i]);
    out[BD.n] = 0;
    return out;
}

