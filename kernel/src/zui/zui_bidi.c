zui_bidi_class_t zui_bidi_class(uint32_t cp)
{
    if (cp > 0x10FFFFu) return ZUI_BIDI_L;
    uint32_t lo = 0, hi = (uint32_t) (sizeof BIDI_RANGES / sizeof BIDI_RANGES[0]);
    while (hi - lo > 1u) { /* the last range starting at or before cp */
        uint32_t mid = (lo + hi) / 2u;
        if ((BIDI_RANGES[mid] >> 5) <= cp)
            lo = mid;
        else
            hi = mid;
    }
    return (zui_bidi_class_t) (BIDI_RANGES[lo] & 31u);
}

