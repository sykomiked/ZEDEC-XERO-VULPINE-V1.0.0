uint32_t zui_bidi_mirror(uint32_t cp)
{
    uint32_t lo = 0, hi = (uint32_t) (sizeof BIDI_MIRROR / sizeof BIDI_MIRROR[0]);
    while (lo < hi) {
        uint32_t mid = (lo + hi) / 2u;
        if (BIDI_MIRROR[mid][0] == cp) return BIDI_MIRROR[mid][1];
        if (BIDI_MIRROR[mid][0] < cp)
            lo = mid + 1u;
        else
            hi = mid;
    }
    return cp;
}

int zui_bidi_bracket(uint32_t cp, uint32_t *pair)
{
    uint32_t lo = 0, hi = (uint32_t) (sizeof BIDI_BRACKET / sizeof BIDI_BRACKET[0]);
    while (lo < hi) {
        uint32_t mid = (lo + hi) / 2u;
        if (BIDI_BRACKET[mid][0] == cp) {
            if (pair) *pair = BIDI_BRACKET[mid][1];
            return BIDI_BRACKET[mid][2];
        }
        if (BIDI_BRACKET[mid][0] < cp)
            lo = mid + 1u;
        else
            hi = mid;
    }
    if (pair) *pair = cp;
    return 0;
}

/* ---- UTF-8 ---------------------------------------------------------------- */

uint32_t zui_utf8_decode(const char *s, uint32_t len, uint32_t *i)
{
    const uint8_t *u = (const uint8_t *) s;
    uint32_t at = *i;
    uint8_t c = u[at];
    uint32_t need, cp, min2 = 0x80u, max2 = 0xBFu;
    if (c < 0x80u) {
        *i = at + 1u;
        return c;
    }
    if (c >= 0xC2u && c <= 0xDFu) {
        need = 1;
        cp = c & 0x1Fu;
    } else if (c >= 0xE0u && c <= 0xEFu) {
        need = 2;
        cp = c & 0x0Fu;
        if (c == 0xE0u) min2 = 0xA0u; /* overlong */
        if (c == 0xEDu) max2 = 0x9Fu; /* surrogates */
    } else if (c >= 0xF0u && c <= 0xF4u) {
        need = 3;
        cp = c & 0x07u;
        if (c == 0xF0u) min2 = 0x90u;
        if (c == 0xF4u) max2 = 0x8Fu;
    } else {
        *i = at + 1u;
        return 0xFFFDu;
    }
    if (len - at <= need) {
        *i = at + 1u;
        return 0xFFFDu;
    }
    for (uint32_t k = 1; k <= need; k++) {
        uint8_t d = u[at + k];
        if (d < (k == 1 ? min2 : 0x80u) || d > (k == 1 ? max2 : 0xBFu)) {
            *i = at + 1u;
            return 0xFFFDu;
        }
        cp = (cp << 6) | (d & 0x3Fu);
    }
    *i = at + need + 1u;
    return cp;
}

uint32_t zui_utf8_encode(uint32_t cp, char *out, uint32_t cap)
{
    uint8_t *o = (uint8_t *) out;
    if (cp > 0x10FFFFu || (cp >= 0xD800u && cp <= 0xDFFFu)) cp = 0xFFFDu;
    if (cp < 0x80u) {
        if (cap < 1u) return 0;
        o[0] = (uint8_t) cp;
        return 1;
    }
    if (cp < 0x800u) {
        if (cap < 2u) return 0;
        o[0] = (uint8_t) (0xC0u | (cp >> 6));
        o[1] = (uint8_t) (0x80u | (cp & 0x3Fu));
        return 2;
    }
    if (cp < 0x10000u) {
        if (cap < 3u) return 0;
        o[0] = (uint8_t) (0xE0u | (cp >> 12));
        o[1] = (uint8_t) (0x80u | ((cp >> 6) & 0x3Fu));
        o[2] = (uint8_t) (0x80u | (cp & 0x3Fu));
        return 3;
    }
    if (cap < 4u) return 0;
    o[0] = (uint8_t) (0xF0u | (cp >> 18));
    o[1] = (uint8_t) (0x80u | ((cp >> 12) & 0x3Fu));
    o[2] = (uint8_t) (0x80u | ((cp >> 6) & 0x3Fu));
    o[3] = (uint8_t) (0x80u | (cp & 0x3Fu));
    return 4;
}

/* ---- helpers -------------------------------------------------------------- */

static bool is_isolate_init(uint8_t t)
{
    return t == LRI || t == RLI || t == FSI;
}
static bool is_removed_class(uint8_t t) /* X9 */
{
    return t == RLE || t == LRE || t == RLO || t == LRO || t == PDF || t == BN;
}
static bool is_ni(uint8_t t) /* neutral or isolate formatting character */
{
    return t == B || t == S || t == WS || t == ON || t == LRI || t == RLI || t == FSI || t == PDI;
}
/* L, R or none (EN and AN count as R): the strong direction for N0..N2. */
static int strong_nx(uint8_t t)
{
    if (t == L) return L;
    if (t == R || t == AL || t == EN || t == AN) return R;
    return -1;
}

/* P2, P3 on [from, to): 0 (L), 1 (R or AL) or -1 (no strong character). */
static int first_strong(const zui_bidi_t *b, uint32_t from, uint32_t to)
{
    for (uint32_t i = from; i < to; i++) {
        uint8_t t = b->cls[i];
        if (t == L) return 0;
        if (t == R || t == AL) return 1;
        if (is_isolate_init(t)) {
            if (b->match[i] == NONE) return -1; /* the isolate runs to the end */
            i = b->match[i];
        }
    }
    return -1;
}

/* BD9: matching isolate initiators and PDIs. */
static void match_isolates(zui_bidi_t *b)
{
    uint16_t *stack = b->seq; /* free at this point */
    uint32_t sp = 0;
    for (uint32_t i = 0; i < b->n; i++) {
        b->match[i] = NONE;
        if (is_isolate_init(b->cls[i])) {
            stack[sp++] = (uint16_t) i;
        } else if (b->cls[i] == PDI && sp) {
            uint16_t o = stack[--sp];
            b->match[o] = (uint16_t) i;
            b->match[i] = o;
        }
    }
}

/* ---- B4: X1..X8 ----------------------------------------------------------- */

static void explicit_levels(zui_bidi_t *b)
{
    uint8_t lvl[ZUI_BIDI_DEPTH + 2u], ovr[ZUI_BIDI_DEPTH + 2u];
    bool iso[ZUI_BIDI_DEPTH + 2u];
    uint32_t top = 0, over_iso = 0, over_emb = 0, valid_iso = 0;
    lvl[0] = b->para_level;
    ovr[0] = ON;
    iso[0] = false;
    for (uint32_t i = 0; i < b->n; i++) {
        uint8_t t = b->cls[i];
        b->type[i] = t;
        b->removed[i] = false;
        switch (t) {
        case RLE:
        case LRE:
        case RLO:
        case LRO: {
            uint32_t nl = (t == RLE || t == RLO) ? ((lvl[top] + 1u) | 1u) : ((lvl[top] + 2u) & ~1u);
            if (nl <= ZUI_BIDI_DEPTH && over_iso == 0 && over_emb == 0) {
                top++;
                lvl[top] = (uint8_t) nl;
                ovr[top] = t == RLO ? R : t == LRO ? L : ON;
                iso[top] = false;
            } else if (over_iso == 0) {
                over_emb++;
            }
            b->removed[i] = true;
            b->level[i] = lvl[top];
            break;
        }
        case RLI:
        case LRI:
        case FSI: {
            bool rtl = t == RLI;
            if (t == FSI) {
                uint32_t to = b->match[i] == NONE ? b->n : b->match[i];
                rtl = first_strong(b, i + 1u, to) == 1;
            }
            b->level[i] = lvl[top];
            if (ovr[top] != ON) b->type[i] = ovr[top];
            uint32_t nl = rtl ? ((lvl[top] + 1u) | 1u) : ((lvl[top] + 2u) & ~1u);
            if (nl <= ZUI_BIDI_DEPTH && over_iso == 0 && over_emb == 0) {
                valid_iso++;
                top++;
                lvl[top] = (uint8_t) nl;
                ovr[top] = ON;
                iso[top] = true;
            } else {
                over_iso++;
            }
            break;
        }
        case PDI:
            if (over_iso > 0) {
                over_iso--;
            } else if (valid_iso > 0) {
                over_emb = 0;
                while (!iso[top]) top--;
                top--;
                valid_iso--;
            }
            b->level[i] = lvl[top];
            if (ovr[top] != ON) b->type[i] = ovr[top];
            break;
        case PDF:
            if (over_iso > 0) {
                /* nothing */
            } else if (over_emb > 0) {
                over_emb--;
            } else if (!iso[top] && top > 0) {
                top--;
            }
            b->removed[i] = true;
            b->level[i] = lvl[top];
            break;
        case B:
            b->level[i] = b->para_level;
            break;
        case BN:
            b->removed[i] = true;
            b->level[i] = lvl[top];
            break;
        default:
            b->level[i] = lvl[top];
            if (ovr[top] != ON) b->type[i] = ovr[top];
            break;
        }
    }
}

/* ---- B5: one isolating run sequence --------------------------------------- */

static void insertion_sort_pairs(zui_bidi_t *b, uint32_t np)
{
    for (uint32_t i = 1; i < np; i++) {
        uint16_t o = b->pair_o[i], c = b->pair_c[i];
        uint32_t j = i;
        while (j > 0 && b->pair_o[j - 1u] > o) {
            b->pair_o[j] = b->pair_o[j - 1u];
            b->pair_c[j] = b->pair_c[j - 1u];
            j--;
        }
        b->pair_o[j] = o;
        b->pair_c[j] = c;
    }
}

/* Closing brackets compared up to canonical equivalence (U+232A is U+3009;
 * only closers are compared: an opener is matched through its pair). */
static uint32_t canon_bracket(uint32_t cp)
{
    return cp == 0x232Au ? 0x3009u : cp;
}

/* N0: pair_o/pair_c hold positions in seq[]. */
static void resolve_brackets(zui_bidi_t *b, uint32_t m, uint8_t sos, uint8_t e)
{
    const uint16_t *q = b->seq;
    uint16_t open_k[ZUI_BIDI_BRACKETS];
    uint32_t open_cp[ZUI_BIDI_BRACKETS];
    uint32_t sp = 0, np = 0;
    for (uint32_t k = 0; k < m; k++) {
        uint32_t i = q[k], pair;
        if (b->type[i] != ON) continue;
        int kind = zui_bidi_bracket(b->cp[i], &pair);
        if (kind == 1) {
            if (sp == ZUI_BIDI_BRACKETS) break; /* BD16: stop for this sequence */
            open_k[sp] = (uint16_t) k;
            open_cp[sp] = canon_bracket(pair); /* the closer it waits for */
            sp++;
        } else if (kind == 2) {
            uint32_t want = canon_bracket(b->cp[i]);
            for (uint32_t s = sp; s-- > 0;) {
                if (open_cp[s] == want) {
                    b->pair_o[np] = open_k[s];
                    b->pair_c[np] = (uint16_t) k;
                    np++;
                    sp = s;
                    break;
                }
            }
        }
    }
    insertion_sort_pairs(b, np);
    for (uint32_t p = 0; p < np; p++) {
        uint32_t o = b->pair_o[p], c = b->pair_c[p];
        bool has_e = false, has_opp = false;
        for (uint32_t k = o + 1u; k < c; k++) {
            int d = strong_nx(b->type[q[k]]);
            if (d < 0) continue;
            if (d == e)
                has_e = true;
            else
                has_opp = true;
        }
        int nt = -1;
        if (has_e) {
            nt = e;
        } else if (has_opp) {
            int before = sos;
            for (uint32_t k = o; k-- > 0;) {
                int d = strong_nx(b->type[q[k]]);
                if (d >= 0) {
                    before = d;
                    break;
                }
            }
            nt = before != e ? before : e;
        }
        if (nt < 0) continue;
        uint32_t ends[2] = {o, c};
        for (int j = 0; j < 2; j++) {
            b->type[q[ends[j]]] = (uint8_t) nt;
            for (uint32_t k = ends[j] + 1u; k < m && b->cls[q[k]] == NSM; k++)
                b->type[q[k]] = (uint8_t) nt;
        }
    }
}

static void resolve_sequence(zui_bidi_t *b, uint32_t m)
{
    uint16_t *q = b->seq;
    uint8_t lev = b->level[q[0]];
    /* sos, eos (X10) */
    uint32_t first = q[0], last = q[m - 1u];
    uint8_t prev = b->para_level, next = b->para_level;
    for (uint32_t i = first; i-- > 0;) {
        if (!b->removed[i]) {
            prev = b->level[i];
            break;
        }
    }
    if (!is_isolate_init(b->type[last])) {
        for (uint32_t i = last + 1u; i < b->n; i++) {
            if (!b->removed[i]) {
                next = b->level[i];
                break;
            }
        }
    }
    uint8_t sos = ((prev > lev ? prev : lev) & 1u) ? R : L;
    uint8_t eos = ((next > lev ? next : lev) & 1u) ? R : L;

    /* W1 */
    for (uint32_t k = 0; k < m; k++) {
        if (b->type[q[k]] != NSM) continue;
        if (k == 0) {
            b->type[q[k]] = sos;
        } else {
            uint8_t p = b->type[q[k - 1u]];
            b->type[q[k]] = (is_isolate_init(p) || p == PDI) ? ON : p;
        }
    }
    /* W2, W3 */
    uint8_t strong = sos;
    for (uint32_t k = 0; k < m; k++) {
        uint8_t t = b->type[q[k]];
        if (t == L || t == R || t == AL) strong = t;
        if (t == EN && strong == AL) b->type[q[k]] = AN;
    }
    for (uint32_t k = 0; k < m; k++)
        if (b->type[q[k]] == AL) b->type[q[k]] = R;
    /* W4 */
    for (uint32_t k = 1; k + 1u < m; k++) {
        uint8_t t = b->type[q[k]], a = b->type[q[k - 1u]], c = b->type[q[k + 1u]];
        if (t == ES && a == EN && c == EN)
            b->type[q[k]] = EN;
        else if (t == CS && a == EN && c == EN)
            b->type[q[k]] = EN;
        else if (t == CS && a == AN && c == AN)
            b->type[q[k]] = AN;
    }
    /* W5 */
    for (uint32_t k = 0; k < m;) {
        if (b->type[q[k]] != ET) {
            k++;
            continue;
        }
        uint32_t e = k;
        while (e < m && b->type[q[e]] == ET) e++;
        bool en = (k > 0 && b->type[q[k - 1u]] == EN) || (e < m && b->type[q[e]] == EN);
        if (en)
            for (uint32_t j = k; j < e; j++) b->type[q[j]] = EN;
        k = e;
    }
    /* W6 */
    for (uint32_t k = 0; k < m; k++) {
        uint8_t t = b->type[q[k]];
        if (t == ES || t == ET || t == CS) b->type[q[k]] = ON;
    }
    /* W7 */
    strong = sos;
    for (uint32_t k = 0; k < m; k++) {
        uint8_t t = b->type[q[k]];
        if (t == L || t == R) strong = t;
        if (t == EN && strong == L) b->type[q[k]] = L;
    }
    /* N0 */
    uint8_t e = (lev & 1u) ? R : L;
    resolve_brackets(b, m, sos, e);
    /* N1, N2 */
    for (uint32_t k = 0; k < m;) {
        if (!is_ni(b->type[q[k]])) {
            k++;
            continue;
        }
        uint32_t end = k;
        while (end < m && is_ni(b->type[q[end]])) end++;
        int before = k == 0 ? sos : strong_nx(b->type[q[k - 1u]]);
        int after = end == m ? eos : strong_nx(b->type[q[end]]);
        uint8_t nt = (before == after && before >= 0) ? (uint8_t) before : e;
        for (uint32_t j = k; j < end; j++) b->type[q[j]] = nt;
        k = end;
    }
}

/* X10: level runs, then each isolating run sequence (BD13). */
static void implicit_levels(zui_bidi_t *b)
{
    uint32_t nr = 0;
    int last_level = -1;
    for (uint32_t i = 0; i < b->n; i++) {
        if (b->removed[i]) continue;
        if (b->level[i] != last_level) {
            b->run_lo[nr] = (uint16_t) i;
            nr++;
            last_level = b->level[i];
        }
        b->run[i] = (uint16_t) (nr - 1u);
        b->run_hi[nr - 1u] = (uint16_t) i;
    }
    for (uint32_t r = 0; r < nr; r++) {
        uint32_t f = b->run_lo[r];
        if (b->cls[f] == PDI && b->match[f] != NONE) continue; /* continues a sequence */
        uint32_t m = 0, cur = r;
        for (;;) {
            for (uint32_t i = b->run_lo[cur]; i <= b->run_hi[cur]; i++)
                if (!b->removed[i]) b->seq[m++] = (uint16_t) i;
            uint32_t l = b->run_hi[cur];
            if (!is_isolate_init(b->cls[l]) || b->match[l] == NONE) break;
            cur = b->run[b->match[l]];
        }
        resolve_sequence(b, m);
    }
    /* I1, I2: after every sequence, so sos and eos above saw explicit levels */
    for (uint32_t i = 0; i < b->n; i++) {
        uint8_t t = b->type[i];
        if (b->removed[i]) continue;
        if (!(b->level[i] & 1u)) {
            if (t == R)
                b->level[i] += 1u;
            else if (t == AN || t == EN)
                b->level[i] += 2u;
        } else if (t == L || t == EN || t == AN) {
            b->level[i] += 1u;
        }
    }
    /* the removed characters draw at the level before them */
    for (uint32_t i = 0; i < b->n; i++)
        if (b->removed[i]) b->level[i] = i ? b->level[i - 1u] : b->para_level;
}

/* ---- B2, B3: a paragraph -------------------------------------------------- */

uint32_t zui_bidi_paragraph(zui_bidi_t *b, const char *utf8, uint32_t len, zui_bidi_dir_t dir)
{
    uint32_t i = 0, n = 0, end_kept = 0;
    b->truncated = false;
    while (utf8 && i < len) {
        uint32_t at = i;
        uint32_t cp = zui_utf8_decode(utf8, len, &i);
        uint8_t c = (uint8_t) zui_bidi_class(cp);
        if (n < ZUI_BIDI_MAX) {
            b->cp[n] = cp;
            b->off[n] = at;
            b->cls[n] = c;
            n++;
            end_kept = i;
        } else {
            b->truncated = true;
        }
        if (c == B) break;
    }
    b->n = n;
    b->bytes = i;
    b->off[n] = end_kept;
    match_isolates(b);
    if (dir == ZUI_BIDI_AUTO) {
        int f = first_strong(b, 0, n);
        b->para_level = f == 1 ? 1u : 0u;
    } else {
        b->para_level = dir == ZUI_BIDI_RTL ? 1u : 0u;
    }
    explicit_levels(b);
    implicit_levels(b);
    return b->bytes;
}

/* ---- B6: a line ------------------------------------------------------------ */

static bool l1_trailing(const zui_bidi_t *b, uint32_t i)
{
    uint8_t c = b->cls[i];
    return c == WS || is_isolate_init(c) || c == PDI || is_removed_class(c);
}

uint32_t zui_bidi_line(const zui_bidi_t *b, uint32_t start, uint32_t end, uint8_t *levels,
                       uint16_t *order, bool keep_removed)
{
    uint8_t lv[ZUI_BIDI_MAX];
    if (end > b->n) end = b->n;
    if (start >= end) return 0;
    uint32_t n = end - start;
    /* L1 */
    for (uint32_t k = 0; k < n; k++) lv[k] = b->level[start + k];
    bool tail = true; /* walking back from the end of the line */
    for (uint32_t k = n; k-- > 0;) {
        uint8_t c = b->cls[start + k];
        if (c == S || c == B) {
            lv[k] = b->para_level;
            tail = true;
        } else if (tail && l1_trailing(b, start + k)) {
            lv[k] = b->para_level;
        } else {
            tail = false;
        }
    }
    if (levels)
        for (uint32_t k = 0; k < n; k++) levels[k] = lv[k];
    if (!order) return 0;
    /* L2 */
    uint32_t cnt = 0;
    uint8_t hi = 0, lo_odd = 0xFF;
    for (uint32_t k = 0; k < n; k++) {
        if (!keep_removed && b->removed[start + k]) continue;
        order[cnt++] = (uint16_t) (start + k);
        if (lv[k] > hi) hi = lv[k];
        if ((lv[k] & 1u) && lv[k] < lo_odd) lo_odd = lv[k];
    }
    for (uint32_t L2 = hi; L2 >= lo_odd && L2 > 0; L2--) {
        for (uint32_t v = 0; v < cnt;) {
            if (lv[order[v] - start] < L2) {
                v++;
                continue;
            }
            uint32_t e = v;
            while (e < cnt && lv[order[e] - start] >= L2) e++;
            for (uint32_t a = v, z = e - 1u; a < z; a++, z--) {
                uint16_t t = order[a];
                order[a] = order[z];
                order[z] = t;
            }
            v = e;
        }
    }
    return cnt;
}

/* ---- B8 ------------------------------------------------------------------- */

uint32_t zui_bidi_visual(const zui_bidi_t *b, uint32_t start, uint32_t end, char *out, uint32_t cap)
{
    uint16_t order[ZUI_BIDI_MAX];
    uint8_t lv[ZUI_BIDI_MAX];
    uint32_t w = 0;
    if (!out || cap == 0) return 0;
    if (end > b->n) end = b->n;
    uint32_t cnt = zui_bidi_line(b, start, end, lv, order, false);
    for (uint32_t v = 0; v < cnt;) {
        uint32_t i = order[v];
        uint32_t from = v, to = v + 1u; /* emit order[from..to) */
        bool flip = false;
        /* L3-like: in a right-to-left run the marks have come out before their
         * base; put the base first again so a plain drawer stacks them. */
        if ((lv[i - start] & 1u) && b->cls[i] == NSM) {
            uint32_t j = v;
            while (j < cnt && b->cls[order[j]] == NSM && (lv[order[j] - start] & 1u)) j++;
            if (j < cnt) {
                to = j + 1u;
                flip = true;
            }
        }
        for (uint32_t k = 0; k < to - from; k++) {
            uint32_t at = flip ? order[to - 1u - k] : order[from + k];
            uint32_t cp = b->cp[at];
            if (lv[at - start] & 1u) cp = zui_bidi_mirror(cp);
            uint32_t len = zui_utf8_encode(cp, out + w, cap - 1u - w);
            if (!len) {
                out[w] = 0;
                return w;
            }
            w += len;
        }
        v = to;
    }
    out[w] = 0;
    return w;
}
