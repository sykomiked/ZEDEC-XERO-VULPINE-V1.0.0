# gen_fixtures.sh — compile the ASL test fixtures with iasl (acpica-tools) and
# write their AML bytes into aml_fixtures.h, which is committed so CI and the
# host tests never need iasl. Run it after editing any fixtures/*.asl:
#
#   bash kernel/src/acpi/test/gen_fixtures.sh
#
# -oa turns off every iasl optimization (constant folding in particular), so
# the opcodes written in the ASL are the opcodes the interpreter runs.
set -euo pipefail
cd "$(dirname "$0")"
command -v iasl >/dev/null || { echo "iasl not found (apt install acpica-tools)"; exit 1; }
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
out=aml_fixtures.h
{
  echo "/* Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC */"
  echo "/* SPDX-License-Identifier: Apache-2.0 */"
  echo "/* aml_fixtures.h — GENERATED by gen_fixtures.sh from the fixtures directory"
  echo " * ($(iasl -v 2>/dev/null | grep -o 'version [0-9]*' | head -1)). Do not edit. */"
  echo "#ifndef ZXV_AML_FIXTURES_H"
  echo "#define ZXV_AML_FIXTURES_H"
  echo "#include <stdint.h>"
} > "$out"
for asl in fixtures/*.asl; do
  name=$(basename "$asl" .asl)
  iasl -oa -p "$tmp/$name" "$asl" > "$tmp/$name.log" 2>&1 || { cat "$tmp/$name.log"; exit 1; }
  python3 -I - "$tmp/$name.aml" "$name" >> "$out" <<'PY'
import sys
data = open(sys.argv[1], 'rb').read()
name = sys.argv[2]
print("static const uint8_t fx_%s[%d] = {" % (name, len(data)))
for i in range(0, len(data), 16):
    print("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")
print("};")
PY
done
echo "#endif" >> "$out"
echo "wrote $(pwd)/$out"
