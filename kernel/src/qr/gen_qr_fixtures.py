"""Generate qr_fixtures.h: reference QR symbols for test_qr.c.

Each fixture is a byte-mode, level-M symbol made by two independent
encoders, python-qrcode and Project Nayuki's qrcodegen, and read back by an
independent decoder, zxing-cpp. A fixture is written only when both encoders
produce the same module matrix AND the decoder returns exactly the input
bytes at level M.

Automatic mask choice (ISO/IEC 18004 7.8.3, penalty rules N1-N4): the
fixture records the mask qrcodegen chose. python-qrcode's penalty scoring
does not follow the standard exactly and picks a different mask for some
inputs. For those cases python-qrcode still confirms the symbol at the mask
qrcodegen chose, but the choice itself rests on qrcodegen; the script
reports how many there were.

segno 1.6.6 was tried as a second reference and is NOT used for exact
comparison. Its write_padding_bits adds 8 - (length % 8) zero bits, which is
8, not 0, when the data plus the 4-bit terminator already end on a byte
boundary (always the case in byte mode), so it emits one extra 0x00 codeword
before the 0xEC/0x11 pad bytes whenever there is room; ISO/IEC 18004 7.4.10
adds padding bits only when the stream does not end on a boundary. Decoders
accept both, but the module matrices differ. The script reports how many
fixtures segno matches anyway (the ones with no room for the extra byte).

    python3 -m venv venv && venv/bin/pip install qrcode segno zxing-cpp numpy
    venv/bin/pip install qrcodegen
    venv/bin/python -I gen_qr_fixtures.py > qr_fixtures.h
"""
import hashlib
import sys

import qrcode
import qrcode.util
import qrcodegen
import numpy as np
import segno
import zxingcpp


def data_for(i, n):
    out = b""
    k = 0
    while len(out) < n:
        out += hashlib.sha256(b"zxv-qr-%d-%d" % (i, k)).digest()
        k += 1
    return out[:n]


def segno_matrix(data, version, mask):
    q = segno.make_qr(data, error="m", mode="byte", version=version, mask=mask, boost_error=False)
    return q.version, q.mask, [list(r) for r in q.matrix]


def qrcode_matrix(data, version, mask):
    q = qrcode.QRCode(version=version, error_correction=qrcode.constants.ERROR_CORRECT_M,
                      mask_pattern=mask, border=0)
    q.add_data(qrcode.util.QRData(data, mode=qrcode.util.MODE_8BIT_BYTE))
    q.make(fit=version is None)
    m = [[1 if c else 0 for c in row] for row in q.get_matrix()]
    return q.version, m


def nayuki_matrix(data, version, mask):
    lo, hi = (version, version) if version else (1, 10)
    q = qrcodegen.QrCode.encode_segments([qrcodegen.QrSegment.make_bytes(data)],
                                         qrcodegen.QrCode.Ecc.MEDIUM, lo, hi,
                                         -1 if mask is None else mask, False)
    n = q.get_size()
    return q.get_version(), q.get_mask(), [[1 if q.get_module(x, y) else 0 for x in range(n)]
                                           for y in range(n)]


def mask_of(mat):
    """Mask number from the first copy of the format information."""
    bits = [mat[8][i] for i in (0, 1, 2, 3, 4, 5, 7)] + [mat[8][8], mat[7][8]]
    bits += [mat[i][8] for i in (5, 4, 3, 2, 1, 0)]
    v = sum(b << (14 - k) for k, b in enumerate(bits)) ^ 0x5412
    return (v >> 10) & 7


CAP_M = [0, 14, 26, 42, 62, 84, 106, 122, 152, 180, 213]

cases = []  # (data, version_req, mask_req)
i = 0
for v in range(1, 11):                      # every version, full capacity, auto mask
    cases.append((data_for(i, CAP_M[v]), None, None)); i += 1
    cases.append((data_for(i, CAP_M[v - 1] + 1), None, None)); i += 1   # smallest that needs v
for m in range(8):                          # every mask at v1, v5 and v7 (version info)
    for v in (1, 5, 7):
        cases.append((data_for(i, 10), v, m)); i += 1
cases.append((b"hello world", None, None))
cases.append((b"ZTP1:" + b"a" * 77, None, None))

def decodes_to(mat, data):
    m = np.pad(np.array(mat, dtype=np.uint8), 4)
    img = np.kron((1 - m) * 255, np.ones((6, 6), dtype=np.uint8)).astype(np.uint8)
    r = zxingcpp.read_barcodes(img)
    return len(r) == 1 and r[0].bytes == data and r[0].ec_level == "M"


print("/* Generated by gen_qr_fixtures.py: python-qrcode and qrcodegen agree on every"
      " symbol, and zxing-cpp reads each back. Do not edit. */")
print("#ifndef QR_FIXTURES_H\n#define QR_FIXTURES_H\n#include <stdint.h>")
print("typedef struct { const char *data_hex; unsigned len; int version_req; int mask_req;"
      " int version; int mask; const char *rows_hex; } qr_fixture_t;")
print("static const qr_fixture_t QR_FIXTURES[] = {")
n = 0
segno_same = 0
pyqr_auto_differs = 0
for data, vreq, mreq in cases:
    nv, nm, nmat = nayuki_matrix(data, vreq, mreq)
    qv, qmat = qrcode_matrix(data, nv, nm)           # same version and mask
    _, _, smat = segno_matrix(data, nv, nm)
    if qv != nv or qmat != nmat or mask_of(nmat) != nm:
        print("encoders disagree: len=%d v=%s m=%s" % (len(data), vreq, mreq), file=sys.stderr)
        continue
    if not decodes_to(nmat, data):
        print("not decodable: len=%d v=%s m=%s" % (len(data), vreq, mreq), file=sys.stderr)
        continue
    if mreq is None:
        _, qauto = qrcode_matrix(data, None, None)
        pyqr_auto_differs += mask_of(qauto) != nm
    segno_same += smat == nmat
    rows = ""
    for r in nmat:
        bits = "".join(str(b) for b in r) + "0" * ((8 - len(r) % 8) % 8)
        rows += "".join("%02x" % int(bits[k:k + 8], 2) for k in range(0, len(bits), 8))
    print('  {"%s", %d, %d, %d, %d, %d,\n   "%s"},' % (data.hex(), len(data), vreq or 0,
                                                    -1 if mreq is None else mreq, nv, nm, rows))
    n += 1
print("};")
print("#define QR_N_FIXTURES %d" % n)
print("#endif")
print("%d fixtures, segno identical on %d, python-qrcode auto mask differs on %d"
      % (n, segno_same, pyqr_auto_differs), file=sys.stderr)
