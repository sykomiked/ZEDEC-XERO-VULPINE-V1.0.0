# Generate zt_whisper_tables.h for zt_whisper.c's log-mel front end (T25):
#   ZT_WH_COS400[i] = round(cos(2 pi i / 400) * 2^30), i < 400: the DFT's
#       cosines (sine k is cosine (k + 300) mod 400) and the periodic Hann
#       window, w[n] = (1 - cos(2 pi n / 400)) / 2.
#   ZT_WH_LOG10_2_Q32 = round(log10(2) * 2^32).
# Every value is computed with 60-digit decimal arithmetic (Taylor series on
# [0, pi/2], extended by symmetry) and rounded half to even, so the file is
# reproducible.
# Usage: python3 gen_whisper_tables.py zt_whisper_tables.h
import sys
from decimal import Decimal, getcontext
getcontext().prec = 60


def pi():
    def atan_inv(x):
        x = Decimal(x); t = 1 / x; s = t; n = 1; x2 = x * x
        while True:
            t /= -x2; n += 2; d = t / n
            if abs(d) < Decimal(10) ** -58: return s
            s += d
    return 16 * atan_inv(5) - 4 * atan_inv(239)


PI = pi()


def cos(x):
    s, t, n = Decimal(0), Decimal(1), 0
    while True:
        s += t
        n += 2
        t = -t * x * x / (n * (n - 1))
        if abs(t) < Decimal(10) ** -58: return s + t


def rnd(d): return int(d.to_integral_value(rounding='ROUND_HALF_EVEN'))


Q = Decimal(2) ** 30
cs = []
for i in range(400):
    k, sgn = i, 1
    if k > 200: k = 400 - k
    if k > 100: k, sgn = 200 - k, -1
    cs.append(sgn * rnd(cos(2 * PI * k / 400) * Q))
log10_2 = Decimal(2).ln() / Decimal(10).ln()
out = ['/* zt_whisper_tables.h — generated by gen_whisper_tables.py. Do not edit. */',
       '#include <stdint.h>',
       '#define ZT_WH_LOG10_2_Q32 %dll /* log10(2) * 2^32 */' % rnd(log10_2 * Decimal(2) ** 32),
       '/* cos(2 pi i / 400) in Q30 */',
       'static const int32_t ZT_WH_COS400[400] = {']
for i in range(0, 400, 8): out.append('    ' + ', '.join(str(v) for v in cs[i:i + 8]) + ',')
out.append('};')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
