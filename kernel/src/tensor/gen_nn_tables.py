# Generate zt_nn_tables.h for zt_nn.c: the gates of the activation functions
# the encoders use, in Q30, at steps of 2^-8 (linear interpolation between
# entries adds at most about 5e-7). Every entry is computed with 60-digit
# decimal arithmetic and rounded to nearest, so the file is reproducible.
#   ZT_NN_PHI[i]   = Phi(x) = (1 + erf(x / sqrt 2)) / 2, x = -8 + i/256 (GELU, exact form)
#   ZT_NN_GTANH[i] = (1 + tanh(sqrt(2/pi) (x + 0.044715 x^3))) / 2, same x (GELU, tanh form)
#   ZT_NN_SIG[i]   = 1 / (1 + e^-x), x = -16 + i/256 (sigmoid, SiLU)
# Usage: python3 gen_nn_tables.py zt_nn_tables.h
import sys
from decimal import Decimal, getcontext
getcontext().prec = 60
def pi():
    def atan_inv(x):
        x = Decimal(x); t = 1 / x; s = t; n = 1; x2 = x * x
        while True:
            t /= -x2; n += 2; d = t / n
            if abs(d) < Decimal(10) ** -58: return s
            s += d
    return 16 * atan_inv(5) - 4 * atan_inv(239)
PI = pi()
def erf(x):
    # Maclaurin series for |x| <= 3, continued fraction (erfc) beyond
    if x < 0: return -erf(-x)
    if x <= 3:
        s, t, n = Decimal(0), x, 0
        while True:
            d = t / (2 * n + 1)
            if abs(d) < Decimal(10) ** -58: break
            s += d; n += 1; t = -t * x * x / n
        return 2 / PI.sqrt() * s
    # erfc(x) = e^-x^2 / sqrt(pi) * 1/(x + 1/2/(x + 1/(x + 3/2/(x + ...))))
    f = Decimal(0)
    for k in range(400, 0, -1): f = (Decimal(k) / 2) / (x + f)
    return 1 - (-x * x).exp() / PI.sqrt() / (x + f)
def tanh(x):
    e = (2 * x).exp(); return (e - 1) / (e + 1)
def rnd(d): return int(d.to_integral_value(rounding='ROUND_HALF_EVEN'))
Q = Decimal(2) ** 30
S2 = Decimal(2).sqrt(); K = (2 / PI).sqrt(); C = Decimal('0.044715')
phi = [rnd((1 + erf((Decimal(-8) + Decimal(i) / 256) / S2)) / 2 * Q) for i in range(4097)]
gt = []
for i in range(4097):
    x = Decimal(-8) + Decimal(i) / 256
    gt.append(rnd((1 + tanh(K * (x + C * x * x * x))) / 2 * Q))
sig = [rnd(1 / (1 + (-(Decimal(-16) + Decimal(i) / 256)).exp()) * Q) for i in range(8193)]
out = ['/* zt_nn_tables.h — generated by gen_nn_tables.py. Do not edit. */', '#include <stdint.h>']
def emit(name, vals, what):
    out.append('/* %s */' % what)
    out.append('static const int32_t %s[%d] = {' % (name, len(vals)))
    for i in range(0, len(vals), 8): out.append('    ' + ', '.join(str(v) for v in vals[i:i + 8]) + ',')
    out.append('};')
emit('ZT_NN_PHI', phi, 'Phi(x) in Q30, x = -8 + i / 256')
emit('ZT_NN_GTANH', gt, '(1 + tanh(sqrt(2/pi)(x + 0.044715 x^3))) / 2 in Q30, x = -8 + i / 256')
emit('ZT_NN_SIG', sig, '1 / (1 + e^-x) in Q30, x = -16 + i / 256')
open(sys.argv[1], 'w').write('\n'.join(out) + '\n')
