/* zt_nn.h — integer building blocks for the networks that sit beside the
 * language model: the image encoder (zt_vision), speech in (zt_whisper) and
 * speech out (zt_tts).
 *
 *   T23 ENCODER BLOCKS.  The same arithmetic as the forward pass (zt_model.h):
 *       activations are Q16 (zt_fx); a matrix product quantises each input
 *       into 16-bit blocks of 32 with a power-of-two exponent and uses
 *       zt_kern.h's kernels (the C reference, or a hosted SIMD/threaded set
 *       that gives the same bits); attention scores and weighted sums are
 *       exact 64-bit integers. What is new here:
 *         - matrices of any GGUF float or block type and any shape: GGUF Q8_0
 *           (and Q4_K/Q6_K with 256-multiple rows) are used in place; other
 *           types, and rows whose length is not a multiple of 32 (a
 *           convolution's in_channels x kernel), are converted once into
 *           zt_q8_t blocks, zero-padded to a multiple of 32;
 *         - LayerNorm with bias (mean rounded to Q16, then rmsnorm's exact
 *           64-bit sum of squares and 1/sqrt);
 *         - GELU (exact erf form and tanh form) and sigmoid/SiLU from Q30
 *           tables at steps of 2^-8 with linear interpolation (generated by
 *           gen_nn_tables.py with 60-digit arithmetic; interpolation error
 *           below 5e-7 of the gate);
 *         - non-causal (or causal) multi-head attention between any query
 *           and key sequences (self- and cross-attention);
 *         - 1-D convolution as im2col plus a matrix product, depthwise 1-D
 *           convolution in 64 bits, and GroupNorm.
 *       Rows of a batch are independent, so a hosted caller may split them
 *       across threads (zt_kern_t.par_rows) without changing a bit.
 * Freestanding: no libc, no malloc, no floating point; 64-bit divisions only
 * through zt_udiv64, a few per normalised row. */
#ifndef ZT_NN_H
#define ZT_NN_H

#include <stdint.h>
#include <stdbool.h>
#include "zt.h"
#include "zt_gguf.h"
#include "zt_model.h"

enum {
    ZT_NN_EMISSING = -40, /* a tensor or key is absent */
    ZT_NN_ESHAPE = -41,   /* a tensor has the wrong shape */
    ZT_NN_ESPACE = -42,   /* a caller buffer is too small */
    ZT_NN_EARG = -43,     /* bad argument */
    ZT_NN_ECONFIG = -44   /* metadata out of range */
};

/* ---- loading: a two-pass arena (one walk sizes it, a second fills it) ---- */
typedef struct {
    uint8_t *base; /* null while sizing */
    uint64_t used, cap;
    zt_fx *scratch; /* one dequantised row, cols_max values */
    uint32_t cols_max;
    zt_model_err_t *err;
} zt_nn_arena_t;

/* Start a pass. Sizing: base = 0 (cap ignored). Filling: base/cap are the
 * caller's memory. cols_max is the longest matrix row the pass will convert. */
void zt_nn_arena_begin(zt_nn_arena_t *a, void *base, uint64_t cap, uint32_t cols_max,
                       zt_model_err_t *err);
/* Bytes taken so far (after a sizing pass: what to allocate, plus 64). */
uint64_t zt_nn_arena_used(const zt_nn_arena_t *a);
void *zt_nn_take(zt_nn_arena_t *a, uint64_t bytes);
bool zt_nn_filling(const zt_nn_arena_t *a);

/* A tensor of exactly cols x rows elements (dims[0] * ... * dims[n-2] == cols
 * and dims[n-1] == rows, or a 1-D tensor of cols elements when rows == 0). */
int32_t zt_nn_tensor(const zt_gguf_t *g, const char *name, uint64_t cols, uint64_t rows,
                     zt_gguf_tensor_t *t, zt_model_err_t *err);
bool zt_nn_has(const zt_gguf_t *g, const char *name);
/* A matrix of rows x cols. out->cols is cols rounded up to 32 (the padding
 * is zero). */
int32_t zt_nn_load_mat(zt_nn_arena_t *a, const zt_gguf_t *g, const char *name, uint32_t cols,
                       uint32_t rows, zt_mat_t *out);
/* A vector of n values as Q16 (biases, embeddings, position tables). */
int32_t zt_nn_load_q16(zt_nn_arena_t *a, const zt_gguf_t *g, const char *name, uint64_t n,
                       const zt_fx **out);
/* A vector of n values with as many fraction bits as fit 32 bits (up to 24):
 * norm gains, depthwise kernels, layer scales. */
int32_t zt_nn_load_gain(zt_nn_arena_t *a, const zt_gguf_t *g, const char *name, uint64_t n,
                        zt_gain_t *out);
/* An f32 key (architecture constants), as raw bits; def when absent. */
uint32_t zt_nn_f32_key(const zt_gguf_t *g, const char *key, uint32_t def);
/* round(f32 * 2^frac), saturating at +-2^62 (NaN is 0). */
int64_t zt_nn_f32_fixed(uint32_t bits, int32_t frac);

/* ---- compute context ---- */
typedef struct {
    const struct zt_kern *kern; /* null: the portable C reference */
    uint32_t max_tok, max_cols, max_keys, max_hd, items;
    int16_t *a16;  /* [max_tok][max_cols] */
    uint8_t *ash;  /* [max_tok][max_cols / 32] */
    int32_t *asum; /* [max_tok][max_cols / 32] */
    int16_t *aT;   /* batched kernels' token-major copy */
    int64_t *ashT, *asumT;
    uint8_t *ashx;
    zt_fx *scores;  /* [items][max_keys] */
    int64_t *acc;   /* [items][max_hd] */
    int32_t *qs;    /* [items][max_hd] */
    uint32_t n_sat; /* values that hit the Q16 range limit (as zt_model_state_t.n_sat) */
} zt_nn_t;

#define ZT_NN_ATT_TILES 8u

/* max_tok: tokens per matrix product call (longer inputs go through in
 * chunks); max_cols: longest input row; max_keys / max_hd: longest key
 * sequence and head size of any attention; max_heads: most heads. */
uint64_t zt_nn_bytes(uint32_t max_tok, uint32_t max_cols, uint32_t max_keys, uint32_t max_hd,
                     uint32_t max_heads);
int32_t zt_nn_init(zt_nn_t *nn, uint32_t max_tok, uint32_t max_cols, uint32_t max_keys,
                   uint32_t max_hd, uint32_t max_heads, void *mem, uint64_t bytes);

/* y[t][r] = W[r] . x[t] (+ bias[r]) for T inputs of n_in values each
 * (n_in <= w->cols; the rest of the row is zero). */
void zt_nn_linear(zt_nn_t *nn, const zt_mat_t *w, const zt_fx *bias, const zt_fx *x,
                  uint32_t xstride, uint32_t n_in, uint32_t T, zt_fx *y, uint32_t ystride);

/* LayerNorm (b may be null: no bias) of T rows of n values, eps as f32 bits. */
typedef struct {
    zt_gain_t g;
    const zt_fx *b;
} zt_nn_norm_t;
void zt_nn_layernorm(zt_nn_t *nn, const zt_fx *x, uint32_t xstride, uint32_t n, uint32_t T,
                     const zt_nn_norm_t *p, uint32_t eps_f32, zt_fx *y, uint32_t ystride);
/* RMS norm (gain only). */
void zt_nn_rmsnorm(zt_nn_t *nn, const zt_fx *x, uint32_t xstride, uint32_t n, uint32_t T,
                   const zt_gain_t *g, uint32_t eps_f32, zt_fx *y, uint32_t ystride);
/* GroupNorm over a [T][C] sequence (channels last): G groups of C / G
 * channels, each normalised over all T steps, then per-channel gain and bias. */
void zt_nn_groupnorm(zt_fx *x, uint32_t xstride, uint32_t T, uint32_t C, uint32_t G,
                     const zt_nn_norm_t *p, uint32_t eps_f32);

enum { ZT_NN_GELU_ERF = 0, ZT_NN_GELU_TANH = 1, ZT_NN_SILU = 2, ZT_NN_SIGMOID = 3 };
zt_fx zt_nn_act1(zt_fx x, uint32_t kind);
/* In place on T rows of n values. */
void zt_nn_act(zt_nn_t *nn, zt_fx *x, uint32_t xstride, uint32_t n, uint32_t T, uint32_t kind);
/* x[t][i] += y[t][i], saturating (counted in nn->n_sat). */
void zt_nn_add(zt_nn_t *nn, zt_fx *x, uint32_t xstride, const zt_fx *y, uint32_t ystride,
               uint32_t n, uint32_t T);

/* Multi-head attention: out[i] (n_head * hd values) for query rows q[i]
 * against key and value rows k[j], v[j] (head h reads columns h*hd..). With
 * causal, query i sees keys 0 .. i + n_k - n_q only. The scores are scaled by
 * 1/sqrt(hd). n_k <= max_keys, hd <= max_hd, n_head <= max_heads. */
void zt_nn_attention(zt_nn_t *nn, const zt_fx *q, uint32_t qstride, const zt_fx *k,
                     uint32_t kstride, const zt_fx *v, uint32_t vstride, uint32_t n_q, uint32_t n_k,
                     uint32_t n_head, uint32_t hd, bool causal, zt_fx *out, uint32_t ostride);

/* 1-D convolution inputs: out[t] = x[t*stride - pad + j][c] laid out as
 * column c*K + j (GGUF's [K, C_in, C_out] kernel order); x is [T][C]
 * (channels last). Returns T_out = (T + 2 pad - K) / stride + 1. */
uint32_t zt_nn_im2col1d(const zt_fx *x, uint32_t xstride, uint32_t T, uint32_t C, uint32_t K,
                        uint32_t stride, uint32_t pad, zt_fx *out, uint32_t ostride);
/* Depthwise 1-D convolution, stride 1: y[t][c] = sum_j w[c*K + j] x[t - pad + j][c] + b[c]
 * (64-bit sums, w with w->frac fraction bits). y must not alias x. */
void zt_nn_dwconv1d(const zt_fx *x, uint32_t xstride, uint32_t T, uint32_t C, uint32_t K,
                    uint32_t pad, const zt_gain_t *w, const zt_fx *b, zt_fx *y, uint32_t ystride);

#endif /* ZT_NN_H */
