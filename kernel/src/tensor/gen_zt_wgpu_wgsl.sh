# gen_zt_wgpu_wgsl.sh OUT.h — writes zt_wgpu.wgsl as one C string, zw_wgsl,
# for zt_wgpu.c (which puts its size constants in front of it at run time).
# Comment-only lines are dropped; nothing else changes. Needs only sh and sed.
set -e
out=${1:?usage: gen_zt_wgpu_wgsl.sh OUT.h}
dir=$(dirname "$0")
tmp="$out.tmp"
{
    echo "/* generated by gen_zt_wgpu_wgsl.sh from zt_wgpu.wgsl: do not edit */"
    echo "static const char zw_wgsl[] ="
    sed -e '/^[[:space:]]*\/\//d' -e '/^[[:space:]]*$/d' -e 's/\\/\\\\/g' -e 's/"/\\"/g' \
        -e 's/^/    "/' -e 's/$/\\n"/' "$dir/zt_wgpu.wgsl"
    echo "    ;"
} >"$tmp"
mv "$tmp" "$out"
