# gen_zvt_vk_spv.sh OUT.h — builds zvt_vk.comp once per stage with
# glslangValidator and writes one C header holding every SPIR-V module and
# the table zvt_vk.c reads (zvv_mods). Exits 1 without glslangValidator.
set -e
out=${1:?usage: gen_zvt_vk_spv.sh OUT.h}
dir=$(dirname "$0")
command -v glslangValidator >/dev/null 2>&1 || { echo "glslangValidator not found" >&2; exit 1; }
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
ks="0 1 2 3 4 5"
{
    echo "/* generated by gen_zvt_vk_spv.sh from zvt_vk.comp: do not edit */"
    for k in $ks; do
        glslangValidator -S comp --target-env vulkan1.1 -DZK="$k" --vn "zvv_spv_$k" \
            -o "$tmp/k$k.h" "$dir/zvt_vk.comp" >"$tmp/log" 2>&1 || { cat "$tmp/log" >&2; exit 1; }
        sed -e '/#pragma once/d' -e 's/^const uint32_t/static const uint32_t/' "$tmp/k$k.h"
    done
    echo "static const struct {"
    echo "    uint32_t zk;"
    echo "    const uint32_t *code;"
    echo "    size_t bytes;"
    echo "} zvv_mods[] = {"
    for k in $ks; do echo "    {$k, zvv_spv_$k, sizeof zvv_spv_$k},"; done
    echo "};"
} >"$out"
