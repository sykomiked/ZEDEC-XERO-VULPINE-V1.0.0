"""Generate trust_roots.h: the root certificates compiled into the kernel.

Usage: gen_trust_roots.py CA_BUNDLE.pem > trust_roots.h

CA_BUNDLE.pem is the Mozilla CA program bundle (the one Python's certifi
ships). Only the roots named in ROOTS are taken: the CAs that issue most
public web server certificates. Each is checked to be in the bundle exactly
once, and its SHA-256 fingerprint is written next to it so a reviewer can
compare against https://ccadb.org. Owners can add their own roots at run
time with tls_trust_add_der().
"""
import base64
import hashlib
import re
import subprocess
import sys

ROOTS = [
    "ISRG Root X1", "ISRG Root X2",
    "GTS Root R1", "GTS Root R3", "GTS Root R4",
    "GlobalSign Root CA - R3", "GlobalSign ECC Root CA - R4", "GlobalSign ECC Root CA - R5",
    "GlobalSign Root CA - R6", "GlobalSign Root R46", "GlobalSign Root E46",
    "DigiCert Global Root G2", "DigiCert Global Root G3",
    "DigiCert TLS RSA4096 Root G5", "DigiCert TLS ECC P384 Root G5",
    "Amazon Root CA 1", "Amazon Root CA 2", "Amazon Root CA 3", "Amazon Root CA 4",
    "Starfield Services Root Certificate Authority - G2",
    "USERTrust RSA Certification Authority", "USERTrust ECC Certification Authority",
    "Sectigo Public Server Authentication Root R46",
    "Sectigo Public Server Authentication Root E46",
    "Go Daddy Root Certificate Authority - G2",
    "Starfield Root Certificate Authority - G2",
    "Microsoft RSA Root Certificate Authority 2017",
    "Microsoft ECC Root Certificate Authority 2017",
    "SSL.com TLS RSA Root CA 2022", "SSL.com TLS ECC Root CA 2022",
    "Certum Trusted Network CA", "Certum Trusted Network CA 2",
    "QuoVadis Root CA 2 G3",

]


def cn_of(der):
    out = subprocess.run(["openssl", "x509", "-inform", "DER", "-noout", "-subject",
                          "-nameopt", "multiline"], input=der, capture_output=True).stdout.decode()
    m = re.search(r"commonName\s*=\s*(.*)", out)
    ou = re.search(r"organizationalUnitName\s*=\s*(.*)", out)
    if m and m.group(1).strip() == "GlobalSign" and ou:
        return ou.group(1).strip()  # GlobalSign names its roots in the OU
    if m:
        return m.group(1).strip()
    m = re.search(r"organizationalUnitName\s*=\s*(.*)", out)
    return m.group(1).strip() if m else ""


def c_string(b):
    s = []
    for x in b:
        ch = chr(x)
        if 0x20 <= x < 0x7f and ch not in '"\\?':
            s.append(ch)
        else:
            s.append("\\%03o" % x)
    return "".join(s)


def main():
    pems = re.findall(r"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----",
                      open(sys.argv[1]).read(), re.S)
    by_cn = {}
    for p in pems:
        der = base64.b64decode("".join(p.split()))
        by_cn.setdefault(cn_of(der), []).append(der)
    out = sys.stdout
    out.write("/* trust_roots.h — root certificates compiled into the kernel.\n"
              " * Generated by gen_trust_roots.py from the Mozilla CA program bundle. Do not\n"
              " * edit; regenerate. Each entry: subject common name and SHA-256 fingerprint.\n"
              " *\n"
              " * Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC\n"
              " * SPDX-License-Identifier: Apache-2.0\n"
              " */\n#ifndef ZXV_TLS_TRUST_ROOTS_H\n#define ZXV_TLS_TRUST_ROOTS_H\n\n"
              "#include <stdint.h>\n\n"
              "typedef struct {\n    const char *name;\n    const uint8_t *der;\n"
              "    uint32_t len;\n} tls_builtin_root_t;\n\n"
              "static const tls_builtin_root_t tls_builtin_roots[] = {\n")
    n = 0
    for name in ROOTS:
        ders = by_cn.get(name, [])
        if len(ders) != 1:
            sys.exit("root %r found %d times in the bundle" % (name, len(ders)))
        der = ders[0]
        fp = hashlib.sha256(der).hexdigest().upper()
        out.write("    /* %s\n     * SHA-256 %s */\n" % (name, fp))
        out.write('    {"%s",\n     (const uint8_t *) "' % name)
        lit = c_string(der)
        # split the literal into ~100-char pieces without cutting an escape
        pieces, cur = [], ""
        i = 0
        while i < len(lit):
            step = 4 if lit[i] == "\\" else 1
            cur += lit[i:i + step]
            i += step
            if len(cur) >= 96:
                pieces.append(cur)
                cur = ""
        if cur:
            pieces.append(cur)
        out.write('"\n     "'.join(pieces))
        out.write('",\n     %d},\n' % len(der))
        n += 1
    out.write("};\n\n#define TLS_BUILTIN_ROOT_COUNT %du\n\n#endif\n" % n)


main()
