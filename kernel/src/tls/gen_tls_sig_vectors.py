"""Generate test_tls_sig_vectors.h from Wycheproof JSON (Apache-2.0,
https://github.com/C2SP/wycheproof, testvectors_v1/).

Usage: gen_tls_sig_vectors.py WYCHEPROOF_TESTVECTORS_DIR > test_tls_sig_vectors.h
"""
import json
import os
import sys

# (file, kind, param, max tests or None for all)
SETS = [
    ("ecdsa_secp256r1_sha256_test.json", "ECDSA", "P256:SHA256", None),
    ("ecdsa_secp384r1_sha384_test.json", "ECDSA", "P384:SHA384", None),
    ("ecdsa_secp256r1_sha512_test.json", "ECDSA", "P256:SHA512", 80),
    ("rsa_pss_2048_sha256_mgf1_32_test.json", "PSS", "SHA256", None),
    ("rsa_pss_4096_sha512_mgf1_64_test.json", "PSS", "SHA512", 40),
    ("rsa_signature_2048_sha256_test.json", "PKCS1", "SHA256", None),
    ("rsa_signature_3072_sha384_test.json", "PKCS1", "SHA384", 40),
]
RESULT = {"invalid": 0, "valid": 1, "acceptable": 2}


def main():
    d = sys.argv[1]
    keys, vecs = [], []
    for fname, kind, param, cap in SETS:
        j = json.load(open(os.path.join(d, fname)))
        n = 0
        for g in j["testGroups"]:
            pk = g["publicKey"]
            if kind == "ECDSA":
                keys.append((pk["uncompressed"], ""))
            else:
                keys.append((pk["modulus"], pk["publicExponent"]))
            ki = len(keys) - 1
            for t in g["tests"]:
                if cap is not None and n >= cap:
                    break
                vecs.append((kind, param, RESULT[t["result"]], t["tcId"], ki, t["msg"], t["sig"]))
                n += 1
    out = sys.stdout
    out.write("/* Generated by gen_tls_sig_vectors.py from Wycheproof (Apache-2.0). Do not edit.\n"
              " * Copyright (c) 2024-2026 Michael Laurence Curzi and 36N9 Genetics, LLC\n"
              " * SPDX-License-Identifier: Apache-2.0 */\n")
    out.write("typedef struct { const char *a, *b; } wp_key_t;\n")
    out.write("typedef struct { int kind, curve, hash, result, tcid, key; const char *msg, *sig; } wp_vec_t;\n")
    out.write("enum { WP_ECDSA = 1, WP_PSS = 2, WP_PKCS1 = 3 };\n")
    out.write("static const wp_key_t wp_keys[] = {\n")
    for a, b in keys:
        out.write('    {"%s", "%s"},\n' % (a, b))
    out.write("};\nstatic const wp_vec_t wp_vecs[] = {\n")
    for kind, param, res, tc, ki, msg, sig in vecs:
        curve = "ECDSA_CURVE_NONE"
        if kind == "ECDSA":
            c, h = param.split(":")
            curve = "ECDSA_" + c
        else:
            h = param
        out.write('    {WP_%s, %s, TLS_HASH_%s, %d, %d, %d, "%s", "%s"},\n'
                  % (kind, curve, h, res, tc, ki, msg, sig))
    out.write("};\n")


main()
