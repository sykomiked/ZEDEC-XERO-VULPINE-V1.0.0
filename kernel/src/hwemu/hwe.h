/* hwe.h — the standard engines: public contracts with a SOFT
 * implementation for each, so every engine call works on any machine.
 *
 * An ENGINE CONTRACT is a matrix function (hwm.h) with a fixed id, a
 * version and a golden-vector set. The behaviour is defined by open C code
 * in this tree, and the vectors were produced from that code (and, where
 * an independent implementation exists, checked against it: hashlib for
 * the hashes and HMAC, math.gcd for gcd). Any implementation, silicon,
 * fabric, microcode or a peer, serves a contract only after reproducing
 * its vectors bit for bit (M2). hwe_install adds the contracts to a matrix
 * with their SOFT providers, so a machine with no engines at all still
 * answers every call; hardware that has them adds HARD/FABRIC/MICRO
 * providers beside the SOFT ones and wins on cost (M3).
 *
 * CONTRACTS (version 1). Integers are little-endian.
 *   HWE_FN_SHA256   op 0: SHA-256(in) -> 32 bytes.
 *   HWE_FN_KECCAK   op 0: SHA3-256(in) -> 32; op 1: SHA3-512(in) -> 64;
 *                   op 2 / op 3: SHAKE128 / SHAKE256, in = u16 out_len ||
 *                   data, out_len 1..512.
 *   HWE_FN_MAC      op 0: HMAC-SHA256, in = u16 key_len || key || message
 *                   -> 32. KEY-BEARING: never served remotely, no memo.
 *   HWE_FN_GCD      op 0: in = n x (u64 a || u64 b), n 1..32 -> n x u64
 *                   gcd(a, b), with gcd(0, 0) = 0.
 *   HWE_FN_LOGIC64  64 lanes of four-valued logic (lpres.h). A lane is 2
 *                   bits holding an lpres_state_t; lane i is bits 2(i%4)
 *                   of byte i/4. op 0: a AND b (lpres_conjoin), op 1: a OR
 *                   b (lpres_disjoin), in = a[16] || b[16]; op 2: NOT a
 *                   (lpres_negate), in = a[16]. -> 16 bytes.
 *   HWE_FN_TENSOR   op 0: zt_dot_raw (tensor/zt_kern.h), one GGUF Q8_0 row
 *                   against 16-bit activation blocks: in = u32 nb (1..8) ||
 *                   row (34 nb bytes) || a (32 nb x i16) || ash (nb bytes)
 *                   -> i32 (Q16). Present unless HWE_NO_TENSOR.
 *
 * Freestanding C11: no libc, no allocation, no float.
 */
#ifndef HWE_H
#define HWE_H

#include <stdint.h>
#include "hwm.h"

#include "hwe_ids.h"

/* One golden vector (hwe_vectors.h, generated by gen_hwe_vectors.c). */
typedef struct {
    uint32_t fn, op;
    const uint8_t *in;
    uint32_t in_len;
    const uint8_t *out;
    uint32_t out_len;
} hwe_vec_t;

/* Mask bits for hwe_install, in the order above. */
#define HWE_SHA256  0x01u
#define HWE_KECCAK  0x02u
#define HWE_MAC     0x04u
#define HWE_GCD     0x08u
#define HWE_LOGIC64 0x10u
#define HWE_TENSOR  0x20u
#define HWE_ALL     0x3Fu
#define HWE_COUNT   6u

/* Add each contract in `mask` that is not yet in the matrix (function,
 * version, golden vectors, policy) and a SOFT provider for it on resource
 * res_index, then prove the provider. The engines this build lacks are
 * skipped. *out_installed (optional) gets the mask actually installed.
 * Cost of a SOFT provider: HWE_SOFT_COST. */
#define HWE_SOFT_COST 1000u
int hwe_install(hwm_t *m, uint32_t res_index, uint32_t mask, uint32_t *out_installed);

/* The mask of engines compiled into this build. */
uint32_t hwe_available(void);
/* Contract id for one mask bit (0 if none). */
uint32_t hwe_fn_id(uint32_t bit);
/* The SOFT implementation itself (an hwm_call_fn; inst = (void *) fn id). */
int hwe_soft_call(void *inst, hwm_t *m, uint32_t op, const uint8_t *in, uint32_t in_len,
                  uint8_t *out, uint32_t out_cap, uint32_t *out_len);
/* Short contract name ("hash.sha256", ...), or "unknown". */
const char *hwe_name(uint32_t fn_id);

#endif /* HWE_H */
