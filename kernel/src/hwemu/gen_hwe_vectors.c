/* gen_hwe_vectors.c — writes hwe_vectors.h, the golden vectors of the
 * standard engines (hwe.h), by running the open C reference on fixed
 * inputs. tools/check_hwe_vectors.py checks the hash, HMAC and gcd vectors
 * against independent implementations. Run: make -C kernel hwe-vectors. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "hwe.h"

static unsigned nvec;

static void emit(uint32_t fn, uint32_t op, const uint8_t *in, uint32_t n)
{
    uint8_t out[512];
    uint32_t len = 0;
    if (hwe_soft_call((void *) (uintptr_t) fn, 0, op, in, n, out, sizeof out, &len) != 0) {
        fprintf(stderr, "reference failed: fn %08x op %u\n", fn, op);
        exit(1);
    }
    printf("static const uint8_t hwe_in%u[] = {", nvec);
    for (uint32_t i = 0; i < n; i++) printf("%s0x%02x", i ? "," : "", in[i]);
    if (n == 0) printf("0");
    printf("};\nstatic const uint8_t hwe_out%u[] = {", nvec);
    for (uint32_t i = 0; i < len; i++) printf("%s0x%02x", i ? "," : "", out[i]);
    printf("};\n#define HWE_V%u {0x%08xu, %uu, hwe_in%u, %uu, hwe_out%u, %uu}\n", nvec, fn, op,
           nvec, n, nvec, len);
    nvec++;
}

static void put16(uint8_t *b, uint32_t v)
{
    b[0] = (uint8_t) v;
    b[1] = (uint8_t) (v >> 8);
}
static void put64(uint8_t *b, uint64_t v)
{
    for (int i = 0; i < 8; i++) b[i] = (uint8_t) (v >> (8 * i));
}

int main(void)
{
    uint8_t b[1024];
    printf("/* Generated by gen_hwe_vectors.c from the open C reference; do not edit.\n"
           " * SPDX-License-Identifier: Apache-2.0 */\n#ifndef HWE_VECTORS_H\n#define "
           "HWE_VECTORS_H\n");
    /* sha256 */
    emit(HWE_FN_SHA256, 0, (const uint8_t *) "", 0);
    emit(HWE_FN_SHA256, 0, (const uint8_t *) "abc", 3);
    for (int i = 0; i < 200; i++) b[i] = (uint8_t) (i * 7 + 3);
    emit(HWE_FN_SHA256, 0, b, 200);
    /* keccak */
    emit(HWE_FN_KECCAK, 0, (const uint8_t *) "abc", 3);
    emit(HWE_FN_KECCAK, 1, (const uint8_t *) "abc", 3);
    put16(b, 32);
    emit(HWE_FN_KECCAK, 2, b, 2);
    put16(b, 64);
    memcpy(b + 2, "abc", 3);
    emit(HWE_FN_KECCAK, 3, b, 5);
    /* mac: RFC 4231 cases 2 and 6 */
    put16(b, 4);
    memcpy(b + 2, "Jefe", 4);
    memcpy(b + 6, "what do ya want for nothing?", 28);
    emit(HWE_FN_MAC, 0, b, 34);
    put16(b, 131);
    memset(b + 2, 0xaa, 131);
    memcpy(b + 133, "Test Using Larger Than Block-Size Key - Hash Key First", 54);
    emit(HWE_FN_MAC, 0, b, 187);
    /* gcd */
    {
        static const uint64_t pairs[][2] = {{0, 0},
                                            {0, 5},
                                            {12, 18},
                                            {0xFFFFFFFFFFFFFFFFull, 0xFFFFFFFFull},
                                            {12200160415121876738ull, 7540113804746346429ull},
                                            {3ull << 40, 9ull << 20},
                                            {1, 0xFFFFFFFFFFFFFFC5ull},
                                            {600851475143ull, 6857ull * 71ull}};
        uint32_t k = sizeof pairs / sizeof pairs[0];
        for (uint32_t i = 0; i < k; i++) {
            put64(b + 16 * i, pairs[i][0]);
            put64(b + 16 * i + 8, pairs[i][1]);
        }
        emit(HWE_FN_GCD, 0, b, 16 * k);
    }
    /* logic64: every (a, b) pair four times */
    memset(b, 0, 32);
    for (int i = 0; i < 64; i++) {
        b[i / 4] |= (uint8_t) ((i % 4) << (2 * (i % 4)));
        b[16 + i / 4] |= (uint8_t) (((i / 4) % 4) << (2 * (i % 4)));
    }
    emit(HWE_FN_LOGIC64, 0, b, 32);
    emit(HWE_FN_LOGIC64, 1, b, 32);
    emit(HWE_FN_LOGIC64, 2, b, 16);
#ifndef HWE_NO_TENSOR
    /* tensor: nb = 2 and nb = 1 (negative scale, larger shift) */
    {
        static const uint16_t scales[3] = {0x3C00, 0x2E66, 0xBC00};
        for (int pass = 0; pass < 2; pass++) {
            uint32_t nb = pass == 0 ? 2 : 1, o = 0;
            b[o++] = (uint8_t) nb;
            b[o++] = 0;
            b[o++] = 0;
            b[o++] = 0;
            for (uint32_t k = 0; k < nb; k++) {
                put16(b + o, scales[pass == 0 ? k : 2]);
                o += 2;
                for (int i = 0; i < 32; i++)
                    b[o++] = (uint8_t) (int8_t) ((i * 37 + (int) k * 11) % 255 - 127);
            }
            for (uint32_t i = 0; i < 32 * nb; i++) {
                int16_t a = (int16_t) ((int32_t) (i * 2654435761u >> 16) - 32768);
                put16(b + o, (uint16_t) a);
                o += 2;
            }
            for (uint32_t k = 0; k < nb; k++) b[o++] = (uint8_t) (pass == 0 ? k * 3 : 9);
            emit(HWE_FN_TENSOR, 0, b, o);
        }
    }
#endif
    printf("static const hwe_vec_t HWE_VECS[] = {");
    for (unsigned i = 0; i < nvec; i++) printf("%sHWE_V%u", i ? ", " : "", i);
    printf("};\n#define HWE_VEC_COUNT %uu\n#endif\n", nvec);
    return 0;
}
