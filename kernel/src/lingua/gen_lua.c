/* gen_lua.c — random program generator for the differential test of the
 * Lua front-end against the reference interpreter (ref_lua.sh runs lua on
 * the same programs as zxlang and requires identical output).
 *
 * The generator executes what it writes with Lua's rules (floored // and
 * %, and/or/not on booleans) and keeps every value inside 63 bits, every
 * divisor non-zero and every for-step non-zero, so each program is well
 * defined in both implementations and the references never meet an error
 * or an overflow.
 *
 * Usage: gen_lua <seed>   (writes the program to stdout) */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static uint64_t rng;
static unsigned rnd(unsigned n)
{
    rng ^= rng << 13;
    rng ^= rng >> 7;
    rng ^= rng << 17;
    return n ? (unsigned) (rng % n) : 0;
}

static long long v[6];
static const char *const vn[6] = {"a", "b", "c", "d", "e", "f"};

static long long fdiv(long long x, long long y)
{
    long long q = x / y;
    if ((x % y) && ((x % y < 0) != (y < 0))) q--;
    return q;
}

static long long fmod_(long long x, long long y)
{
    return x - fdiv(x, y) * y;
}

/* An expression of the given depth: text into out, its value returned. */
static long long expr(char *out, int depth)
{
    unsigned k = depth <= 0 ? rnd(3) : rnd(10);
    if (k == 0) {
        long long x = (long long) rnd(120) - 60;
        sprintf(out, "%lld", x);
        return x;
    }
    if (k == 1) {
        int i = (int) rnd(6);
        sprintf(out, "%s", vn[i]);
        return v[i];
    }
    char a[512], b[512];
    long long x = expr(a, depth - 1), y = expr(b, depth - 1), r;
    unsigned op = rnd(8);
    if ((op == 3 || op == 4) && y == 0) op = 0; /* never divide by zero */
    switch (op) {
    case 0:
        r = x + y;
        break;
    case 1:
        r = x - y;
        break;
    case 2:
        r = x * y;
        break;
    case 3:
        r = fdiv(x, y);
        break;
    case 4:
        r = fmod_(x, y);
        break;
    case 5:
        r = x & y;
        break;
    case 6:
        r = x | y;
        break;
    default:
        r = x ^ y;
        break;
    }
    if (r < INT64_MIN + 1 || r > INT64_MAX - 1) { /* stay clear of the edges */
        strcpy(out, a);
        return x;
    }
    static const char *const ops[] = {" + ", " - ", " * ", " // ", " % ", " & ", " | ", " ~ "};
    sprintf(out, "(%s%s%s)", a, ops[op], b);
    return r;
}

static int rel_expr(char *out, int depth, int *val)
{
    char a[512], b[512];
    long long x = expr(a, depth), y = expr(b, depth);
    static const char *const rel[] = {" == ", " ~= ", " < ", " <= ", " > ", " >= "};
    int i = (int) rnd(6);
    *val = i == 0   ? x == y
           : i == 1 ? x != y
           : i == 2 ? x < y
           : i == 3 ? x <= y
           : i == 4 ? x > y
                    : x >= y;
    sprintf(out, "%s%s%s", a, rel[i], b);
    return 0;
}

int main(int argc, char **argv)
{
    if (argc < 2) {
        fprintf(stderr, "usage: gen_lua seed\n");
        return 2;
    }
    rng = strtoull(argv[1], 0, 10) * 0x9E3779B97F4A7C15ull + 7;
    printf("-- generated by gen_lua\n");
    for (int i = 0; i < 6; i++) v[i] = (long long) rnd(80) - 40;
    printf("a, b, c, d, e, f = %lld, %lld, %lld, %lld, %lld, %lld\n", v[0], v[1], v[2], v[3], v[4],
           v[5]);
    int nstmt = 12 + (int) rnd(24);
    for (int s = 0; s < nstmt; s++) {
        unsigned kind = rnd(4);
        int i = (int) rnd(6);
        int depth = 1 + (int) rnd(3);
        char e1[512], e2[512], e3[512];
        if (kind == 0) { /* an assignment */
            long long x = expr(e1, depth);
            v[i] = x;
            printf("%s = %s\n", vn[i], e1);
        } else if (kind == 1) { /* a print of two expressions */
            long long x = expr(e1, depth), y = expr(e2, depth);
            (void) x;
            (void) y;
            printf("print(%s, %s)\n", e1, e2);
        } else if (kind == 2) { /* a conditional assignment */
            int t;
            rel_expr(e1, depth, &t);
            long long x = expr(e3, depth);
            if (t) v[i] = x;
            printf("if %s then\n  %s = %s\nend\n", e1, vn[i], e3);
        } else { /* a bounded loop that accumulates */
            long long lo = (long long) rnd(10) - 5, hi = lo + (long long) rnd(9) + 1;
            printf("for n = %lld, %lld do\n  %s = %s + n\nend\n", lo, hi, vn[i], vn[i]);
            for (long long n = lo; n <= hi; n++) v[i] = v[i] + n;
        }
    }
    printf("print(a, b, c, d, e, f)\n");
    return 0;
}