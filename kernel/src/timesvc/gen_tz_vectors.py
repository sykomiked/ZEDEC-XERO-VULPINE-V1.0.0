#!/usr/bin/env python3
# gen_tz_vectors.py: write test_tz_vectors.h for test_tz.c from Python's
# zoneinfo (which reads the same tzdata TZif files).
#
#   python3 gen_tz_vectors.py /usr/share/zoneinfo > test_tz_vectors.h
#
# Two sets:
#  - every zone in the built-in table, 2027-2046: the state at the start and
#    every transition (found by scanning and bisecting), checked against the
#    zone's POSIX string;
#  - a handful of TZif files embedded whole, 1901-2100, checked against the
#    TZif parser.
#
