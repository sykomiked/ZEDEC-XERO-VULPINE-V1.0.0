# SPDX-License-Identifier: Apache-2.0
import datetime as dt
import os
import sys
import zoneinfo

FIXTURES = ["America/New_York", "Europe/Dublin", "Europe/London", "Australia/Lord_Howe",
            "Africa/Casablanca", "Asia/Kolkata", "America/Sao_Paulo", "Pacific/Chatham",
            "America/St_Johns", "America/Nuuk", "Antarctica/Troll", "Pacific/Kiritimati"]
STEP = 3 * 86400


def ts(y):
    return int(dt.datetime(y, 1, 1, tzinfo=dt.timezone.utc).timestamp())


def state(tz, t):
    d = dt.datetime.fromtimestamp(t, tz)
    return (int(d.utcoffset().total_seconds()), int(bool(d.dst())), d.tzname())


def transitions(tz, lo, hi):
    out = []
    t, s = lo, state(tz, lo)
    while t < hi:
        n = min(t + STEP, hi)
        sn = state(tz, n)
        if sn != s:
            a, b = t, n  # state(a) == s, state(b) != s
            while b - a > 1:
                m = (a + b) // 2
                if state(tz, m) == s:
                    a = m
                else:
                    b = m
            out.append((b, state(tz, b)))
            t, s = b, state(tz, b)
        else:
            t = n
    return out


def octal(data):
    s, line = [], ""
    for byte in data:
        line += "\\%03o" % byte
        if len(line) >= 88:
            s.append(f'"{line}"')
            line = ""
    if line:
        s.append(f'"{line}"')
    return "\n    ".join(s)


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
    abbrs = []

    def ab(x):
        if x not in abbrs:
            abbrs.append(x)
        return abbrs.index(x)

    zones, rows = [], []

    def add(name, lo, hi):
        tz = zoneinfo.ZoneInfo(name)
        s0 = state(tz, lo)
        tr = transitions(tz, lo, hi)
        zones.append((name, lo, s0[0], s0[1], ab(s0[2]), len(rows), len(tr)))
        for t, s in tr:
            rows.append((t, s[0], s[1], ab(s[2])))

    names = sorted(n for n in zoneinfo.available_timezones() if n != "Factory")
    for n in names:
        add(n, ts(2027), ts(2046))
    n_builtin = len(zones)
    for n in FIXTURES:
        add(n, ts(1901), ts(2100))

    o = sys.stdout
    o.write("/* test_tz_vectors.h: zone states from Python zoneinfo; generated by\n")
    o.write(" * gen_tz_vectors.py, do not edit. The embedded TZif files are tzdata,\n")
    o.write(" * which is in the public domain.\n")
    o.write(" * SPDX-License-Identifier: Apache-2.0 AND LicenseRef-Public-Domain\n */\n")
    o.write(f"#define TV_N_BUILTIN {n_builtin}u\n#define TV_N_ZONES {len(zones)}u\n")
    o.write(f"#define TV_N_FIXTURES {len(FIXTURES)}u\n\n")
    o.write("static const char *const tv_abbr[] = {\n")
    for a in abbrs:
        o.write(f'    "{a}",\n')
    o.write("};\n\n")
    o.write("static const struct {\n    const char *name;\n    int64_t from;\n    int32_t off;\n"
            "    uint8_t dst, abbr;\n    uint32_t first, count;\n} tv_zone[TV_N_ZONES] = {\n")
    for z in zones:
        o.write('    {"%s", %d, %d, %d, %d, %d, %d},\n' % z)
    o.write("};\n\n")
    o.write("static const struct {\n    int64_t t;\n    int32_t off;\n    uint8_t dst, abbr;\n"
            "} tv_tr[] = {\n")
    for r in rows:
        o.write("    {%d, %d, %d, %d},\n" % r)
    o.write("};\n\n")
    o.write("static const struct {\n    const char *data;\n    uint32_t len;\n} tv_tzif[TV_N_FIXTURES] = {\n")
    for n in FIXTURES:
        data = open(os.path.join(root, n), "rb").read()
        o.write(f"    {{{octal(data)},\n     {len(data)}u}},\n")
    o.write("};\n")


if __name__ == "__main__":
    main()
