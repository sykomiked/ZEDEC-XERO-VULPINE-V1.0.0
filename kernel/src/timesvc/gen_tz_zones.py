#!/usr/bin/env python3
# gen_tz_zones.py: write tz_zones.h, the IANA zone name -> POSIX TZ string
# table, from the footers of the TZif files in a zoneinfo directory.
#
#   python3 gen_tz_zones.py /usr/share/zoneinfo > tz_zones.h
#
# tzdata is in the public domain. The table holds each zone's current rules
# only; see tz.h.
#
