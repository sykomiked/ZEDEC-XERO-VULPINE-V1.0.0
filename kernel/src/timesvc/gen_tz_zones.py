# SPDX-License-Identifier: Apache-2.0
import os
import sys
import zoneinfo


def footer(path):
    data = open(path, "rb").read()
    if not data.startswith(b"TZif") or data[4:5] < b"2":
        raise SystemExit(f"{path}: not a TZif v2+ file")
    end = data.rstrip(b"\n")
    tz = data[end.rfind(b"\n") + 1:len(end)]
    return tz.decode("ascii")


def main():
    root = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo"
    version = "unknown"
    zi = os.path.join(root, "tzdata.zi")
    if os.path.exists(zi):
        version = open(zi).readline().split()[-1]
    names = sorted(n for n in zoneinfo.available_timezones() if n != "Factory")
    rows = []
    for n in names:
        rows.append((n, footer(os.path.join(root, n))))
    out = sys.stdout
    out.write("/* tz_zones.h: IANA zone name -> POSIX TZ string (current rules).\n")
    out.write(" * Generated by gen_tz_zones.py from the tzdata TZif footers; do not\n")
    out.write(" * edit. tzdata is in the public domain.\n")
    out.write(" * SPDX-License-Identifier: Apache-2.0 AND LicenseRef-Public-Domain\n */\n")
    out.write("#ifndef ZXV_TZ_ZONES_H\n#define ZXV_TZ_ZONES_H\n\n")
    out.write(f'#define TZ_ZONES_VERSION "{version}"\n')
    out.write(f"#define TZ_ZONE_COUNT {len(rows)}u\n\n")
    out.write("static const struct {\n    const char *name, *tz;\n} tz_zones[TZ_ZONE_COUNT] = {\n")
    for n, tz in rows:
        out.write(f'    {{"{n}", "{tz}"}},\n')
    out.write("};\n\n#endif /* ZXV_TZ_ZONES_H */\n")


if __name__ == "__main__":
    main()
