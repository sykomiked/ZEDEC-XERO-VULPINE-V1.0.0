OURS = {
    'chiglet': 'ʧˈɪɡlət',
    'chiglets': 'ʧˈɪɡləts',
    "chiglet's": 'ʧˈɪɡləts',
    'zxv': 'zˌiˌɛksvˈi',
    'zedec': 'zˈɛdɛk',
    'github': 'ɡˈɪthʌb',
    'gitlab': 'ɡˈɪtlæb',
    'kokoro': 'kəkˈɔɹO',
    'vulpine': 'vˈʌlpIn',
    'vino': 'vˈinO',
    'tiamat': 'tˈiəmɑt',
    'ascw': 'ˌAˌɛssˌidˈʌbᵊlju',
    'wifi': 'wˈIfI',
}


def main():
    gold = json.load(open(sys.argv[1], encoding='utf-8'))
    out = {}
    for w in COMMON + NUMBERS:
        v = gold.get(w)
        if isinstance(v, dict):
            v = v['DEFAULT']
        if v is None:  # an inflection: speech_g2p_en stems it (G4)
            print('not in gold, left to stemming:', w)
            continue
        out[w] = v
    for c in 'abcdefghijklmnopqrstuvwxyz':  # letter names, as "#a" .. "#z"
        out['#' + c] = gold[c.upper()]
    out.update(OURS)
    keys = sorted(out, key=lambda k: k.encode('utf-8'))
    with open(sys.argv[2], 'w', encoding='utf-8') as f:
        f.write('/* Generated by tools/kokoro/gen_g2p_words.py from misaki us_gold.json\n'
                ' * (hexgrad/misaki, Apache-2.0) and our own words. Do not edit. */\n')
        for k in keys:
            f.write('    {"%s", "%s"},\n' % (k.replace('"', '\\"'), out[k]))
    print(len(keys), 'words')


if __name__ == '__main__':
    main()
